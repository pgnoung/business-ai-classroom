const withoutUrls = (text) => String(text ?? "").replace(/https?:\/\/\S+/giu, " ");

export function customerIsClosing(text) {
  const value = withoutUrls(text).trim();
  // คำสั่งพี่ง้วง 28 ก.ย.: "ขอเช็คคิว/วันก่อน" = ปิดบทสนทนาเช่นกัน — แม้จะถามรอบมาด้วย ("ขอเช็คคิวก่อน มีรอบไหนบ้าง")
  // เขาก็ได้รายการรอบในคำตอบนั้นแล้ว (scheduleCheck.mjs) การปิดท้ายว่า "สะดวกรอบไหนคะ" คือการจี้
  if (value && classifyScheduleCheck(value)) return true;
  return Boolean(value) && CLOSING_FORM.test(value) && !QUESTION_FORM.test(value);
}

