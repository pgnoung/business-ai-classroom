export const REPLY_CLOSING_QUESTION_KEY = "reply_closing_question";
export const REPLY_CLOSING_QUESTION_MODES = Object.freeze(["on", "off"]);

/** ไม่มีค่า = on (คำสั่งเจ้าของ) · off = ถ้อยคำก่อนหน้านี้ทุกไบต์ · อ่านพัง = off */
export function replyClosingQuestionMode(db) {
  try {
    const raw = String(db?.getSetting?.(REPLY_CLOSING_QUESTION_KEY) ?? "").trim().toLowerCase();
    return raw === "off" ? "off" : "on";
  } catch {
    return "off";
  }
}

export function replyClosingQuestionEnabled(db) {
  return replyClosingQuestionMode(db) === "on";
}

