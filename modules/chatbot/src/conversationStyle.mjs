// 2026-09-28: "ได้เลยค่ะ/ได้เลยครับ" คือคำตอบรับข้อเสนอที่พบบ่อยที่สุด แต่เดิมรับแค่ "ได้เลย" เปล่า ๆ
// ลูกค้าที่ตอบรับอย่างสุภาพจึงไม่ถูกนับว่าตอบรับข้อเสนอ (ข้อสังเกตจากทีมตรวจ audit ก.ย.)
// 2026-10-10: "คับ" (สะกดแบบพิมพ์เร็วของ ครับ) เคยไม่นับเป็นคำรับ — ลูกค้าจริงตอบข้อเสนอส่งรายละเอียดการสมัครด้วย "คับ"
const SHORT_ACK = /^(?:ครับผม|ครับ|คับ|ค่ะ|ค่า|คะ|โอเค|โอเคครับ|โอเคคับ|โอเคค่ะ|ได้ครับ|ได้คับ|ได้ค่ะ|ได้เลย(?:ครับ|คับ|ค่ะ|ค่า|คะ|จ้า|นะคะ|นะครับ)?|อืม|อือ|อ๋อ|รับทราบ|ขอบคุณ|ขอบคุณครับ|ขอบคุณค่ะ)[.!…🙏✨😊\s]*$/iu;

// เราเคยถามคำถามอะไรกับห้องนี้ไปแล้วหรือยัง — สถานะจริงของบทสนทนา ไม่ใช่การเดาจากถ้อยคำ
export function weAskedSomethingBefore(history = []) {
  return recentAskedQuestions(Array.isArray(history) ? history : [], { maxItems: 1 }).length > 0;
}

export function hasQuestionFatigue(text, history = null) {
  const value = String(text || "").trim();
  if (QUESTION_FATIGUE_BLUNT.test(value)) return true;
  if (!QUESTION_FATIGUE_POLITE.test(value)) return false;
  return weAskedSomethingBefore(history);
}

export function isShortAcknowledgement(text) {
  return SHORT_ACK.test(String(text || "").trim());
}

// The webhook stores inbound messages before the pipeline runs. The final
// contiguous user block is the same burst supplied separately as userText;
// remove it so Sol never sees the current message twice.
export function historyBeforeCurrentInbound(turns = []) {
  if (!Array.isArray(turns)) return [];
  let end = turns.length;
  while (end > 0 && turns[end - 1]?.role === "user") end -= 1;
  return turns.slice(0, end);
}

// v1.2.1 (เคสจริงลูกแพร: บอทวนถาม "งานไหนเสียเวลาสุด" ทั้งที่ลูกค้าตอบไปแล้ว —
// กติกาลอย ๆ "ห้ามถามซ้ำ" ไม่พอ ต้องลิสต์คำถามจริงที่ถามไปแล้วให้โมเดลเห็นตรง ๆ)
const ASKED_QUESTION_SENTENCE = /(?:ไหม|มั้ย|หรือเปล่า|รึเปล่า|หรือยัง|อะไร|ไหน|เมื่อไหร่|ยังไง|อย่างไร|เท่าไหร่|เท่าไร|กี่|ใช่ไหม|\?)/u;
const MAX_ASKED_QUESTIONS = 3;
const MAX_ASKED_QUESTION_LENGTH = 90;

export function recentAskedQuestions(turns = [], { maxItems = MAX_ASKED_QUESTIONS } = {}) {
  if (!Array.isArray(turns)) return [];
  const questions = [];
  for (let index = turns.length - 1; index >= 0 && questions.length < maxItems; index -= 1) {
    const turn = turns[index];
    if (turn?.role !== "assistant") continue;
    const sentences = String(turn.content || "")
      .split(/(?<=(?:ค่ะ|นะคะ|ค่า|คะ|ครับ|\?)[\s!]*)\s+|\n+/u)
      .map((part) => part.trim())
      .filter(Boolean);
    for (const sentence of sentences.reverse()) {
      if (!ASKED_QUESTION_SENTENCE.test(sentence)) continue;
      const trimmed = [...sentence].slice(0, MAX_ASKED_QUESTION_LENGTH).join("");
      if (questions.includes(trimmed)) continue;
      questions.push(trimmed);
      if (questions.length >= maxItems) break;
    }
  }
  return questions;
}


