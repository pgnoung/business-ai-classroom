// `brandText` rewrites the legacy course-brand vocabulary in static prompt
// templates. Customer names and prior questions are interpolated into those
// templates, so protect each interpolation site before branding and restore it
// byte-for-byte afterwards. Do not search-and-replace the finished rule: a
// customer named "ลูกแพร" must not protect static references to the old agent.
function restoreBrandLiterals(text, protectedLiterals) {
  text = brandText(text);
  for (const { literal, marker } of protectedLiterals) text = text.split(marker).join(literal);
  restoreCapturedPriceDirectiveLiterals(protectedLiterals);
  return text;
}

