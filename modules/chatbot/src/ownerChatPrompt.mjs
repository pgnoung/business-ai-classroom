export function looksLikePromptLeak(reply) {
  const value = String(reply || "");
  // ป้ายโหมด "[ชื่อ · โหมดคุยกับ…]" — ส่วนหลังจุดกลางคือคำที่ไม่ควรโผล่ในคำตอบ (ลูกแพร = "โหมดคุยกับพี่ง้วง" เหมือนเดิม)
  const markCore = ownerPersonaMark().replace(/^\[|\]$/gu, "").split("·").pop().trim();
  if (markCore && value.includes(markCore)) return true;
  return leakLines().some((line) => value.includes(line));
}
