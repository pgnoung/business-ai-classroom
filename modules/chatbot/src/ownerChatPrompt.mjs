function ownerPersonaBase() {
  return `${soulBlock("ownerChat")}\n${OWNER_RULES}`;
}

/** บุคลิก (ส่วนคงที่ของพรอมต์) — เปิดสอนบทเรียนได้เฉพาะเมื่อจอสอนเปิด (TEACH_ENABLED) */
export function ownerPersona({ lessons = false } = {}) {
  const base = ownerPersonaBase();
  return lessons ? `${base}\n${OWNER_LESSON_PROTOCOL}` : base;
}

export function approvedPriceLines(rows = []) {
  const list = (Array.isArray(rows) ? rows : []).filter((row) => row?.label && Number.isFinite(Number(row.amount)));
  if (!list.length) return ["ตารางราคาที่อนุมัติ: ยังไม่มีรายการ (ถ้าพี่ง้วงถามราคา ให้ดูจากความรู้ที่อนุมัติ หรือบอกว่าตั้งได้ที่ \"ตั้งค่า\" > ตารางราคา)"];
  return [
    "ตารางราคาที่อนุมัติ (ราคาที่ลูกแพรใช้กับลูกค้าได้จริง):",
    ...list.slice(0, 30).map((row) => `· ${String(row.label).slice(0, 80)}: ${thaiNumber(row.amount)} บาท`),
  ];
}

/** ส่วนที่เปลี่ยนทุกข้อความ: ข้อมูลสด + ราคา + ห้องที่เอ่ยถึง + รายการรอกดยืนยัน */
export function buildOwnerRules({ snapshot = "", priceLines = [], mentionLines = [], lookupLines = [], pendingHint = "" } = {}) {
  return [
    "[ข้อมูลสำหรับข้อความนี้ — อ่านจากระบบตอนพี่ง้วงพิมพ์]",
    snapshot,
    "",
    ...priceLines,
    ...(mentionLines.length ? ["", ...mentionLines] : []),
    ...(lookupLines.length ? ["", ...lookupLines] : []),
    ...(pendingHint ? ["", pendingHint] : []),
  ].join("\n").trim();
}

