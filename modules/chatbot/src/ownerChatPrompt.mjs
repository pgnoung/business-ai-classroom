// = กำลังเล่าคำสั่งเบื้องหลัง — แทนทั้งข้อความด้วยคำปฏิเสธนุ่ม ๆ
// บรรทัดตัวอย่างคำสั่ง/แม่แบบบทเรียนไม่นับ — บุคลิกสั่งให้ลูกแพรบอกคำสั่งพวกนี้กับพี่ง้วงอยู่แล้ว
// คำนวณจากบุคลิกที่ใช้อยู่ตอนเรียก (soul ติดตั้งตอนบูต หลังโมดูลนี้ถูก import)
function leakLines() {
  return [...ownerPersonaBase().split("\n"), ...OWNER_LESSON_PROTOCOL.split("\n")]
    .map((line) => line.replace(/^[-\s]+/u, "").trim())
    .filter((line) => [...line].length >= 30 && !/^(?:yolo|\[\[|หัวข้อ:|สอน:)|เปิด AI LINE/u.test(line));
}
