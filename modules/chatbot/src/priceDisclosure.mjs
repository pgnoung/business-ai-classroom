// ("ขอแจ้งราคาไปยังผู้บริหารก่อน" = ลูกค้าขอตัวไปแจ้งเอง จึงตัด) · "ใบเสนอราคา" ไม่ใช่คำกริยาเสนอ (ไม่ตัด ให้ veto/คำขอใบเสนอราคาทำงานเหมือนเดิม)
const PRICE_TO_DECIDER = new RegExp(
  "(?<!ใบ|ช่วย|ช่วย\\s|รบกวน|รบกวน\\s|ขอให้|กรุณา)(?:แจ้ง|ส่งต่อ|ส่ง|เสนอ|ยื่น|นำ|เอา)\\s?(?:ราคา|ค่าเรียน|ค่าคอร์ส|ค่าอบรม|ค่าใช้จ่าย)"
  + "[^\\n?？]{0,20}?(?:ไป(?:ยัง|ให้|ที่|ทาง)?|ให้)\\s?(?:เสนอ|ปรึกษา|ถาม)?\\s?(?:ทาง|กับ)?\\s?"
  + "(?:ผู้บริหาร|หัวหน้า|บริษัท|จัดซื้อ|บอส|นาย|เจ้านาย|ผู้จัดการ|ผู้อำนวยการ|ผอ\\.?|ผู้อนุมัติ|ฝ่าย|ต้นสังกัด|องค์กร|HR|ผู้ใหญ่|boss|manager)"
  + "(?![^\\n]{0,12}?(?:หน่อย|ได้ไหม|ได้มั้ย|ได้มั๊ย|ได้ป่าว|ได้รึเปล่า|ได้หรือเปล่า))",
  "giu",
);

// รีวิวรอบสุดท้าย 12 ต.ค.: ถ้าข้อความเดียวกันมีคำขอให้เราส่ง/แจ้งราคา ("ส่งราคาให้หน่อยครับ จะเอาไปเสนอหัวหน้า" ·
// "ส่งราคามาให้…" · "…ได้ไหมครับ") ยังเป็นคำขอราคาเสมอ — ตัดช่วงส่งต่อเฉพาะเมื่อไม่มีคำขอเลยทั้งข้อความ
export const PRICE_REQUEST_TO_US = /(?:ให้|มา)\s?หน่อย|หน่อย(?:ครับ|ค่ะ|คะ|คับ|นะ|จ้า)|ได้\s?(?:ไหม|มั้ย|มั๊ย|ป่าว|รึเปล่า|หรือเปล่า)|รบกวน|ช่วย\s?(?:ส่ง|แจ้ง|บอก)|ขอ\s?(?:ราคา|ค่าเรียน|รายละเอียดราคา)|(?:ส่ง|แจ้ง)\S{0,10}?มา(?:ให้|ทาง|$|\s)/u;
function moneyReadable(value) {
  const forwarding = PRICE_REQUEST_TO_US.test(value) ? value : value.replace(PRICE_TO_DECIDER, " ");
  return forwarding
    .replace(NOT_MUCH_IDIOM, (match, lead) => (MONEY_WORD_IN_GAP.test(lead) ? match : `${lead} `));
}

export function asksAboutMoney(text) {
  const raw = String(text ?? "");
  // ลูกค้าขอใบเสนอราคาจากเรา = ถามเรื่องเงิน (ชนะ veto เสมอ) — อ่านจากข้อความเต็ม
  if (QUOTATION_REQUEST_TO_US.test(raw)) return true;
  const value = moneyReadable(raw);
  // ถามค่าเรียนของเราตรง ๆ = คำถามเรื่องเงิน ไม่ว่าประโยคเดียวกันจะมีเรื่องงานของเขาปนหรือไม่
  if (DIRECT_PRICE_ASK.test(value)) return true;
  if (OWN_PRICING_WORK.test(value)) return false;
  return MONEY_ASK.test(value);
}

// "เราเคยพิมพ์ราคาคลาสไปแล้วในห้องนี้หรือยัง"
//
// ของเดิมจับ "เลขหลักพันที่มีลูกน้ำ / เลขติดคำว่าบาท" ตัวไหนก็ได้ ซึ่งแปลว่า
// "สอนมาแล้วกว่า 5,000 คน" · "ที่นั่ง 20 ที่" · "ค่าจอดรถ 40 บาท" ถูกนับเป็น
// "เราแจ้งราคาไปแล้ว" ทั้งหมด แล้วลัดวงจรการคัดกรองทิ้งทั้งชุด (ตรวจปรปักษ์ 2026-09-04)
// ตอนนี้จึงเทียบกับ "ราคาต่อหัวที่อนุมัติแล้ว" เท่านั้น โดยใช้นิยามเดียวกับตัวกันราคา
// (complianceGuard.multipliableAmounts — ตัดแถวส่วนลด/ค่าบริการเสริมออก และตัดเลข < 4,000)
// ไม่มีตารางราคา = อ่านไม่ออกว่าเคยแจ้งหรือยัง จึงคืน false แล้วให้หมุดถาวรทำงานแทน
const NUMERIC_TOKEN = /\d[\d,]*/gu;
// "ไม่รู้ตารางราคาเลย" (null) ต่างจาก "รู้แล้วว่าว่าง" (Set ว่าง) โดยเจตนา:
//   - ไปป์ไลน์ส่ง Set มาเสมอ (อ่านตารางไม่ได้ = Set ว่าง) โปรดักชันจึงได้การจับคู่แบบเป๊ะทุกครั้ง
//   - ผู้เรียกที่ไม่มีตารางอยู่ในมือ = เราไม่รู้ว่าเลขไหนคือราคา ต้องล้มไปทาง quote ตามกติกา
//     หัวไฟล์ ไม่ใช่พาห้องที่เคยได้ราคาไปแล้วกลับไปคัดกรองใหม่ (เคสจริงในคลังเทสต์:
//     บอทตอบ "15,900 บาทค่ะ" ไปแล้ว ลูกค้าถามต่อว่า "มีโปรไหม" — คนนั้นต้องได้คำตอบ)
const MONEY_SHAPED = /(?:\d{1,3},\d{3}|\d[\d,]*\s*บาท|\d[\d,]*\.-)/u;

export function approvedClassAmounts(rows) {
  try {
    return multipliableAmounts(rows);
  } catch {
    return new Set();
  }
}

function textStatesApprovedPrice(value, amounts) {
  for (const match of String(value ?? "").matchAll(NUMERIC_TOKEN)) {
    if (amounts.has(Number(match[0].replaceAll(",", "")))) return true;
  }
  return false;
}

// ร่องรอยของ "เราขอถามคัดกรองไปแล้ว" ในเนื้อคำตอบ — ใช้เป็นเข็มขัดเสริมคอลัมน์ในฐานข้อมูล
// เท่านั้น จึงต้องเป็นวลีที่ยาวและเฉพาะพอที่จะไม่มีวันโผล่ในคำตอบคัดกรองธรรมดา
// (ความพยายามรอบก่อนใช้ marker หลวม ๆ อย่าง "มีหลายคลาส" / "ทำงานสายอะไร" แล้วทำให้
//  การถามครั้งแรกจริง ๆ ถูกอ่านเป็นการถามซ้ำ = เทราคาใส่คนแปลกหน้าทันที)
//
// ย้ำ: วลีนี้อยู่ในพรอมต์ในฐานะ "ตัวอย่าง" (เช่น "...") และร่างถูก humanizer เขียนใหม่
// ก่อนถึงลูกค้า มันจึงหายไปได้ตลอดเวลา — ห้ามให้สถานะสำคัญของห้องแขวนอยู่กับมันเดี่ยว ๆ
export const PRICE_DEFERRAL_FRAMING = "เพื่อให้เลือกคลาสที่เหมาะสมและได้ประโยชน์สูงสุดต่อผู้เรียน";
const PRICE_DEFERRAL_FOOTPRINT = /ได้ประโยชน์สูงสุดต่อผู้เรียน/u;

// งานที่ทีมผู้ดูแลเป็นคนออกใบเสนอราคาเสมอ — เทิร์นแบบนี้บอกได้แค่ "ราคาเริ่มต้น"
// ห้ามยกโปรโมชั่นทั้งชุด. ตัวจับอยู่ที่ salesPolicy.mjs ที่เดียว (ของเดิมมีสำเนาชื่อ
// PROJECT_PRICE_CONTEXT อยู่ตรงนี้ ซึ่งไม่ตรงกับตัวที่ pipeline ใช้ประกาศโหมดคัดกรองก่อนเสนอ)
const PROJECT_MIN_HEADCOUNT = 4;

function turnsOf(history) {
  return Array.isArray(history) ? history : [];
}

/**
 * เราเคยพิมพ์ "ราคาคลาสที่อนุมัติแล้ว" ให้เขาเห็นในประวัติที่มองเห็นอยู่หรือยัง
 * @param {Array} history เทิร์นที่ส่งเข้าพรอมต์
 * @param {Set<number>|null} approvedAmounts ราคาต่อหัวที่อนุมัติ (จาก approvedClassAmounts)
 */
export function priceAlreadyStated(history = [], approvedAmounts = null) {
  const amounts = approvedAmounts instanceof Set ? approvedAmounts : null;
  const statesPrice = amounts
    ? (value) => textStatesApprovedPrice(value, amounts)
    : (value) => MONEY_SHAPED.test(String(value ?? ""));
  return turnsOf(history).some((turn) => turn?.role === "assistant" && statesPrice(turn?.content));
}

// "เราเคยขอถามคัดกรองเรื่องราคาไปแล้วในห้องนี้หรือยัง"
//
// แหล่งความจริงคือคอลัมน์ `customers.price_deferred_at` ไม่ใช่การอ่านข้อความย้อนหลัง
// เหตุผล: history ที่ส่งเข้าพรอมต์คือ db.recentTurns(customerId, config.historyTurns) ซึ่ง
// ตั้งต้นที่ 12 แถว และหนึ่งรอบสนทนากินได้ ~5 แถว — สัญญาณที่อยู่ในตัวหนังสืออย่างเดียว
// จะเลื่อนหลุดหน้าต่างแล้ว "ติดอาวุธการถามคัดกรองใหม่" ให้ลูกค้าคนเดิมโดยอัตโนมัติ
// คอลัมน์เขียนครั้งแรกชนะและไม่มีวันหมดอายุ (นโยบายข้อ 2: ถามซ้ำแล้วห้ามเลี่ยงอีก "ตลอดไป")
// ตัวอ่านจากข้อความเป็นเข็มขัดเสริมกรณีเขียนฐานไม่สำเร็จ และทั้งสองทางดันไปทาง quote เท่านั้น
export function deferralFootprintVisible(history = []) {
  return turnsOf(history).some(
    (turn) => turn?.role === "assistant" && PRICE_DEFERRAL_FOOTPRINT.test(String(turn?.content ?? "")),
  );
}

