// "ถามค่าเรียนของเราตรง ๆ" แบบแคบ: รูปถามจำนวนเงินตรง ๆ หรือรูปขอให้เราส่ง/แจ้ง ที่มีคำเรื่องเงิน — ไม่ใช่คำเรื่องเงินคำไหนก็ได้
function directPriceAsk(text) {
  const raw = String(text ?? "");
  if (QUOTATION_REQUEST_TO_US.test(raw)) return true;
  const value = moneyReadable(raw);
  return DIRECT_PRICE_ASK.test(value) || (PRICE_REQUEST_TO_US.test(value) && !OWN_PRICING_WORK.test(value) && MONEY_ASK.test(value));
}
// เทิร์นนี้ = การถามราคาที่ควรแบ่งรับ: ถามตรง ๆ หรือคำเรื่องเงินที่ไม่ใช่การเล่าราคา/ค่าใช้จ่ายในธุรกิจของเขาเอง ("ราคา" คำเดียวยังนับ)
const hedgeableAsk = (value) => directPriceAsk(value) || (asksAboutMoney(value) && !OWN_BUSINESS_MONEY.test(value));
// รีวิวรอบ 2: ตัวกันถามซ้ำนับเฉพาะหลักฐานว่าเคยคุยเรื่องราคาเราจริง — ลูกค้าถามค่าเรียนเราตรง ๆ หรือคำตอบของเราที่บอกว่าจะแจ้งค่าเรียน/
// เหตุผลของการคัดกรอง (คำเรื่องเงินในเรื่องธุรกิจของเขาไม่นับ: เดิมคนขายของที่เล่างานตัวเองได้ราคาทันทีโดยไม่ถูกแบ่งรับ)
function earlierPriceTalk(turn) {
  const content = String(turn?.content ?? "");
  if (turn?.role === "assistant") return PRICE_DEFERRAL_FOOTPRINT.test(content) || PRICE_PROMISE_FOOTPRINT.test(content);
  return turn?.role === "user" && directPriceAsk(content);
}

const COMPANION_ASK_RE = /(?:มา|ไป|เรียน)\s?(?:กับ|กัน|คู่กับ)\s?(?:เพื่อน|แฟน|สามี|ภรรยา|ภรรยา|พี่|น้อง|ลูก|ทีม|หุ้นส่วน|คู่|สอง|สาม|2|3)|มา(?:เป็น)?คู่|(?:สอง|สาม|2|3)\s?(?:คน|ท่าน)/u;
function valueHedgeFits({ value, turns, projectPricing, inboundFlags }) {
  if (projectPricing) return false;
  if (!hedgeableAsk(value)) return false;
  if (QUOTATION_REQUEST_TO_US.test(value) || HUMAN_GATED_MONEY_TOPIC.test(value) || PROCUREMENT_ASK.test(value) || ORGANISATION_ASK.test(value)) return false;
  if (moneyHardshipIn(value)) return false;
  // รีวิวรอบ 2 (HIGH): ขอส่วนลด / มากันสองสามท่าน = ดีลคู่หรือส่วนลดคนเดียวทันทีตามเดิม (แบ่งรับแล้วเทิร์นถัดไปเคยได้แค่การ์ดคนเดียว ดีลคู่หาย)
  if (inboundFlags.includes("asks_discount") || DISCOUNT_RE.test(value)) return false;
  if (PAIR_HEADCOUNTS.has(resolveClassRouting({ text: value, history: turns }).headcount)) return false;
  // ตรวจซ้ำรอบสุดท้าย 12 ต.ค.: มากับเพื่อน/แฟน/คู่ หรือบอกจำนวนเป็นคำ ("มากันสองคน") = ราคาทันทีเหมือน production
  // (เดิมโดนแบ่งรับแล้วถามซ้ำว่า "มาเรียนเองหรือมากับทีม" ทั้งที่เพิ่งบอก)
  if (COMPANION_ASK_RE.test(value)) return false;
  return !turns.some(earlierPriceTalk);
}

