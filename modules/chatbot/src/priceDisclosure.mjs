  // ทุกตัวประกอบจึงเงียบเรื่องโปรฯ พร้อมกันทั้งพรอมต์
  if (asksToRescheduleAttendance(text)) return false;
  if (projectOpportunity && PROJECT_OPPORTUNITY_TYPES.has(projectOpportunity)) return false;
  // กติกาของพี่ง้วง: งานตั้งแต่ 4 ท่านขึ้นไป ทีมผู้ดูแลออกใบเสนอราคาเสมอ ห้ามยกตารางโปรฯ
  // (resolveClassRouting เก็บ "เลขล่าสุดที่ลูกค้าบอก" ไม่ใช่ "เลขไหนก็ได้ในหน้าต่าง" —
