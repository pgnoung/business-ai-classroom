// Stored interest is context for the reply, never permission to ignore current intent.
export function replyLeadContext(customer = null) {
  const score = customer?.last_score;
  const known = Number.isInteger(score) && score >= 0 && score <= 10;
  const band = !known ? "unknown" : score >= 8 ? "hot" : score >= 5 ? "warm" : "cold";
  return "[คะแนนประกอบการตอบ — ใช้ภายใน ห้ามบอกคะแนนหรือ stage ให้ลูกค้า]\n"
    + (known ? `คะแนนที่บันทึกล่าสุด ${score}/10 (${band})` : "ยังไม่มีคะแนนความสนใจที่ใช้ได้ (unknown); ห้ามเดาว่าลูกค้าไม่สนใจ")
    + "\nคะแนนเป็นข้อมูลก่อนหน้า scorer อาจยังไม่ประเมินข้อความล่าสุด ต้องอ่านเจตนาและบริบทล่าสุดทุกครั้ง "
    + "cold: ช่วยให้เห็นความเหมาะโดยไม่ซักถามเป็นชุด; warm: ให้รายละเอียดและหลักฐานที่ตรงโจทย์; hot: ตอบข้อสงสัยสุดท้ายและช่วยขั้นตอนที่ลูกค้าต้องการ "
    + "คำขอชัดเจนให้ทำตามได้โดยไม่รอคะแนนเพิ่ม คะแนนสูงไม่อนุญาตให้เร่งขายหลังขอพักหรือส่งข้อมูลซ้ำ "
    + "คะแนนไม่เปลี่ยนกติกาข้อมูลอนุมัติ ราคา การชำระเงิน และการส่งต่อคน คะแนนความสนใจไม่ใช่คะแนนคุณภาพลูกค้าหรือคุณภาพคำตอบ";
}
