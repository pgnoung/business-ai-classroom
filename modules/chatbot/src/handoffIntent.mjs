// ก่อน ไม่ใช่การจอง และคำตอบนั้นจะไม่มีวันมาถ้าห้องถูกปิดในวินาทีถัดไป
//
// จงใจ **ไม่** ใส่ "รอบหน้า/ครั้งหน้า" — "งั้นขอจองรอบหน้าค่ะ" คือการจองรอบถัดไปจริง ๆ
// ส่วน "ไว้จองรอบหน้าค่ะ" (ผัดวันประกันพรุ่ง) ถูกคัดออกด้วยคำว่า "ไว้" ที่อยู่ก่อนกริยาแล้ว
const CONDITIONAL_AFTER = /ถ้า|หาก|เผื่อ|กรณี|ทีหลัง/u;

// "แต่..." ที่ตามมาทีหลัง = ประโยคกลับข้าง ("อยากสมัครค่ะ แต่ติดวันเสาร์")
// อ่านจาก "หางของทั้งข้อความ" ไม่ใช่แค่ประโยคเดียวกัน เพราะข้อโต้แย้งมักขึ้นประโยคใหม่
// (ข้อ 6: รอบแรกรู้จักแค่ แต่ยัง/แต่ไม่/แต่ขอ แล้วปิดห้องใส่คนที่ติดวันเสาร์)
//
// R4 (2026-09-05 รอบสาม): รอบสองเหวี่ยงกลับสุดทาง — "แต่" ตัวไหนก็ล้มการจับหมด ผลคือ
// "ขอจองค่ะ แต่ขอโอนวันศุกร์นะคะ" (ตัดสินใจแล้ว ต่อรองแค่วันโอน = เรื่องธุรการ) หลุด
// ตอนนี้ "แต่" ล้มการจับได้สองทางเท่านั้น: ตามด้วยคำลังเล/ติดขัด หรือตามด้วยคำถาม
const BUT_MARKER = /แต่/gu;
const HEDGE_AFTER_BUT = /^\s*(?:ยัง|ไม่|ขอคิด|ขอเวลา|ขอปรึกษา|ขอดู|ติด|งบ|กลัว|กังวล|แน่ใจ|เดี๋ยว|ค่อย|รอ)/u;
const HEDGED_TAIL_ALWAYS = /เพียงแต่|ติดตรงที่/u;

/** หางของข้อความหลังกริยา "กลับข้าง" การตัดสินใจหรือเปล่า */
function tailHedged(tail) {
  const value = String(tail ?? "");
  if (HEDGED_TAIL_ALWAYS.test(value)) return true;
  BUT_MARKER.lastIndex = 0;
  for (let found = BUT_MARKER.exec(value); found; found = BUT_MARKER.exec(value)) {
    const rest = value.slice(found.index + found[0].length);
    if (HEDGE_AFTER_BUT.test(rest) || QUESTION_AFTER.test(rest)) return true;
  }
  return false;
}

