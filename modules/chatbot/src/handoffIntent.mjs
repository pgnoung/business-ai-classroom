// รอบนี้ใช้ "ประโยค" เป็นขอบเขตแทน ภาษาไทยไม่มีจุด แต่มีคำลงท้ายสุภาพซึ่งทำหน้าที่
// เดียวกับจุดในทางปฏิบัติ — จงใจ **ไม่** ตัดที่ช่องว่างเปล่า ๆ เพราะคนไทยเว้นวรรคกลาง
// ประโยคเดียวตลอด ("จองรอบ 19 ไว้ให้เพื่อนได้ไหมคะ" ต้องเป็นประโยคเดียว ไม่งั้นคำถาม
// จะหลุดไปอยู่คนละท่อนกับกริยาแล้วกลายเป็นการจอง)
//
// "ค่า" ไม่อยู่ในรายการโดยเจตนา — มันคือคำว่า "ค่าสมัคร/ค่าเรียน" บ่อยกว่าคำลงท้ายมาก
// ถ้าใส่เข้าไป "ค่าสมัครค่ะ" จะถูกตัดเป็นสองประโยคแล้ว "ค่า" หายไปจากบริบทของกริยา
const SENTENCE_SPLIT = /(?<=(?:ค่ะ|คะ|ครับ|คับ|ค้าบ|จ้า|จ้ะ|จ๊ะ|ฮะ))|[\n,.!?;:]+/u;

/** ตัดข้อความเป็นประโยคพร้อมตำแหน่งเริ่มต้นในข้อความเดิม (ต้องใช้ตำแหน่งเพื่ออ่านหางต่อ) */
function sentencesOf(value) {
  const out = [];
  let cursor = 0;
  for (const piece of value.split(SENTENCE_SPLIT)) {
    const at = value.indexOf(piece, cursor);
    const start = at < 0 ? cursor : at;
    if (piece.trim()) out.push({ text: piece, start });
    cursor = start + piece.length;
  }
  return out.length ? out : [{ text: value, start: 0 }];
}

/**
 * ตัดข้อความไทยเป็นประโยคด้วยกติกาเดียวกับตัวจับใบ้ (คำลงท้ายสุภาพ + วรรคตอน)
 *
 * กุญแจดอกที่ 2 (looksLikeHandoverReply ใน pipeline) ต้องอ่าน "รายประโยค" ไม่ใช่รายบรรทัด
 * เพราะ humanizer ยุบประโยคสั้น ๆ เข้าเป็นบอลลูนเดียวเสมอ — ใช้ตัวตัดตัวเดียวกันทั้งสองฝั่ง
 * ไม่ทำสำเนา ไม่งั้นวันหนึ่งสองฝั่งจะอ่านคนละประโยคกันโดยไม่มีใครรู้
 *
 * @param {unknown} value
 * @returns {string[]}
 */
export function splitThaiSentences(value) {
  const text = String(value ?? "");
  if (!text.trim()) return [];
  return sentencesOf(text).map((sentence) => sentence.text);
}

