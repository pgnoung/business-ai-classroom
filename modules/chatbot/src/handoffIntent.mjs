function shortMatch(value) {
  return String(value ?? "").replace(/\s+/gu, " ").trim().slice(0, HANDOFF_MATCH_MAX_CHARS);
}

// "ข้อความก้อนนี้มาจากการกดปุ่มสำเร็จรูปหรือเปล่า" — ปุ่มไม่ใช่การตัดสินใจ
// ("จองคิวได้ไหม" คือปุ่มมาตรฐานของ Facebook · เคสจริง 2026-09-03/04 ใน presetButtons.mjs)
// รับได้ทั้ง boolean และก้อน fact จาก presetButtonFact เพื่อให้ผู้เรียกส่งอะไรมาก็ไม่พลาด
