const CONTROL_RE = /[\u0000-\u0008\u000B-\u001F\u007F-\u009F​-‏‪-‮⁠-⁤﻿]/gu;
const EMAIL_RE = /[\w.+-]+@[\w-]+(?:\.[\w-]+)+/gu;
const PHONE_RE = /(?:\+?66|0)\d{1,2}[-\s.]?\d{3}[-\s.]?\d{3,4}/gu;
const LONG_NUMBER_RE = /\d[\d\s-]{8,}\d/gu; // เลขบัตร/บัญชี/เลขยาว ๆ
const URL_RE = /https?:\/\/\S+/giu;

/** ปิดข้อมูลติดต่อ/เลขยาวที่ผู้เรียนเผลอพิมพ์ — ไม่ส่งต่อให้โมเดลและไม่สะท้อนกลับในข้อความ */
export function maskSensitive(text) {
  return String(text ?? "")
    .replace(URL_RE, "[ลิงก์]")
    .replace(EMAIL_RE, "[อีเมล]")
    .replace(PHONE_RE, "[เบอร์]")
    .replace(LONG_NUMBER_RE, "[ตัวเลข]");
}

/** ข้อความหนึ่งช่องจากฟอร์ม/แชท → บรรทัดเดียวที่สะอาด ไม่เกิน max code point (ตัดแล้วต่อ …) */
export function cleanIntakeField(value, max) {
  const text = maskSensitive(String(value ?? "").replace(CONTROL_RE, " "))
    .replace(/\s+/gu, " ")
    .trim();
  const chars = [...text];
  return chars.length > max ? `${chars.slice(0, Math.max(0, max - 1)).join("").trimEnd()}…` : text;
}

