// promisePushGate.mjs — F8 (ตรวจย้อนหลัง ก.ย. 2026): คำรับปาก "ทีมงานจะ…" ควรปลุกคนจริงไหม
//
// ของจริงเดือน ก.ย.: push จากคำรับปาก 65 ครั้ง ผิด 28 — เกือบทั้งหมดคือบอทไม่รู้คำตอบเรื่องความรู้
// (Telegram, Gemini, n8n, e-book, ชื่อเครื่องมือทำวิดีโอ) แล้วพูดว่า "ขอให้ทีมงานยืนยันรายละเอียด"
// ทีมจึงชินกับเสียงเตือนจนคำรับปากที่ต้องมีคนทำจริง 7 เคส (นัดโทร ส่งลิงก์เข้าเรียน) ตกหล่น
//
// ตัดสินจาก "ฝั่งลูกค้า" เป็นหลัก ไม่ใช่กริยาของบอท: ผู้ตรวจวัดแล้วว่าประตูแบบกริยาบอทตัดของจริง
// ทิ้ง 20 เคส ส่วนประตูฝั่งลูกค้าตัดเสียงรบกวนครบ 30/30 — เสริมด้วยนัดที่บอทรับปากพร้อมเวลา/เบอร์
// (ลูกค้าตอบแค่ "18:00" แต่บอทรับปากว่าทีมงานจะโทรตอนนั้น = นัดที่ต้องมีคนทำ)
// ไม่เข้าประตู = โน้ตยังเขียนเหมือนเดิม (คิวคำสัญญาค้างในคอนโซลยังเห็น) แค่ไม่ปลุกคนด้วย push
import { normalizeThai } from "./safetyRouter.mjs";

// สิ่งที่ลูกค้าขอ/ให้มาแล้วต้องมีคนทำต่อ — ระวังกับดักตัวอักษรซ้อน:
// "นัด" อยู่ใน "ถนัด" · "ไลน์" อยู่ใน "ออนไลน์"/"อินไลน์" และธุรกิจนี้สอนเรื่อง LINE เอง ลูกค้าจึงพูดถึง
// "ไลน์ OA / ไลน์วูม" เป็นหัวข้อความรู้บ่อยมาก — นับ "ไลน์" เฉพาะรูปที่ขอช่องทางติดต่อจริง
const LINE_PRODUCT_AFTER = "(?!\\s*(?:วูม|voom|oa|official|กลุ่ม|แมน|shopping|ช้อปปิ้ง))";
const CUSTOMER_OWED_ACTION = new RegExp([
  "\\d[\\d\\s-]{8,12}\\d", "เบอร์", "โทร", "ติดต่อ", "ลิงก์", "ลิงค์", "link",
  "ใบเสนอราคา", "สิทธิ์", "เข้าเรียน", "ไอดี", "line\\s*id",
  `(?:ขอ|แอด|add|ทัก|เพิ่มเพื่อน|มี)\\s*(?:ทาง\\s*)?ไลน์${LINE_PRODUCT_AFTER}`,
  "ไลน์\\s*(?:ส่วนตัว|ทีมงาน|แอดมิน|พี่ง้วง|โค้ช)",
  "(?<!ถ)นัด", "สะดวก",
  "ขอคุย", "คนจริง", "มนุษย์", "แอดมิน", "เจ้าหน้าที่", "ทีมงาน", "โอน", "สลิป",
  "เข้าไม่ได้", "กดไม่ได้", "ล็อกอิน", "login", "เรท", "จ้าง", "ร่วมงาน",
].join("|"), "iu");

// ประโยครับปากของบอทที่ "ติดต่อ/โทร/นัด" พร้อมเบอร์หรือเวลา = นัดจริงที่ต้องมีคนทำ
// (ราคา "12,900" มีจุลภาค จึงไม่ใช่เบอร์ · เวลา HH:MM / HH.MM ต้องเป็นนาที 00–59
//  · เวลาเรียน "รอบ 26 ก.ย. 10:00–17:00 ทีมงานจะยืนยันที่นั่ง" ไม่ใช่นัดติดต่อ จึงต้องมีกริยาติดต่อด้วย)
const PROMISE_CONTACT_VERB = /โทร|ติดต่อ|(?<!ถ)นัด|คุย|call/iu;
const PROMISE_SCHEDULE = new RegExp([
  "\\d[\\d\\s-]{8,12}\\d",
  "(?<![\\d,.])(?:[01]?\\d|2[0-3])[:.][0-5]\\d(?![\\d,])",
  "\\d{1,2}\\s*(?:โมง|นาฬิกา|ทุ่ม)",
  "(?:บ่าย|เช้า|เย็น|ค่ำ)\\s*\\d",
  "พรุ่งนี้", "มะรืน",
  "วัน(?:จันทร์|อังคาร|พุธ|พฤหัส|ศุกร์|เสาร์|อาทิตย์)",
].join("|"), "u");

/** ข้อความลูกค้าเทิร์นนี้ (หรือสองข้อความก่อนหน้า) ขอ/ให้สิ่งที่ต้องมีคนทำไหม */
export function customerOwesHumanAction(customerTexts = []) {
  return (Array.isArray(customerTexts) ? customerTexts : [customerTexts])
    .some((text) => CUSTOMER_OWED_ACTION.test(normalizeThai(String(text || ""))));
}

// บอทรับปากว่าทีมงานจะ "ติดต่อกลับ/โทรหา" = มีคนต้องทำแน่นอน แม้ไม่มีเวลา (ทรงที่พี่ง้วงเลือกไว้ 19 ส.ค.)
// ต่างจากคำเลี่ยงเรื่องความรู้ ("ขอให้ทีมงานยืนยันรายละเอียด") ที่เป็นเสียงรบกวนทั้งหมดในข้อมูลจริง
// (วัดบนชุดที่ผู้ตรวจติดป้ายแล้ว: ไม่มี push ที่ผิดเคสไหนมาจากรูปนี้เลย)
const PROMISE_CALLBACK = /ติดต่อ(?:กลับ|ไปหา)|โทร(?:กลับ|หา)|จะโทร/u;

/** ประโยครับปากของบอทเป็นนัดติดต่อจริงไหม (ติดต่อกลับ หรือกริยาติดต่อ + เบอร์/เวลา) */
export function promiseIsScheduled(promiseLine = "") {
  const line = normalizeThai(String(promiseLine || ""));
  return PROMISE_CALLBACK.test(line) || (PROMISE_CONTACT_VERB.test(line) && PROMISE_SCHEDULE.test(line));
}

/** คำรับปาก "ทีมงานจะ…" ควร push ปลุกคนไหม (โน้ตเขียนเสมอ — ตัวนี้ตัดสินเฉพาะ push) */
export function promiseNeedsPush({ customerTexts = [], promiseLine = "" } = {}) {
  return customerOwesHumanAction(customerTexts) || promiseIsScheduled(promiseLine);
}
