// คำสั่งพี่ง้วง 2026-10-10: "ควรให้บอกราคาตั้งแต่ตอนลูกค้าตกลงรับรายละเอียดการสมัคร" — รับข้อเสนอนี้ = เปิดประตูราคาในเทิร์นเดียวกัน
// รีวิวปรปักษ์ 10 ต.ค.: เดิมด่านราคาอ่านคำรับแบบแคบ (คำรับเป๊ะ ๆ) แต่ v3 อ่านแบบกว้าง → "ส่งมาเลยค่ะ" / "เอาค่ะ" ถูกส่งเข้าขั้นสมัคร
// ทั้งที่ราคายังปิด (ขอชื่อ-อีเมลก่อนเห็นราคา) — สองที่จึงต้องเรียกตัวตัดสินตัวเดียวกันนี้
//
// ไฟล์ใบ: ห้าม import อะไรเพิ่ม (stage.mjs พา pipeline/priceDisclosure เข้ามาทางอ้อม = วงจร)

// ข้อเสนอส่งรายละเอียด/ขั้นตอนการสมัคร · ถามว่าจะสมัครรอบ/เรียนเลยไหม · ส่งต่อทีมดูแลการสมัคร
const REGISTRATION_DETAILS_OFFER = new RegExp([
  "(?:ส่ง|แจ้ง)[^\\n]{0,20}?(?:รายละเอียด|ข้อมูล|ขั้นตอน)(?:การ)?(?:สมัคร|ลงทะเบียน)",
  "(?:ต้องการ|อยาก|พร้อม)สมัคร(?:รอบ|เรียน)[^\\n?？]{0,30}?(?:ไหม|มั้ย)",
  "ส่งต่อ(?:ให้)?ทีม[^\\n]{0,30}?(?:สมัคร|ลงทะเบียน)",
  "ขั้นตอน(?:การ)?สมัคร",
  "จอง(?:ที่นั่ง|ที่)[^\\n?？]{0,30}?(?:ไหม|มั้ย)",
].join("|"), "u");
// ข้อเสนออื่นที่มีคำว่าสมัครปน (รีวิว/หัวข้อ/ตัวอย่าง/เงื่อนไข/ช่วยเลือกคลาสก่อนสมัคร) และลูกแพรขอข้อมูลจากลูกค้า ไม่นับ
const NOT_REGISTRATION_OFFER = /รีวิว|หัวข้อ|ตัวอย่าง|เนื้อหา|เงื่อนไข|ก่อนสมัคร|เทียบ|เลือกคลาส|เหมาะ|รบกวน|ของคุณ/u;

export function isRegistrationDetailsOffer(offer = "") {
  const value = String(offer || "");
  return REGISTRATION_DETAILS_OFFER.test(value) && !NOT_REGISTRATION_OFFER.test(value);
}

// คำถามใช่/ไม่ใช่ข้อสุดท้ายของก้อนข้อความล่าสุดของลูกแพร ("…ให้เลยไหมคะ?")
const YES_NO = /ไหม|มั้ย|มั๊ย/u;
const CONFIRM = /ใช่(?:ไหม|มั้ย)/u;
export function lastYesNoAskOf(burst = "") {
  const parts = String(burst || "").split(/\n+|(?<=[?？])\s*/u).map((part) => part.trim()).filter(Boolean);
  for (let i = parts.length - 1; i >= 0; i -= 1) {
    if (!/[?？]|ไหม|มั้ย|มั๊ย/u.test(parts[i])) continue;
    return YES_NO.test(parts[i]) && !CONFIRM.test(parts[i]) ? parts[i] : "";
  }
  return "";
}

// คำรับสั้น ๆ ("คับ" · "ส่งมาเลยค่ะ" · "เอาค่ะ" · "ได้เลยค่ะ รบกวนด้วยนะคะ" · "ok ครับ") — ไม่มีคำลังเล/ข้อกังวล/คำถามอื่นปน
// (ค่ะ/คะ/ค่า เป็นคำรับเฉพาะเมื่อจบคำ — "ค่าสมัครเท่าไรครับ" คือถามราคา)
const ACCEPT_HEAD = /^(?:ได้|เอา|(?:ค่ะ|คะ|ค่า)(?=$|[\s!.~ๆ]|ค่ะ|คะ)|ครับ|คับ|ok|โอเค|สนใจ|ขอ(?!โทษ|คิด)|ส่ง|ดี|อยาก|รบกวน|อืม|จ้า|ใช่|yes|ตกลง)/iu;
// มีคำลังเล/ข้อกังวล/คำถามอื่นปน (ราคา วิธีจ่าย ที่เรียน เวลา) = ไม่ใช่คำรับเปล่า ๆ
// รีวิวปรปักษ์ 10 ต.ค.: ขอ/ส่ง อย่างอื่น (เบอร์ทีม · รอบอื่น · รีวิว · ตาราง · โปรโมชั่น) และคำถาม/ข้อกังวลที่พ่วงมา ไม่ใช่การรับข้อเสนอการสมัคร
const NOT_PLAIN_ACCEPT = new RegExp(["ก่อน", "คิด", "ไม่", "แต่", "ปรึกษา", "กังวล", "ไหว", "เดี๋ยว", "(?<!อ)ยาก", "รอ(?!บ)", "ลังเล", "แน่ใจ", "มั่นใจ",
  "เงิน", "แพง", "งบ", "ลด", "ป่วย", "ตกงาน", "ไหม", "มั้ย", "[?？]", "เท่า", "ราคา", "ค่า(?:เรียน|สมัคร|ใช้จ่าย|คอร์ส)", "บาท", "จ่าย", "โอน",
  "ผ่อน", "บัตร", "บัญชี", "สลิป", "ยังไง", "อย่างไร", "ที่ไหน", "กี่", "เมื่อไ", "อะไร", "บ้าง", "ใคร", "ทำไม", "เปล่า", "เหรอ", "หรอ", "หรือ",
  "ไกล", "กลัว", "ห่วง", "เหนื่อย", "เสียดาย", "ทีม", "เบอร์", "แอดมิน", "โทร", "ติดต่อ", "รอบ", "เปลี่ยน", "รีวิว", "รูป",
  "ตาราง", "หัวข้อ", "โปร", "อื่น"].join("|"), "u");
const ACCEPT_MAX = 40;
export function isPlainAccept(text = "") {
  const value = String(text || "").trim();
  return Boolean(value) && [...value].length <= ACCEPT_MAX && ACCEPT_HEAD.test(value) && !NOT_PLAIN_ACCEPT.test(value);
}

/** ข้อความล่าสุดของลูกแพรจบด้วยข้อเสนอส่งรายละเอียดการสมัคร และลูกค้าตอบรับสั้น ๆ — คืนประโยคข้อเสนอ ("" = ไม่ใช่) */
export function acceptedRegistrationOffer({ text = "", lastBotText = "" } = {}) {
  if (!isPlainAccept(text)) return "";
  const ask = lastYesNoAskOf(lastBotText);
  return ask && isRegistrationDetailsOffer(ask) ? ask : "";
}

/** ก้อนข้อความล่าสุดของลูกแพร/ทีมก่อนข้อความนี้ ("" = เทิร์นก่อนหน้าเป็นของลูกค้า) */
export function trailingBotText(history = []) {
  const turns = Array.isArray(history) ? history : [];
  const out = [];
  for (let i = turns.length - 1; i >= 0 && turns[i]?.role === "assistant"; i -= 1) out.unshift(String(turns[i]?.content ?? ""));
  return out.join("\n");
}
