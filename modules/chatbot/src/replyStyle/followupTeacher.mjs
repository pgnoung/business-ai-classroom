/** กติกาทักตาม + กติกาแบบครู (สวิตช์เปิดเท่านั้น) */
export function withFollowupTeacher(rules, db) {
  return followupTeacherMode(db) === "on" ? `${rules}\n\n${FOLLOWUP_TEACHER_RULES.join("\n")}` : rules;
}
