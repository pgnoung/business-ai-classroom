      // รีวิวเคสจริง 5 ต.ค.: สิ่งที่ลูกค้าถามเอง (วิธีจ่าย / วิธีสมัคร) ต้องได้คำตอบ ไม่ใช่ถูกเลี่ยงด้วยประโยคดูแลใจ
