const usable = (d, type, text) => allows(d, type) && !repeatsText(d, text);

/** ข้อเสนอปิดท้ายของ BRIDGE (null = ข้อเสนอทุกแบบเพิ่งเสนอไปแล้วและลูกค้ายังไม่ตอบ → คำถามเปิด) */
const ENROLL_OFFER = "\"ไม่ทราบว่าคุณ(ชื่อ) สะดวกเริ่มรอบไหนดีนะคะ เลือกแล้วลูกแพรส่งรายละเอียดการสมัครให้ค่ะ\"";
