export const WISH_BEYOND_LEVEL_MOVE = "เขาบอกว่าอยากเรียนคลาส AI Agent Workflow Automation แต่ระดับตอนนี้ยังไม่ถึงระดับ 5: บอกหนึ่งประโยคว่าคลาส Workflow "
  + "ต่อยอดจากพื้นฐานในคลาส AI Agent for Business จึงแนะนำให้เริ่มจาก Business ก่อน (การ์ดราคามีทั้งสองคลาส Business ก่อน) — ไม่บอกว่าเขาเรียน Workflow ไม่ได้";
function priceClosing(facts, d = {}) {
  if (d.roundPick) return BOOKING_STEP;
  if (d.reason === "price_owed" && facts.statedTiming) return timingClosing(facts, d);
  if (facts.wishBeyondLevel) return twoRounds(facts) && usable(d, "rounds", chooseRounds(facts)) ? `ชวนเลือกรอบของคลาส ${DEFAULT_CLASS} เช่น ${chooseRounds(facts)}` : HESITATION_QUESTION;
  if (!facts.classKey || (d.stage === "PRICE" && priceShowsBothClasses(facts))) return classChoiceClosing(facts, d);
  // feedback ทีม 10 ต.ค.: เลือกรอบไว้แล้วค่อยถามค่าเรียน = ก้าวสมัครของรอบนั้น (เคยถูกถามยืนยันรอบซ้ำ)
  if (keepPick(facts)) return BOOKING_STEP;
  if (twoRounds(facts) && usable(d, "rounds", chooseRounds(facts))) return `ชวนเลือกรอบ เช่น ${chooseRounds(facts)}`;
  return facts.roundLabels?.length ? ENROLL_STEP : HESITATION_QUESTION;
}

// ข้อ 6 รอบรีวิว 2: ราคาที่ค้างจากเทิร์นแบ่งรับ แล้วลูกค้าตอบช่วงเวลาที่ช้ากว่านี้ ("ยังไม่รีบครับ น่าจะต้นปีหน้า") — เดิมปิดด้วยการชวนเลือกรอบเดือนนี้
// = รับช่วงเวลาของเขา ไม่ชวนรอบที่เร็วกว่านั้น · มีรอบในช่วงนั้น = ชวนรอบเหล่านั้น · ไม่มี = ชวนบอกเมื่อใกล้ช่วงนั้น (ไม่มีระบบจองที่/แจ้งเตือนรอบใหม่ จึงไม่รับปาก)
function timingClosing(facts, d = {}) {
  const timing = facts.statedTiming || {};
  const later = timing.roundLabels || [];
  const head = `รับช่วงเวลาที่เขาบอก ("${clip(timing.label, 40)}") ไม่ชวนเลือกรอบที่เร็วกว่านั้น`;
  const choose = later.length >= 2 ? `"สะดวกรอบ ${later[0]} หรือ ${later[1]} ดีคะ?"` : "";
  if (choose && usable(d, "rounds", choose)) return `${head} — ชวนเลือกรอบในช่วงนั้น เช่น ${choose}`;
  if (later.length) return `${head} — ถามหนึ่งข้อว่ารอบ ${later[0]} ซึ่งอยู่ในช่วงนั้นสะดวกไหม`;
  const when = timing.from ? "ใกล้ช่วงนั้นแล้ว" : "พร้อมเมื่อไหร่";
  return `${head} — บอกเบา ๆ ว่า${when}อยากดูรอบ บอกลูกแพรได้เลย แล้วถามเบา ๆ หนึ่งข้อว่ามีส่วนไหนอยากรู้เพิ่มไว้ประกอบการวางแผนไหม${DATE_NO_PROMISE}`;
}

// ดีลคู่หลังลูกค้าข้ามคำถามรอบมาถามส่วนลด = ชวนเลือกรอบได้หนึ่งครั้ง (รีวิวเคสจริง 5 ต.ค. case-015) · ประโยคเดิมเพิ่งถาม = คำถามเปิด
function dealClosing(facts, d = {}) {
  if (d.roundPick || keepPick(facts)) return BOOKING_STEP;
  if (d.reason === "price_owed" && facts.statedTiming) return timingClosing(facts, d);
  const choose = chooseRounds(facts, "สะดวกมาเรียนรอบ");
  if (twoRounds(facts)) return usable(d, "rounds", choose) ? `ชวนเลือกรอบ เช่น ${choose}` : OPEN_QUESTION;
  return usable(d, "rounds", ROUNDS_OFFER) ? ROUNDS_OFFER : OPEN_QUESTION;
}
// ขั้นสุดท้ายของงาน DEAL_PAIR (ถ้อยคำเดิมของ v3.2 ในกรณีที่ไม่เปลี่ยน)
function dealMove(facts, d = {}) {
  const closing = dealClosing(facts, d);
  if (closing === OPEN_QUESTION || closing === BOOKING_STEP || (d.reason === "price_owed" && facts.statedTiming)) return `ปิดด้วย${closing}`;
  return closing === ROUNDS_OFFER ? `ปิดด้วยข้อเสนอแบบขออนุญาตหนึ่งข้อ: ${ROUNDS_OFFER}`
    : `ปิดด้วยการชวนเลือกรอบ เช่น ${chooseRounds(facts, "สะดวกมาเรียนรอบ")}`;
}

function dealShort(facts, d = {}) {
  const closing = dealClosing(facts, d);
  if (closing === OPEN_QUESTION) return OPEN_QUESTION_SHORT;
  if (d.reason === "price_owed" && facts.statedTiming) return "ก้าวถัดไปที่ตรงกับช่วงเวลาของเขา ไม่ชวนรอบที่เร็วกว่านั้น";
  return closing === BOOKING_STEP ? "ก้าวสมัครหนึ่งข้อ" : "ชวนเลือกรอบ";
}

