// เคสจริง 5 ต.ค.: ห้ามปิดซ้ำด้วยสิ่งที่ลูกค้ายังไม่ตอบรับ (ยกประโยคเดิมให้เห็น + ชนิดข้อเสนอที่ห้ามใช้)
const AVOID_QUOTE_CHARS = 80;
function avoidLine(d) {
  if (!d.avoid?.length) return "";
  const quotes = [...new Set(d.avoid.map((item) => `"${[...item.text].slice(0, AVOID_QUOTE_CHARS).join("")}"`))].join(" · ");
  const labels = [...avoidTypesOf(d)].map((type) => TYPE_LABEL[type]).filter(Boolean);
  return `- สองเทิร์นล่าสุดลูกแพรปิดท้ายด้วย: ${quotes} — เทิร์นนี้ห้ามปิดด้วยประโยคเดิมหรือถามซ้ำ`
    + `${labels.length ? ` · ลูกค้ายังไม่ตอบรับข้อเสนอเรื่อง${labels.join(" / ")} ห้ามเสนอซ้ำ` : ""}`;
}

// รีวิวเคสจริงทั้งวัน 5 ต.ค.: ข้อความแรกของลูกแพรต้องทักทาย (intro) · คำถามของลูกค้าต้องได้คำตอบก่อนบันได/คำถามคัดกรอง (answer_first)
// ทักแรกทักทายในข้อแรกของงานเองอยู่แล้ว = คำตอบอยู่ต่อจากคำทักทาย · ขอพื้นฐานก่อนราคามีขั้น "ตอบเรื่องอื่นก่อน" ในงานอยู่แล้ว
function leadMoves(d, moves, f = {}) {
  const mods = d.modifiers || [];
  const out = [...moves];
  // คำตอบอยู่ต่อจากข้อแรกของงานเมื่อข้อแรกคือทักทาย (ทักแรก) หรือคำขอโทษที่ทำให้งง (งงคำถามในโฆษณา)
  const after = d.stage === "FIRST_CONTACT" || d.reason === "confused_opening" ? 1 : 0;
  // พี่ง้วง 12 ต.ค.: ทักแรกตอบจากข้อมูลคลาสจริงที่ให้ไว้ในงาน (เดิมโมเดลไม่มีข้อมูลเลย แล้วตอบว่ายังยืนยันไม่ได้)
  const answer = d.stage === "FIRST_CONTACT" && !hasDetails(d) && classInfoAsked(f.text) ? firstAnswerMove(f) : ANSWER_FIRST_MOVE;
  if (mods.includes("answer_first") && d.stage !== "SCREEN_PRICE") out.splice(after, 0, answer);
  if (mods.includes("intro")) out.unshift(INTRO_MOVE);
  return out;
}

function movesFor(spec, d, facts, quiet) {
  const moves = spec.moves(d, facts).filter(Boolean);
  // หลังแจ้งราคา/ส่งรอบ: ขั้นถามปิดท้ายของจังหวะ (คำถามเรื่องงาน) เปลี่ยนเป็นก้าวถัดไป
  if (!quiet && d.afterPrice && moves.length) moves[moves.length - 1] = `ปิดท้าย: ${nextStepClosing(d, facts)}`;
  if (quiet && asksAtEnd(d) && moves.length) moves[moves.length - 1] = quietMove(quiet, d);
  return leadMoves(d, moves, facts).map((move, i) => `${i + 1}. ${move}`);
}

/** ปิดท้ายแบบสั้น (บรรทัดสรุปท้ายข้อความลูกค้า = คำสั่งที่โมเดลอ่านทีหลังสุด) */
export function closingShortFor(d, facts = {}) {
  const spec = STAGES[d.stage] || STAGES.DISCOVERY;
  const quiet = closingMode(d);
  const short = quiet && !OWN_CLOSING.has(d.stage) ? QUIET[quiet].short : d.afterPrice ? AFTER_PRICE_SHORT
    : typeof spec.closingShort === "function" ? spec.closingShort(d, facts) : spec.closingShort;
  return d.avoid?.length ? `${short} · ไม่ซ้ำข้อเสนอเดิม` : short;
}

/**
 * บล็อก "งานของเทิร์นนี้" ที่โมเดลอ่าน + ข้อมูลที่ postCheck/recap ใช้
 * @returns {{thai: string, band: number[], closingShort: string, text: string}}
 */
// รีวิวเคสจริงทั้งวัน 5 ต.ค. (รอบรีวิวสอง): เทิร์นรับคำเงียบ ๆ (ปฏิเสธคลาส/ข้อเสนอ · ยังไม่พร้อม · บ่นงบ) ได้ความยาว 220–420 ของจังหวะข้อกังวล
// — โมเดลต้องเติมเนื้อหาจนยาวพอ (และด่าน S6 สั่งให้ยาวขึ้นถ้าตอบสั้น) ซึ่งมักเป็นจุดขายหรือข้อเสนอ = ความยาวสั้นของตัวเอง
const QUIET_OBJECTION_BAND = Object.freeze([80, 240]);
export function bandFor(d = {}) {
  if (d.stage === "DISCOVERY" && d.reason === "dig") return DIG_BAND;
  // ข้อ 6: แบ่งรับด้วยคุณค่า (มีบันได/รายละเอียดคลาส = ความยาวของทรงนั้นตามเดิม) · scorer บอกว่าพร้อม = สั้นลง เว้นแต่ต้องตอบเรื่องอื่นก่อน
  if (d.stage === "SCREEN_PRICE" && d.hedge && !d.ladder && !hasDetails(d)) {
    return hedgeBandReady(d) ? HEDGE_READY_BAND : HEDGE_BAND;
  }
  if (d.stage === "OBJECTION" && (d.softDecline || d.offerDeclined || d.notReady || d.classDeclined)) return QUIET_OBJECTION_BAND;
  // รีวิวเคสจริง 6–7 ต.ค.: ข้อความแรกที่ขอรายละเอียดมีข้อมูลคลาส 2–3 ประโยคเพิ่ม (บันไดอยู่ในช่องเติม ไม่นับความยาว)
  if (hasDetails(d) && DETAILS_BAND[d.stage]) return DETAILS_BAND[d.stage];
  if (d.stage === "FIRST_CONTACT" && (d.modifiers || []).includes("answer_first")) return FIRST_ANSWER_BAND;
  if ((d.stage === "BRIDGE" && d.reason === "enroll_opening") || (d.stage === "LOGISTICS" && d.reason === "enroll_opening_round")) return ENROLL_OPENING_BAND;
  if (openingValue(d)) return OPENING_VALUE_BAND[d.stage];
  // รอคนตัดสินใจ: รับคำ + เสนอสรุปไว้ส่งต่อ + ลูกแพรยินดีประสานงาน ยาวกว่าคำลาธรรมดาเล็กน้อย
  if (d.stage === "GOODBYE" && d.reason === "care_moment" && d.care === "waiting") return CARE_WAITING_BAND;
  if (d.stage === "GOODBYE" && d.reason === OFFTOPIC_CLOSE_REASON) return OFFTOPIC_CLOSE_BAND;
  return (STAGES[d.stage] || STAGES.DISCOVERY).band;
}

export function stageTask(d, facts, { openSlots = [], guardRepair = "" } = {}) {
  const spec = STAGES[d.stage] || STAGES.DISCOVERY;
  const band = bandFor(d);
  const [min, max] = band;
  const quiet = OWN_CLOSING.has(d.stage) ? null : closingMode(d);
  const slotLine = openSlots.length
    ? `ช่องเติมที่เปิด: ${spec.slotNote ? spec.slotNote(d, facts) : openSlots.map((name) => `{{${name}}}`).join(" ")}`
    : "ช่องเติมที่เปิด: ไม่มี";
  // ข้อ 6: แบ่งรับด้วยคุณค่าใช้จังหวะเดียวกับการขอพื้นฐานก่อนราคา แต่ชื่องานต้องบอกโมเดลตรง ๆ ว่านี่ไม่ใช่การคัดกรองคนแปลกหน้า
  const thai = d.stage === "SCREEN_PRICE" && d.hedge ? HEDGE_THAI
    : d.stage === "GOODBYE" && d.reason === OFFTOPIC_CLOSE_REASON ? OFFTOPIC_CLOSE_THAI : spec.thai;
  const lines = [
    `## งานของเทิร์นนี้: ${thai}`,
    `ความยาว: ราว ${min}–${max} ตัวอักษร (ไม่นับช่องเติม)`,
    "ทำให้ครบตามลำดับ:",
    ...movesFor(spec, d, facts, quiet),
    slotLine,
    `ปิดท้าย: ${quiet ? QUIET[quiet].closing : d.afterPrice ? nextStepClosing(d, facts) : spec.closing(d, facts)}`,
    ...modifierLines(d, facts),
    ...(guardRepair ? [`## ข้อกำกับเพิ่มจากด่านตรวจ (ต้องทำตาม)\n${guardRepair}`] : []),
  ];
  return { thai, band, closingShort: closingShortFor(d, facts), text: lines.join("\n") };
}
