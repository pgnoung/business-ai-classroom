const DECIDER = "(?:สามี|ภรรยา|แฟน|หัวหน้า|เจ้านาย|ผู้จัดการ|ผู้บริหาร|ผู้อำนวยการ|บอส|ที่บ้าน|ครอบครัว|พ่อ|แม่|ผู้ใหญ่|บริษัท|ฝ่ายบุคคล|ฝ่ายจัดซื้อ|จัดซื้อ|หุ้นส่วน|hr\\b)";
