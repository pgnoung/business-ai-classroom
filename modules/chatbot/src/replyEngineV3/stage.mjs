const STICKER_PART = /^\s*(?:\[sticker[^\]]*\]|\(ลูกค้าส่งสติกเกอร์[^)]*\))\s*$/iu;
// บรรทัดลาที่มีเรื่องราคา ("ขอบคุณที่สนใจนะคะ ราคา…") = เปิดเรื่องราคา ไม่ใช่ลา
const FAREWELL_PRICE_RE = /ราคา|ค่าเรียน|โปรโมชั่น|early ?bird|\d{3,}|\d,\d{3}/iu;
// รีวิวเคสจริงทั้งวัน 5 ต.ค. (รอบรีวิว): คำตอบราคาที่จบด้วย "ถ้าพร้อมสมัครรอบไหน ทักลูกแพรมาได้เลยนะคะ" แล้วลูกค้าตอบ "ได้ค่ะ" เคยเงียบ
// — ก้อนล่าสุดของลูกแพรมีราคา/รอบ/การสมัคร = "ได้ค่ะ" อาจเป็นการตกลง ต้องตอบ (ดูทั้งก้อน ไม่ใช่แค่บรรทัดท้าย)
const FAREWELL_SALES_RE = /ราคา|ค่าเรียน|โปรโมชั่น|early ?bird|\d,\d{3}|\d{3,}\s*บาท|รอบ(?!คอบ)|สมัคร|จอง|ที่นั่ง|โอน|ชำระ/iu;
/** ทุกบับเบิลของก้อนเป็นคำรับ/อีโมจิ/สติกเกอร์ล้วน หลังคำลาของลูกแพรที่ไม่มีคำถามหรือข้อเสนอค้าง */
export function silentAfterFarewell(f = {}) {
  if (f.money) return false;
  const parts = Array.isArray(f.parts) && f.parts.length ? f.parts.map(String) : [String(f.text || "")];
  // คำลาต้องเป็นประโยคท้ายที่มีตัวอักษรของบรรทัดท้าย (ตัวแบ่งประโยคแยก 😊 ท้ายบรรทัดเป็นประโยคเดี่ยว)
  const lastLine = String(f.lastBotText || "").split("\n").map((line) => line.trim()).filter(Boolean).at(-1) || "";
  const lastSentence = sentencesOf(lastLine).filter((sentence) => /\p{L}/u.test(sentence)).at(-1) || "";
  if (!BOT_FAREWELL.test(lastSentence) || FAREWELL_PRICE_RE.test(lastLine) || FAREWELL_SALES_RE.test(String(f.lastBotText || ""))) return false;
  // รีวิวเคสจริงทั้งวัน 5 ต.ค. (รอบรีวิว): เงียบได้เฉพาะคำที่คอนโซลก็นับว่าไม่ต้องตอบ (ตัวจับเดียวกับรายการห้องรอคน) — ไม่งั้นห้องที่ลูกแพรเงียบไป
  // ค้างอยู่ในรายการ "รอคนตอบ" ทั้งที่ไม่มีใครต้องตอบ
  return parts.every((part) => {
    const sticker = STICKER_PART.test(part);
    return afterBotFarewell(f, sticker ? "" : part.trim()) && (sticker || isAckOnlyInbound({ type: "text", text: part }));
  });
}

/** ก้อนข้อความล่าสุดของลูกแพรก่อนเทิร์นนี้ ("" = เทิร์นก่อนหน้าเป็นของลูกค้า) */
export function lastBotBurstOf(history = []) {
  const turns = Array.isArray(history) ? history : [];
  const out = [];
  for (let i = turns.length - 1; i >= 0 && turns[i]?.role === "assistant"; i -= 1) out.unshift(String(turns[i]?.content ?? ""));
  return out.join("\n");
}

/** ตัวเรียกของไปป์ไลน์ (ก่อนโชว์กำลังพิมพ์และก่อนเลือกเลน) — history = ประวัติก่อนก้อนปัจจุบัน */
export function silentAckTurn({ text = "", parts = [], history = [] } = {}) {
  const turns = Array.isArray(history) ? history : [];
  return silentAfterFarewell({ text, parts, prevRole: turns.at(-1)?.role || "", lastBotText: lastBotBurstOf(turns) });
}

