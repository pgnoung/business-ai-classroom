// คำถามที่ลูกแพรถามค้างไว้ท้ายข้อความล่าสุด ("" = ไม่มี)
function pendingQuestion(f) {
  if (f.prevRole !== "assistant") return "";
  const line = String(f.lastBotText || "").split("\n").map((part) => part.trim()).filter(Boolean).at(-1) || "";
  const sentence = line.split(/(?<=(?:ค่ะ|คะ|ครับ|[?？!]))\s+/u).filter(Boolean).at(-1) || "";
  return isClosingQuestion(sentence) ? sentence : "";
}


// ข้อเสนอของลูกแพรเอง ถ้าเป็นคำถาม/ข้อเสนอล่าสุดของก้อน — "" = คำถามล่าสุดเป็นเรื่องอื่น หรือไม่มีข้อเสนอ
// (รีวิว v3.2: ข้อเสนอเก่ากลางก้อนห้ามชนะคำถามที่ถามตามหลัง — ลูกค้ากำลังตอบคำถามนั้น)
// คืนเฉพาะท่อนตั้งแต่ผู้เสนอจนถึงคำปิดข้อเสนอ เพื่อไม่ให้คำว่า คลาส/รอบ ในประโยคข้างเคียงมาตัดสินแทน
const PURPOSE_TAIL = /^(?:จะได้|เพื่อ(?:ให้|จะ)?|ลูกแพรจะได้)/u;
export function offerSentence(lastBotText = "") {
  const sentences = sentencesOf(lastBotText);
  for (let i = sentences.length - 1; i >= 0; i -= 1) {
    const sentence = sentences[i];
    if (!askLike(sentence)) continue;
    const actor = OFFER_ACTOR.exec(sentence);
    // พี่ง้วง 13 ต.ค.: "ให้ลูกแพรส่งหัวข้อ…ให้ดูก่อนไหมคะ" + บับเบิลต่อ "จะได้เช็กว่า…ค่ะ?" — ท่อนเหตุผลต่อท้ายไม่ใช่คำถามใหม่ ข้ามไปหาข้อเสนอ
    if (!actor && PURPOSE_TAIL.test(sentence)) continue;
    if (!actor || CONFIRM_ASK.test(sentence)) return "";
    const clause = sentence.slice(actor.index);
    const close = OFFER_CLOSE.exec(clause);
    return close ? clause.slice(0, close.index + close[0].length).trim() : "";
  }
  return "";
}

