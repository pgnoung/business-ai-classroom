const ACCEPT_TAIL_WORDS = ["หน่อย", "ด้วย", "ครับ", "เลย", "ค่ะ", "คะ", "คับ", "จ้า", "นะ"];
function stripAcceptTail(value = "") {
  let cut = value.length;
  for (;;) {
    const hit = ACCEPT_TAIL_WORDS.find((word) => value.endsWith(word, cut));
    if (!hit) break;
    cut -= hit.length;
    while (cut > 0 && /\s/u.test(value[cut - 1])) cut -= 1;
  }
  return value.slice(0, cut);
}
