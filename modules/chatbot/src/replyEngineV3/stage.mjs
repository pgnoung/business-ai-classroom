const EXEC_REVIEW = `${NOT_NEEDED}(?:รอ(?!บ)|ส่งให้|ให้|(?<!ใบ)เสนอ|นำเสนอ|ปรึกษา|ขออนุมัติ)\\S{0,4}?ผู้บริหาร\\S{0,10}?(?:พิจารณา|อนุมัติ|ตัดสินใจ)`;
