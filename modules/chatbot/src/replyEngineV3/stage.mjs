// รีวิวเคสจริงทั้งวัน 5 ต.ค. (รอบรีวิวสอง): "แอดมินคะ" / "ลูกแพรคะ" หลังคำลา = เรียกหาคน (เคยเงียบ) — ชื่อล้วนไม่ใช่คำรับ ต้องมีคำขอบคุณ/รับทราบด้วย
const ADDRESS_CALL_RE = /ลูกแพร|แอดมิน|ทีมงาน/u;
const ACK_CONTENT_RE = /ขอบ(?:พระ)?คุณ|thank|ยินดี|เช่นกัน|สาธุ|รับทราบ/iu;

// ---- เงียบหลังลา (รีวิวเคสจริงทั้งวัน 5 ต.ค.) ----
// ลูกแพรลาแล้ว ลูกค้าตอบ "ค่ะ" แล้ว "👍" — v3 ได้จังหวะ GOODBYE ทุกครั้ง (เสียโมเดลหนึ่งยก + ส่งคำลา "ทักลูกแพรได้ตลอด" ซ้ำสามรอบในห้องเดียว)
