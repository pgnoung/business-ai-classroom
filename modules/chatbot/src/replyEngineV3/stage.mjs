const NOT_READY_RE = /(?:ยัง)?ไม่(?:ค่อย)?พร้อม(?:เรียน|สมัคร|จะเรียน|ลงเรียน)?(?!\s*(?:ไหม|มั้ย|มั๊ย))|ไม่ได้(?:อยาก|คิดจะ|ตั้งใจ(?:จะ)?)เรียน|ยังไม่(?:ได้)?คิด(?:จะ|ว่าจะ)เรียน/u;
