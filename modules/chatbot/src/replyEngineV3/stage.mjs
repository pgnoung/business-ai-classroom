/**
 * สำรองของ followupStopOf สำหรับเทิร์นที่ไม่มี metadata ของ v3 (เลน/แม่แบบของเครื่องเดิม) — อ่านจากข้อความล่าสุดของลูกค้าอย่างเดียว
 * money_hardship · pressure · crisis · waiting · declined · defer · goodbye · "" — ตัวจับชุดเดียวกับตัวตัดสินจังหวะ
 * (ข้อความที่ยังถามหรือบอกจะสมัคร = "" · defer/waiting = ทักครั้งเดียว · goodbye = ลูกค้าลาเอง)
 */
export function followupStopSignal(text = "") {
  const t = String(text || "").trim();
  if (!t) return "";
  const enroll = ENROLL_RE.test(t) || ENROLLED_RE.test(t);
  if (concernOf({ text: t })?.hardship) return enroll ? "" : "money_hardship";
  if (enroll || ROUND_PICK_RE.test(t)) return "";
  const care = careMomentOf({}, t);
  if (care) return care;
  const asks = ASKS_RE.test(t) || STILL_ASKING.test(t);
  const long = [...t].length > EXIT_MAX_CHARS;
  // "สนใจค่ะ แต่ขอปรึกษาแฟนก่อน" (มีคำพร้อมซื้อ ตัวดูแลใจของเทิร์นจึงไม่นับ) · "ขอรอเงินเดือนออกก่อน" = ยังรออยู่
  if (!asks && !long && (CARE_WAITING_RE.test(t) || WAIT_FOR_MONEY_RE.test(t)) && !CARE_WAIT_DONE_RE.test(t)) return "waiting";
  const compact = t.replace(EMOJI, "").replace(/\s+/gu, "");
  const buying = buyingWords(t);
  if (!buying && !long && !NEGATED_DECLINE_RE.test(compact) && !EXIT_REPORTED_RE.test(t)) {
    if (DECLINE_ONLY_RE.test(compact) || EXPLICIT_PASS_RE.test(compact)) return "declined";
    if (NOT_INTERESTED_RE.test(compact) && !asks && !EXIT_GUARD_RE.test(t)) return "declined";
    // "ไม่สนใจ ไว้ก่อนนะคะ" (ขึ้นต้นด้วยคำปฏิเสธ แล้วต่อด้วยคำเลื่อน) = ปฏิเสธ ไม่ใช่ขอเวลาคิด — "ไม่สนใจคลาสนี้ แต่อยากได้อีกคลาส" ไม่นับ
    if (FOLLOWUP_DECLINE_LEAD.test(compact) && !asks && !FOLLOWUP_DECLINE_BUT.test(t)) return "declined";
    if (NO_BUDGET_RE.test(t) && !asks) return "money_hardship";
  }
  if (asks || long) return "";
  if (FOLLOWUP_DEFER_RE.test(t) || (STILL_INTERESTED_RE.test(t) && DEFER_CONTEXT_RE.test(t))) return "defer";
  if (buying) return "";
  if ([...compact].length <= CUSTOMER_CLOSE_MAX_CHARS && CUSTOMER_CLOSE_RE.test(compact) && CLOSE_WORD_RE.test(compact)) return "goodbye";
  return "";
}

