// · ลูกค้าบอกเองว่าจะสมัคร (enroll) ไม่นับเงินตึง (ก้าวสมัครที่เขาถามยังตามต่อได้)
// รีวิวเคสจริง 6–7 ต.ค. (รอบรีวิว 8 · นโยบายทักตามที่เจนเคาะ): "ขอคิดดูก่อน" / "ขอบคุณค่ะ เดี๋ยวดูก่อน" / "ขอบคุณข้อมูลค่ะ สนใจอยู่ค่ะ"
// ได้ป้ายลา (goodbye) เลยไม่ได้ทักตามเลยสักครั้ง (จำลอง 8 วัน: hot 2→0 · warm 3→0) — ขอเวลาคิด = "defer" (ทักครั้งเดียววันถัดไป/วันที่ 3)
// · รอปรึกษาคนที่บ้าน/หัวหน้า หรือรอเงินเดือน = "care:waiting" (ทักครั้งเดียวภายหลัง) · ป้ายลาเหลือเฉพาะลูกค้าปิดเองจริง ๆ
export function followupStopOf(d = {}, text = "") {
  if (d.stage === "EXIT") return `exit:${d.exit || d.reason || ""}`;
  if (d.stage === "SILENT") return "silent";
  if (d.stage === "GOODBYE") {
    if (d.reason === "care_moment") return `care:${d.care || "crisis"}`;
    // 12 ต.ค. 2026: ตีจบแชทนอกเรื่อง = หยุดทักตามถาวร (ห้องเป็นสีเหลือง — ลูกค้าทักกลับมาด้วยเรื่องเรียนค่อยเริ่มใหม่)
    if (d.reason === OFFTOPIC_CLOSE_REASON) return OFFTOPIC_FOLLOWUP_STOP;
    const said = followupStopSignal(text);
    return said === "defer" ? "defer" : said === "waiting" ? "care:waiting" : "goodbye";
  }
  if ((d.modifiers || []).includes("money_hardship") && !d.enroll) return "money_hardship";
  if (d.stage === "OBJECTION" && (d.offerDeclined || d.classDeclined || d.notReady || d.softDecline)) return "declined";
  return "";
}

