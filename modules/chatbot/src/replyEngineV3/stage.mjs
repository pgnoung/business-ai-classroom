const ACCEPT_LEAD_RE = /^\s?(?:(?:ได้(?:เลย)?|เอา|โอเค|okay|ok|สนใจ|ส่ง(?:มา|ให้)?(?:ดู)?(?:เลย)?|อยาก(?:ดู|ได้))(?:ค่ะ|คะ|ค่า|ครับ|คับ|จ้า|นะ)*|ครับ|คับ|ค่ะ|ค่า)(?=\s|[,.!]|$)/iu;
/**
 * ข้อเท็จจริงของเทิร์นที่ทำให้ไม่แบ่งรับ ("" = แบ่งรับได้)
 * · round_pick = เลือกรอบในข้อความนี้ → ราคา + ก้าวสมัครของรอบนั้น
 * · accepted_offer = รับข้อเสนอที่ลูกแพรเพิ่งเสนอ (ส่งรอบ/หัวข้อ/รายละเอียด) ในข้อความเดียวกับที่ถามราคา → ราคา + สิ่งที่รับ (ตามเดิม)
 * · all_known = รู้ระดับ/คลาส จำนวนคน และรอบที่เลือกครบแล้ว — ไม่มีคำถามที่เปลี่ยนราคาเหลือ → แจ้งราคาพร้อมคุณค่าเลย
 */
export function valueHedgeExemptOf(f = {}) {
  if (roundPickOf(f)) return "round_pick";
  const t = String(f.text || "");
  if (f.pendingOffer?.accepted || f.continuation?.action === "continue_previous_offer") return "accepted_offer";
  if (f.prevRole === "assistant" && pendingOfferOf(f) && ACCEPT_LEAD_RE.test(t) && !HESITATE_RE.test(t)) return "accepted_offer";
  const headcountKnown = Number.isInteger(f.routing?.headcount) || soloSaidIn(f);
  if (f.pickedRound && headcountKnown && hedgeLevelKnown(f)) return "all_known";
  // พี่ง้วง 13 ต.ค.: คุยจนรู้งาน/เป้าหมายและจำนวนคนแล้ว (แชทจริง: คุย 50 นาที บอกงานเอกสาร ทำคนเดียว แล้วถามราคา โดนถามระดับอีกข้อ)
  // = คำถามที่เหลือไม่เปลี่ยนราคาที่เขาต้องรู้ → แจ้งราคาพร้อมคุณค่าเลย (เกณฑ์ "รู้งาน" ตัวเดียวกับ stageTasks.hedgeTopic)
  const goalKnown = Boolean(f.goal?.evidence || f.painPoint) || (f.discoveryDepth || 0) >= 2;
  if (goalKnown && headcountKnown) return "story_known";
  // พี่ง้วง 14 ต.ค.: ให้ AI ตัวให้คะแนน (Luna) ช่วยตัดสินว่า "คุยกันลึกพอสมควรแก่การให้ราคาแล้ว" หรือ "เพิ่งคุยแล้วเปิดมาด้วยราคา"
  // ใช้การอ่าน price_read ของแถวคะแนนล่าสุด (Luna อ่านหลังเทิร์นก่อน = ภาพของบทสนทนาก่อนลูกค้าถามราคา ไม่เพิ่มเวลา/ค่าใช้จ่าย)
  // warming (เล่าโจทย์/เป้าหมายแล้ว หรือถามความเหมาะสมของคลาส) · ready (พิมพ์เองว่าอยากเรียน) = คุยเรื่องคลาสแล้วแจ้งราคาเลย
  // early / ยังไม่มีการอ่าน (เปิดห้องมาด้วยราคา) = แบ่งรับตามเดิม · พื้นขั้นต่ำ: ลูกค้าพิมพ์มาก่อนหน้านี้แล้วอย่างน้อย 2 ข้อความ
  if (LUNA_PRICE_EARNED.has(f.priceRead?.readiness) && priorCustomerTurns(f) >= LUNA_PRICE_MIN_TURNS) return "luna_earned";
  return "";
}

