// คนตัดสินใจที่ลูกค้าเอ่ยถึง (ใช้คำของเขาในงานดูแลใจ) — "" = ไม่ได้เอ่ย
const DECIDER_WORD_RE = new RegExp(DECIDER, "iu");
const deciderOf = (t = "") => (DECIDER_WORD_RE.exec(t)?.[0] || "").replace(/^hr$/iu, "HR");
// รีวิวเคสจริงทั้งวัน 5 ต.ค. (รอบรีวิวสอง): ปรึกษาที่บ้าน/หัวหน้าเสร็จแล้วและได้คำตอบรับ ("ปรึกษาสามีแล้ว ตกลงเรียน" · "หัวหน้าอนุมัติแล้ว")
// เคยได้คำว่าไม่ต้องรีบแล้วจบ = ปล่อยคนที่พร้อมซื้อ — ได้คำตอบรับแล้ว = ไม่ใช่จังหวะรอ
const CARE_WAIT_DONE_RE = /อนุมัติแล้ว|(?<!ไม่)ตกลง|(?<!ไม่)โอเค|(?<!ไม่)ให้(?:มา)?เรียน|(?<!ไม่)เรียนได้|(?<!ไม่)ได้เลย|(?:^|\s)เอา(?=ค่ะ|คะ|ครับ|คับ|เลย|\s|$)/u;
const CARE_MAX_CHARS = 200;
/**
 * 12 ต.ค. 2026 (รีวิวตีจบแชทนอกเรื่อง): ข้อความนี้เป็นจังหวะดูแลใจ (ถูกกดดัน · ตกงาน/ป่วย/น้ำท่วม/สูญเสีย · รอคนตัดสินใจ) — pure
 * นิยามเดียวกับ careMomentOf ของ v3 แต่ไม่รวมด่านที่ขึ้นกับห้อง/ความยาว — ตัวตีจบนอกเรื่อง (offtopicClose.mjs) ไม่ทับจังหวะนี้
 * @returns {"pressure" | "crisis" | "waiting" | ""}
 */
export function careSignalOf(text = "") {
  const t = String(text ?? "");
  if (CARE_PRESSURE_RE.test(t)) return "pressure";
  if (careCrisis(t)) return "crisis";
  return CARE_WAITING_RE.test(t) && !CARE_WAIT_DONE_RE.test(t) ? "waiting" : "";
}
/** "crisis" · "pressure" · "waiting" · "" = ไม่ใช่ */
// รอบรีวิว 12 ต.ค. (ห้อง FB-fd7e6b8d): ได้ราคาไปแล้ว แล้วบอกว่า "แจ้งราคาไปยัง ผู้บริหารเพื่อพิจารณาก่อนครับ" — มีคำว่าราคา
// จึงเคยได้การ์ดราคาซ้ำ + ชวนเลือกรอบ = ห้องที่ได้ราคาแล้วพูดถึงการส่งต่อ/รอคนตัดสินใจ (ไม่ได้ถามราคาซ้ำ) คือจังหวะรอ ไม่ใช่ถามราคา
// คำขอให้เราส่งราคาอีกครั้ง ("ส่งราคาให้หน่อยครับ จะเอาไปเสนอหัวหน้า") = ส่งให้ ไม่ใช่จังหวะรอ (ชุดเดียวกับ priceDisclosure)
const waitingAfterPrice = (f, t) => Boolean(f.priceQuoted) && (FORWARD_TO_DECIDER_RE.test(t) || CARE_WAITING_RE.test(t)) && !PRICE_REASK.test(t)
  && !DISCOUNT_RE.test(t) && !PRICE_REQUEST_TO_US.test(t);
function careMomentOf(f, t) {
  const money = f.money && !waitingAfterPrice(f, t);
  if (!t || [...t].length > CARE_MAX_CHARS || money || ASKS_RE.test(t) || STILL_ASKING.test(t) || buyingWords(t) || ROUND_PICK_RE.test(t)) return "";
  if (CARE_PRESSURE_RE.test(t)) return "pressure";
  if (careCrisis(t)) return "crisis";
  if (CARE_WAITING_RE.test(t) && !CARE_WAIT_DONE_RE.test(t)) return "waiting";
  return "";
}
