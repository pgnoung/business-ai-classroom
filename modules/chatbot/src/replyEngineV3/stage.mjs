const CONFUSED_SHORT_CHARS = 40;
// ห้องร้อนตอบแค่คำปฏิเสธ ("ไม่ต้องการค่ะ" ต่อข้อเสนอเดียว / ต่อคำถามชวนเลือกรอบ) = ปฏิเสธสิ่งที่เสนอ ไม่ถามบังคับ ไม่เสนออย่างอื่นแทน
