const DECLINE_ONLY_RE = /^(?:ยัง|ตอนนี้|ช่วงนี้)?(?:ไม่(?:ค่อย)?สนใจ|ไม่ต้องการ|ไม่เอา|ไม่ต้อง|ยังไม่สนใจ|ยังไม่เอา)(?:แล้ว|ก่อน|ตอนนี้|เลย|ดีกว่า|ค่ะ|คะ|ค่า|ครับผม|ครับ|คับ|นะ|จ้า|ขอบคุณ(?:มาก)?|ขอบใจ|(?:เดี๋ยว|ไว้)?ค่อย(?:ทัก|มา|ติดต่อ|ถาม|ดู)(?:มา|ใหม่|อีกที)?|(?:เดี๋ยว|ไว้)?(?:ไป)?(?:ดู|อ่าน|หา)(?:ข้อมูล)?(?:ใน|ที่|จาก)?(?:เพจ|เว็บ|ไลน์|โพสต์)?เอง)*[.!…]*$/u;
const DECLINE_ONLY_EN = /^\s*(?:no\s*thanks?|no\s*thank\s*you|not\s+interested)\W*(?:ค่ะ|คะ|ครับ|คับ)?\s*$/iu;
// ห้องร้อนบอกว่าไม่สนใจ/ไม่ต้องการ โดยไม่ได้ถามอะไรและไม่มีเรื่องเรียนค้าง ("ไม่ต้องการค่ะ ขอบคุณสำหรับข้อมูลนะคะ") = ปฏิเสธแบบไม่ต้องตามขาย
function offerDeclined(f, t) {
  if (!hotRoomOf(f) || f.prevRole !== "assistant") return false;
  const bare = t.replace(EMOJI, "");
  const compact = bare.replace(/\s+/gu, "");
  if (DECLINE_ONLY_RE.test(compact) || DECLINE_ONLY_EN.test(bare)) return true;
  // คำปฏิเสธต้องปิดประโยค ("ไม่เรียนวันเสาร์" · "ไม่ต้องการให้โทร" · "ไม่สนใจคลาสพื้นฐาน" ไม่นับ) · ไม่ใช่คำของคนอื่น/สมัครไปแล้ว
  return NOT_INTERESTED_RE.test(compact) && !NEGATED_DECLINE_RE.test(compact) && !EXIT_REPORTED_RE.test(t) && !ENROLLED_RE.test(t)
    && !ASKS_RE.test(t) && !STILL_ASKING.test(t) && !EXIT_GUARD_RE.test(t) && !buyingWords(t) && [...t].length <= EXIT_MAX_CHARS;
}

// รีวิวเคสจริงทั้งวัน 5 ต.ค. (รอบรีวิวสอง): ห้องที่ได้ราคา/รอบแล้วบอกว่าไม่สนใจ "คลาสนี้" / "คอร์สนี้ไม่ใช่" / "ไม่ใช่คลาสที่หา"
// เคยได้คำขายคลาส (sales_offer) หรือคำถามชวนเลือกรอบหลังราคา — ปฏิเสธคลาสนั้น = รับคำเงียบ ๆ ไม่ขายต่อ ไม่ส่งรอบ ไม่บังคับถาม
// (บอกอีกคลาสได้หนึ่งประโยคเฉพาะตอนข้อเท็จจริงชี้ว่าอีกคลาสตรงกับเขา — ตัดสินใน turnFacts)
// ข้อความที่ยังอยากได้อีกคลาส ("สนใจอีกคลาสมากกว่า" / "เอา Workflow") หรือยังถามอยู่ = ไม่ใช่จังหวะนี้
const DECLINE_VERB = "ไม่(?:ค่อย)?(?:สนใจ|เอา|ต้องการ|เรียน|สมัคร|อยากเรียน)";
const THIS_CLASS = "(?:คลาส|คอร์ส)(?:เรียน)?(?:นี้|นี่|นั้น|ที่(?:แนะนำ|ว่า|ส่งมา))";
const NAMED_CLASS = "(?:คลาส|คอร์ส|ตัว)?(?:aiagent)?(?:for)?(?:business|workflow|automation|พื้นฐาน|ต่อยอด)";
const NOT_FIT = "(?:ไม่ใช่|ไม่ตอบโจทย์|ไม่เหมาะ|ไม่ตรง(?:กับ)?(?:ที่(?:หา|ต้องการ|อยาก)|โจทย์|ความต้องการ))";
const CLASS_DECLINE_RE = new RegExp(`${DECLINE_VERB}(?:${THIS_CLASS}|${NAMED_CLASS})|${THIS_CLASS}\\S{0,4}?${NOT_FIT}`
  + "|ไม่ใช่(?:คลาส|คอร์ส)ที่(?:หา|ต้องการ|อยาก)", "iu");
const WANTS_OTHER_CLASS_RE = /อีก(?:คลาส|คอร์ส|ตัว|อัน)|(?:คลาส|คอร์ส|ตัว|อัน)อื่น|แทน|มากกว่า|แต่|อยาก|ขอ(?:ข้อมูล|ดู|รายละเอียด|ทราบ)|(?<!ไม่(?:ค่อย)?)(?:สนใจ|เอา|เรียน)(?:คลาส|คอร์ส|ตัว)?(?:aiagent)?(?:for)?(?:business|workflow|automation|พื้นฐาน|ต่อยอด)/iu;
function classDeclined(f, t) {
  if (f.prevRole !== "assistant" || !t || [...t].length > EXIT_MAX_CHARS || f.money) return false;
  const compact = t.replace(EMOJI, "").replace(/\s+/gu, "").toLowerCase();
  if (!CLASS_DECLINE_RE.test(compact) || NEGATED_DECLINE_RE.test(compact) || EXIT_REPORTED_RE.test(t) || ENROLLED_RE.test(t)) return false;
  return !WANTS_OTHER_CLASS_RE.test(compact) && !ASKS_RE.test(t) && !STILL_ASKING.test(t) && !buyingWords(t) && !ROUND_PICK_RE.test(t);
}

// ลำดับเดียวกับ §C ทุกบรรทัด (สาขาแรกที่ตรงชนะ)
// concern = ข้อกังวลของเทิร์น · pick = ลูกค้าเลือกรอบเอง · enroll = ลูกค้าเลือกรอบหรือถามวิธีสมัครเอง
function decideCore(f, { concern = concernOf(f), pick = false, enroll = false } = {}) {
  const t = String(f.text || "");
  const quote = f.disclosure?.mode === "quote";
  // รีวิวเคสจริง 5 ต.ค.: คนที่บอกว่าจะสมัคร/เลือกรอบแล้ว ห้ามตกไปเป็นข้อกังวล (เงินตึงยังใส่ money_hardship ให้ดูแลใจ)
  const worry = enroll ? null : concern;
  // ตัวจับลังเลของเครื่องเดิมนับ "คุ้มจริง" เป็นลังเล — "คุ้มจริงครับ สนใจครับ" (คำชม + คำพร้อมซื้อ ไม่มีความสงสัย) ไม่ใช่ข้อกังวล
  const hesitates = f.hesitates && !(buyingWords(t) && !REAL_DOUBT_RE.test(t));
  const mods = [];
  if (f.burstCount > 1) mods.push("burst");
  if (f.fatigue) mods.push("fatigue");
  if (f.scheduleCheck) mods.push("schedule_check");
  // รีวิวเคสจริงทั้งวัน 5 ต.ค. (ห้อง LINE ช่วงค่ำ): ข้อความนี้มาระหว่างที่คำตอบก่อนหน้ากำลังทยอยส่ง — บอกโมเดลว่าลูกค้าเห็นอะไรไปแล้ว
  if (f.overlap) mods.push("overlap");
  // เคสจริง 5 ต.ค.: "ลูกแพรไม่อยากให้ฝืนงบ" แล้วยังชวนดูรอบ — เงินตึง/ต้องยืมเงิน = เทิร์นนี้ไม่ชวนดูรอบ จอง หรือราคา
  if (concern?.hardship) mods.push("money_hardship");
  // รีวิวเคสจริงทั้งวัน 5 ต.ค.: เงียบหลังลา / ปิดอย่างสุภาพ ชนะทุกจังหวะ (ทักแรก บันได ราคา) — ตัวจับทั้งสองกันข้อความที่ยังถามหรือยังสนใจไว้แล้ว
  if (silentAfterFarewell({ ...f, text: t })) return decision("SILENT", "ack_after_farewell", mods);
  const exit = exitReasonOf(f);
  if (exit) return decision("EXIT", exit, mods, { exit });
  // รีวิวเคสจริงทั้งวัน 5 ต.ค. (รอบรีวิว): บ่นว่าค่าเรียนไม่ไหว/เกินกำลังโดยไม่ได้ขอผ่าน = ข้อกังวลเรื่องงบแบบดูแลใจ (ไม่ใช่ปิดห้อง
  // ไม่ใช่การ์ดราคาซ้ำ และไม่ใช่คำถามชวนเลือกรอบ) · มาคนเดียวแล้วไม่ไหว = บอกทางมาเป็นคู่ได้ถ้ามีดีลที่อนุมัติ
  const budget = budgetDeclineOf(f);
  if (budget) return decision("OBJECTION", "budget", mods, { softDecline: true, ...(budget.alone ? { alone: true } : {}) });
  // continuity จากข้อความที่ส่งจริงล่าสุด: รับคำแบบ compound ได้แม้ไม่มี assistant เป็นแถวสุดท้าย
  // แต่คำปฏิเสธ/ขอคิด/กังวลถูกตัดตั้งแต่ normalize และ concern ยังชนะตามเดิม
  // คำขอข้อมูลที่ระบุชนิดชัด (เช่น ยังไม่พร้อมสมัคร แต่ขอดูรีวิว) เดินหน้าส่งข้อมูลนั้นได้
  // โดยไม่เลื่อนเป็นการสมัคร; offer สมัคร/รอบ/คลาสยังคงถูก pause/concern guard เดิมกันไว้
  const informationalOffer = ["review", "content", "other"].includes(f.pendingOffer?.type);
  if (f.pendingOffer?.accepted && (informationalOffer || !enrollDoubt(f, t, concern)) && !DISCOUNT_RE.test(t)) {
    if (f.pendingOffer.type === "registration") return decision("LOGISTICS", "accepted_enroll_offer", mods, { logistics: "booking" });
    if (f.pendingOffer.type === "rounds") return decision("LOGISTICS", "accepted_rounds_offer", mods, { logistics: "rounds" });
    if (f.pendingOffer.type === "review") return decision("REASSURE", "accepted_review_offer", mods);
    if (f.pendingOffer.type === "class") return decision("BRIDGE", "accepted_class_offer", mods, { offer: contextOfferText(f.pendingOffer) });
    return decision("DELIVER", "accepted_offer", mods, { offer: contextOfferText(f.pendingOffer) });
  }
  // รีวิวเคสจริงทั้งวัน 5 ต.ค.: ถามราคาข้อความแรกได้ "ทักแรก" (เหตุผลยาว + บันได) ส่วนถามทีหลังได้ "ขอพื้นฐานก่อนราคา" — คำตัดสินราคาเดียวกัน
  // ต้องได้สคริปต์เดียวกัน จึงตรวจขอพื้นฐานก่อนทักแรก · บันไดครบ (เมนู + รูป) เฉพาะตอนยังไม่รู้ระดับเลยและยังคุยไม่เกินสองเทิร์น
  // (เคสจริง: คนที่ตอบว่าเคยใช้นิดหน่อย / "ยัง" ไปแล้วได้เมนู 5 ระดับ + รูปซ้ำ · ห้องที่คุยมาเจ็ดเทิร์นได้เมนูยาวแทนราคา)
  // พี่ง้วง 12 ต.ค.: ข้อความแรกบอกว่าจะสมัคร = ไม่ส่งบันได (เมนู + รูป) — ถามราคามาด้วยยังแบ่งรับตามเดิม ด้วยคำถามคัดกรองข้อเดียว
  // พี่ง้วง 12 ต.ค. (ข้อ 6): คนที่รู้จักแล้ว (ตอบบันได/บอกชื่อ/scorer อ่านโจทย์ออก) ถามราคาตรง ๆ ครั้งแรก = แบ่งรับด้วยคุณค่า
  // จังหวะเดียวกับการขอพื้นฐานก่อนบอกค่าเรียน (คำถามข้อเดียว + บอกว่าตอบแล้วแจ้งทันที — ด่านหลังร่างเติมให้ถ้าขาด) แต่งานของเทิร์นต่างกัน:
  // บอกว่าได้อะไร/คุ้มยังไงผูกกับเป้าหมายของเขา ไม่ถามสิ่งที่เขาตอบไปแล้ว (stageTasks: hedgeValueMove/hedgeQuestion) · ยังไม่รู้ระดับเลย = บันไดเหมือนเดิม
  // คำตัดสินแบ่งรับมาจาก turnFacts (priceDisclosure.withValueHedge) — เฉพาะเทิร์นที่ v3 เขียน
  const valueHedge = f.disclosure?.mode === "defer" && f.disclosure?.reason === "defer_known_value_hedge";
  if (f.disclosure?.mode === "defer" && (f.disclosure?.reason === "defer_cold_stranger_screening" || valueHedge)) {
    return decision("SCREEN_PRICE", valueHedge ? "value_hedge" : "defer_screening", mods, {
      ladder: f.routing.level === null && !f.impliedLevel && !f.ladderShown && !f.enrollOpening && f.allowedImages.has("ai-stage-ladder")
        && (f.userTurns ?? 1) <= SCREEN_LADDER_MAX_USER_TURNS && !f.serviceTopic,
      // scorer อ่านว่าพร้อมแล้ว = แบ่งรับสั้นลง คำถามเบาที่สุด (ความยาวของงานอ่านธงนี้ — ถ้อยคำอ่าน facts.priceRead เอง)
      ...(valueHedge ? { hedge: true, ...(f.priceRead?.readiness === "ready" ? { hedgeReady: true } : {}) } : {}),
    });
  }
  // ladderSkip = ข้อความแรกบอกระดับเป็นนัยแล้ว / งงคำถามในโฆษณา / ห้องเคยได้ราคาแล้ว (ตัดสินใน turnFacts)
  // feedback ทีม 10 ต.ค.: ตอบ "ยัง/ไม่เคย" ต่อคำถามโฆษณาเรื่อง AI Agent = รับคำตอบ แล้วถามพื้นฐานการใช้ AI ทั่วไปด้วยบันได (ไม่สรุปว่าไม่เคยใช้ AI)
  // พี่ง้วง 12 ต.ค. (แชทจริง 11 ต.ค.: "จะสมัครเรียน" ต้องผ่านบันไดและการขออนุญาต 4 ครั้งกว่าจะได้ราคา): ข้อความเปิดห้องที่บอกว่าจะสมัคร
  // = ไม่ส่งบันได (แม้จะตอบ "ยัง" ต่อคำถามในโฆษณามาด้วย) — บอกว่าคลาสดียังไง แล้วพาไปรอบ/ขั้นสมัครของคลาสที่ใช่ (ตัดสินใน turnFacts)
  // รอบรีวิว 12 ต.ค.: ข้อความเปิดห้องบอกรอบมาด้วย ("สมัครเรียนค่ะ รอบ 31 ต.ค.") เคยถูกถามซ้ำว่าสะดวกรอบไหน — รอบนั้นเปิดอยู่ = รับรอบแล้วไปขั้นสมัคร
  // · วันที่ที่ไม่ใช่รอบที่เปิด (เต็ม/รอบของอีกคลาส/ไม่มีรอบ) = บอกตามจริงพร้อมรอบที่ใกล้ที่สุด (จังหวะถามวันที่เดิม)
  if (f.enrollOpening && (f.enrollRound || f.requestedDate?.status === "open")) {
    return decision("LOGISTICS", "enroll_opening_round", mods, { logistics: "booking", enrollOpening: true });
  }
  if (f.enrollOpening && f.requestedDate) return decision("LOGISTICS", "date_ask", mods, { logistics: "date", enrollOpening: true });
  if (f.enrollOpening) return decision("BRIDGE", "enroll_opening", mods, { enrollOpening: true });
  if (f.agentLadder) return decision("FIRST_CONTACT", "agent_opening", mods);
  if (f.ladderRule && !f.ladderSkip) return decision("FIRST_CONTACT", "ladder_rule", mods);
  // งงคำถามต้อนรับในโฆษณา = ขอโทษ อธิบายสั้น ตอบสิ่งที่ถาม แล้วถามง่าย ๆ ข้อเดียว (เคสจริง: ได้บันไดแทนคำตอบ คำตอบจริงมาจากข้อความทักตาม 70 นาทีถัดมา)
  if (f.confusedOpening) return decision("REASSURE", "confused_opening", mods);
  if (isGoodbye(f, t)) return decision("GOODBYE", "closing_words", mods);
  if (burstGoodbye(f)) return decision("GOODBYE", "closing_words_last_bubble", mods);
  const care = careMomentOf(f, t.trim());
  // รอคนตัดสินใจ = บอกงานด้วยคำของลูกค้าว่ารอใคร ("ผู้บริหาร" · "หัวหน้า") เพื่อรับคำอย่างเข้าใจและเสนอสรุปไว้ส่งต่อ
  if (care) return decision("GOODBYE", "care_moment", mods, { care, ...(care === "waiting" && deciderOf(t) ? { decider: deciderOf(t) } : {}) });
  // ตรวจคิว 13 ต.ค.: ทีมงานคนจริงเพิ่งดูแลห้องนี้ แล้วลูกค้าทักสั้น ๆ (สวัสดี/ขอบคุณ/ได้ค่ะ) = ทักกลับและถามว่ามีอะไรให้ช่วยต่อ ไม่ขาย
  if (f.adminRecent && !f.money && [...t.trim()].length <= ADMIN_ROOM_SHORT && !/[?？]/u.test(t)) return decision("DISCOVERY", "admin_room", mods);
  if (classDeclined(f, t)) return decision("OBJECTION", "undecided", mods, { offerDeclined: true, classDeclined: true });
  // รีวิวเคสจริงทั้งวัน 5 ต.ค. (รอบรีวิวสอง): กลางห้องที่ได้ราคา/รอบแล้ว หรือมีคำถามค้าง แล้วบอกว่า "แค่กดดูเฉย ๆ" เคยได้คำถามชวนเลือกรอบ
  // = รับคำว่าดูก่อนได้ ไม่ต้องรีบ ไม่ขายต่อ (ห้องที่ไม่มีอะไรค้างและยังไม่ได้ราคา = ปิดอย่างสุภาพตามเดิม)
  if (f.prevRole === "assistant" && BROWSING_RE.test(t) && !buyingWords(t) && !ASKS_RE.test(t) && (hotRoomOf(f) || pendingQuestion(f))) {
    return decision("OBJECTION", "undecided", mods, { notReady: true });
  }
  const hotRoom = Boolean(f.priceQuoted || f.roundsSent);
  // รีวิวเคสจริงทั้งวัน 5 ต.ค. (รอบรีวิว): ห้องร้อนถามว่าใครทักมา/ทักมาทำไม = ตอบตามจริงตรง ๆ แบบไม่ถาม (ไม่ปิดห้อง ไม่เชื่อมเข้าคลาส ไม่ชวนเลือกรอบ)
  if (hotRoom && WHO_ASK_RE.test(t) && !TRUST_ASK_RE.test(t) && !WHO_CURIOUS_RE.test(t) && !f.money) {
    return decision("LOGISTICS", "after_price", mods.includes("fatigue") ? mods : [...mods, "fatigue"], { logistics: "next", whoAsk: true });
  }
  if (hotRoom && CONFUSED_RE.test(t) && !AI_TERM_RE.test(t) && [...t.trim()].length <= CONFUSED_SHORT_CHARS) {
    return decision("REASSURE", "confused_after_price", mods);
  }
  // ตรวจทีละบรรทัด: ลูกค้าพิมพ์หลายบรรทัดในข้อความเดียว ("ยังค่ะ / หมายถึง AI ตัวอื่น")
  if (f.prevRole === "assistant" && f.parts.some((part) => String(part).split(/\n+/u).some((line) => MISREAD_RE.test(line.trim())))) {
    return decision("MISREAD", "customer_correction", mods);
  }
  // คำสั่งพี่ง้วง 10 ต.ค.: รับข้อเสนอส่งรายละเอียดการสมัคร = ด่านราคาเปิด (quote_accepted_offer) — ขั้นสมัครของเครื่องเดิมแจ้งค่าเรียน
  // พร้อมขั้นตอนสมัครในข้อความเดียว จึงต้องตัดสินก่อนจังหวะราคา/ดีลคู่ (ไม่งั้นได้การ์ดราคาแล้ววนเสนอส่งรายละเอียดการสมัครอีก)
  // ตัวอ่านคำรับตัวเดียวกับด่านราคา (registrationOffer.mjs) · เลือกรอบในข้อความนี้ / ขอส่วนลด = ตามจังหวะของมัน
  const contextEnroll = f.pendingOffer?.accepted && f.pendingOffer.type === "registration"
    ? contextOfferText(f.pendingOffer) : "";
  const enrollAsk = contextEnroll || (f.prevRole === "assistant" ? acceptedRegistrationOffer({ text: t, lastBotText: f.lastBotText }) : "");
  if (enrollAsk && !pick && enrollOfferForRound(enrollAsk, f) && !f.inboundFlags.includes("asks_discount") && !DISCOUNT_RE.test(t)
    && !enrollDoubt(f, t, concern)) {
    return decision("LOGISTICS", "accepted_enroll_offer", mods, { logistics: "booking" });
  }
  if (quote && f.money && (f.inboundFlags.includes("asks_discount") || DISCOUNT_RE.test(t))) {
    return decision([2, 3].includes(f.routing.headcount) ? "DEAL_PAIR" : "DEAL_SINGLE", "discount_ask", mods);
  }
  if (quote && f.money && [2, 3].includes(f.routing.headcount)) return decision("DEAL_PAIR", "group_price_ask", mods);
  // บ่นแพง/เกินงบ/กังวลหลังได้ราคาไปแล้ว = ข้อกังวล ไม่ใช่การถามราคาซ้ำ (เดิมตกสาขา PRICE เพราะ "แพง" นับเป็นคำเรื่องเงิน)
  if (quote && f.priceQuoted && (OBJECTION_RE.test(t) || worry) && !PRICE_REASK.test(t) && !pick) return decision("OBJECTION", objectionType(t), mods);
  // ราคาค้างจ่ายแต่ลูกค้าเพิ่งเล่าว่าเงินตึง = ดูแลใจก่อน (ถามราคาเองยังได้ราคา)
  const owedNow = quote && !f.money && f.disclosure.owed && !concern?.hardship;
  // ข้อ 6 รอบรีวิว 2 (HIGH): ตอบคำถามแบ่งรับว่ามากันสองสามท่าน ("2 คนค่ะ") = ราคาที่ค้างมาพร้อมดีลคู่ (ช่อง {{ดีล}} มีราคาปกติก่อน แล้วจึงราคาคู่)
  // — เดิมได้การ์ดคนเดียว ดีลคู่หาย ต้องถามซ้ำเป็นครั้งที่สาม · ไม่มีดีลคู่ที่อนุมัติ/ไม่รู้คลาส = การ์ดราคาตามเดิม
  if (owedNow && [2, 3].includes(f.routing.headcount) && f.pairDealAvailable === true) return decision("DEAL_PAIR", "price_owed", mods);
  if (quote && (f.money || owedNow)) return decision("PRICE", f.money ? "money_ask" : "price_owed", mods);
  // ลูกค้าตอบคำถามชวนเลือกรอบ ("รอบ 24 ค่ะ") = รับรอบแล้ว → ก้าวสมัคร (ตรวจซ้ำเคสจริง 5 ต.ค.: เคยเป็น BRIDGE/goal แล้วโดนชวนดูหัวข้อ)
  if (pick) return decision("LOGISTICS", "accepted_round_pick", mods, { logistics: "booking" });
  // feedback ทีม 10 ต.ค.: เลือกรอบไว้แล้วบอกว่าจะสมัคร/ถามวิธีสมัคร ("สมัครเลยค่ะ") เคยได้คำชวนเลือกรอบซ้ำ = ขั้นสมัครของเครื่องเดิม
  if (enroll && f.pickedRound && !enrollDoubt(f, t, concern)) return decision("LOGISTICS", "enroll_after_pick", mods, { logistics: "booking" });
  // รีวิวเคสจริงทั้งวัน 5 ต.ค.: ถามว่าวันเสาร์ที่… มีเรียนไหม (วันนั้นเป็นรอบของอีกคลาส) ได้ข้อเสนอดูหัวข้อ และบอกผิดว่าวันนั้นไม่มีรอบเลย
  // — ถามวันที่ = ตอบเรื่องรอบของวันนั้นตามข้อเท็จจริง (เงินตึงยังดูแลใจก่อน)
  if (f.requestedDate && !concern?.hardship) return decision("LOGISTICS", "date_ask", mods, { logistics: "date" });
  if (f.roundDayAsked && !f.requestedDate && !concern?.hardship) return decision("LOGISTICS", "logistics", mods, { logistics: "rounds" });
  if (offerDeclined(f, t)) return decision("OBJECTION", objectionType(t), mods, { offerDeclined: true });
  if ((NOT_READY_RE.test(t) || (NOT_DECIDED_RE.test(t) && !ASKS_RE.test(t))) && !buyingWords(t) && !concern?.hardship && !f.money) return decision("OBJECTION", "undecided", mods, { notReady: true });
  // มีประโยคข้อเสนอ = อ่านจากประโยคนั้นประโยคเดียว (ก้อนเต็มอาจมีคำว่า รอบ/คลาส ในเรื่องอื่น)
  const { offer, accepted } = acceptanceOf(f);
  const precise = Boolean(accepted) && accepted === offer;
  const offerExtra = precise ? { offer } : {};
  // ไม่มีประโยคข้อเสนอแบบ "ให้ลูกแพร…" ("ต้องการสมัครรอบเสาร์ 17 ต.ค. ที่เลือกไว้เลยไหมคะ?") = อ่านจากคำถามใช่/ไม่ใช่ข้อสุดท้ายของก้อนเท่านั้น
  if (accepted && /รอบ/u.test(accepted)) return decision("LOGISTICS", "accepted_rounds_offer", mods, { logistics: "rounds" });
  // พี่ง้วง 13 ต.ค.: ไม่มีประโยคข้อเสนอ = accepted คือทั้งก้อน — คำว่า "รีวิว" ในประโยคแนะนำรีวิวข้างเคียงเคยทำให้รับข้อเสนอส่งหัวข้อกลายเป็นคำปลอบใจ
  if (precise && /รีวิว/u.test(accepted)) return decision("REASSURE", "accepted_review_offer", mods);
  if (precise && ACCEPTED_CONTENT.test(accepted)) return decision("DELIVER", "accepted_offer", mods, offerExtra);
  if (precise && ACCEPTED_CLASS.test(accepted)) return decision("BRIDGE", "accepted_class_offer", mods, offerExtra);
  if ((accepted && /เช็ก?ค?ลิสต์|รายการ|ตัวอย่าง|ขั้นตอน/u.test(accepted)) || DELIVER_RE.test(t)) {
    return decision("DELIVER", "list_request", mods, offerExtra);
  }
  // รับข้อเสนออื่นของลูกแพร (ร่าง/สรุป/ดูให้/แนะนำจุดปรับ) = ทำสิ่งที่เสนอเลย ไม่ถามซ้ำ
  if (precise) return decision("DELIVER", "accepted_offer", mods, offerExtra);
  // ตรวจคิว 13 ต.ค.: ลูกค้าตอบคำถามแบบให้เลือกที่ลูกแพรเสนอเอง ("อยากเริ่มตั้งค่าจาก Claude หรือ ChatGPT ก่อนคะ?" → "เริ่มที่ Claude ก่อนครับ"
  // · "อยากเห็นตัวอย่างฝั่งไหนก่อนคะ?" → "อยากเห็นทั้งสองแบบ" · "วางน้ำเสียง หรือทำสคริปต์ก่อนคะ?" → "น้ำเสียง") เคยได้คำขายคลาส
  // + ขออนุญาตส่งหัวข้อ = ส่ง/อธิบายสิ่งที่เขาเลือกเลย
  const choice = choicePickOf(f, t);
  if (choice) return decision("DELIVER", "choice_pick", mods, { ask: choice });
  // ข้อกังวล (เงิน/รับไม่ไหว/คุ้มไหม) ชนะสอบถามข้อมูล แนวคิด และตัวจับ BRIDGE ทุกตัว (สอนในแชท/ขายของ/รายได้/คุยลึก)
  if (OBJECTION_RE.test(t) || hesitates || worry) return decision("OBJECTION", objectionType(t), mods);
  // ตรวจคิว 13 ต.ค.: ขอเองว่า "ส่งคอร์สเรียนมาดูหน่อย" · "ในคลาสมีอะไร ผมจะได้อะไรบ้าง" เคยได้ "ขออนุญาตส่งหัวข้อ…ไหมคะ?" กลับ = ส่งเลย
  if (!f.firstReply && CONTENT_ASK_RE.test(t)) return decision("DELIVER", "content_ask", mods, { ask: CONTENT_ASK_TASK });
  if (LOGISTICS_RE.test(t) || f.scheduleCheck) {
    return decision("LOGISTICS", "logistics", mods, { logistics: /วันไหน|วัน\S{0,3}?อื่น|รอบ|ตาราง/u.test(t) || f.scheduleCheck ? "rounds" : "other" });
  }
  if (CONCEPT_RE.test(t)) return decision("CONCEPT", "concept_question", mods);
  const low = Boolean(f.confidence || LOWCONF_RE.test(t) || (f.openingShortAnswer && f.focus?.negative));
  // ถามวิธีสมัครเอง ("สมัครยังไงคะ") = เชื่อมเข้าคลาสพร้อมก้าวสมัคร ไม่ใช่ทำความรู้จักต่อ
  // รีวิวเคสจริงทั้งวัน 5 ต.ค.: คำตอบเปิดห้อง (ยัง + ทำไม่เป็น) เข้าตัวเบรกการสอน (รูป "ทำไม่เป็น") แล้วได้คำขายคลาสยาวเป็นข้อความแรก
  // — คำตอบของคำถามต้อนรับคือการบอกระดับ ไม่ใช่การขอให้สอนในแชท
  // คำถามสั้นที่อ้างย้อนถึงหัวข้อธุรกิจซึ่งลูกแพรเพิ่งพูด ไม่ใช่การขอให้สอนเรื่องทั่วไปฟรี
  // ให้จังหวะปกติตอบหัวข้อนั้นก่อน แทนการบังคับสะพานไปคลาสเสียเงินอีกครั้ง
  const directBusinessAnswer = f.businessTopicFollowup || f.trialLinkRequested;
  const brake = f.coachingBrake && !f.openingAnswer && !directBusinessAnswer;
  // หัวข้อธุรกิจที่ลูกแพรเพิ่งเสนอเองต้องได้คำตอบก่อน แม้ห้องจะถึงเพดาน discovery/มี goal แล้ว
  // มิฉะนั้นคำถาม “ถ้ามี ต้องเริ่มจากตรงไหน” จะถูกบังคับกลับไปเสนอคลาสเสียเงินซ้ำ
  if (directBusinessAnswer) return decision("DISCOVERY", "default", mods);
  // รีวิวเคสจริงทั้งวัน 5 ต.ค.: หลังแจ้งราคา/ส่งรอบแล้ว ห้ามถอยกลับไปทำความรู้จัก (ห้องที่ได้ราคา + ชวนเลือกรอบ ตอบสั้นกำกวม แล้วโดนถามเรื่องงานซ้ำ)
  // ตัวนับความลึก/เพดานคำถามไม่เชื่อมเข้าคลาสซ้ำหลังราคา (ขายไปแล้ว) — พื้นหลังราคาข้างล่างพาไปก้าวถัดไปแทน
  const hot = Boolean(f.priceQuoted || f.roundsSent);
  const depthReached = !hot && (f.routing.level ?? f.impliedLevel?.level ?? null) !== null && f.discoveryDepth >= 2;
  // รีวิวเคสจริงทั้งวัน 5 ต.ค.: ห้องร้อนตอบระดับเป็นช่วงที่อ่านไม่ออก ตัวนับความลึกเลยไม่ทำงาน ถูกถามทำความรู้จักติดกันสี่ข้อ
  // — ถามได้ไม่เกินสองข้อติด (นับได้แม้ไม่รู้ระดับ) แล้วเชื่อมเข้าคลาส
  const capReached = !hot && (f.discoveryStreak || 0) >= DISCOVERY_STREAK_CAP;
  // คนทำเล่นเพื่อความสนุกที่ตอบปฏิเสธสั้น ๆ ว่าไม่มีงานจะใช้ = ไม่เชื่อมเข้าคลาสตามตัวนับ (ลูกแพรไม่ขายคนที่บอกชัดว่าไม่ได้มาซื้อ)
  // รีวิวเคสจริงทั้งวัน 5 ต.ค. (รอบรีวิว): "เป็นนักศึกษา ยังไม่ได้ทำงาน" · "ใช้ถามสูตรอาหาร ไม่ได้ใช้ทำงาน" · "เป็นแม่บ้าน ไม่ได้ทำธุรกิจ" ได้คำขายคลาส
  // (เพดานคำถาม/ตัวเบรกการสอน/ตัวอ่านเป้าหมาย) — บอกเองว่าไม่ได้ใช้ทำงาน = ไม่เชื่อมเข้าคลาสด้วยเหตุพวกนี้ (บอกว่าอยากเรียนจริงจังยังเชื่อมได้)
  const held = f.hobbyNoWork === true && Boolean(pendingQuestion(f)) && (depthReached || capReached || brake || f.goalFresh);
  const bridge = (brake && !held) ? "coaching_brake" : (f.goalFresh && !held) ? "goal" : (COMMIT_RE.test(t) || enroll) ? "commitment"
    : INCOME_RE.test(t) ? "income" : f.sales?.stage === "offer" ? "sales_offer"
      // รีวิวเคสจริงทั้งวัน 5 ต.ค. (ห้อง LINE ช่วงค่ำ): คำตอบ BRIDGE ก่อนหน้าถูกหยุดกลางชุดเพราะลูกค้าพิมพ์แทรก = เทิร์นนี้ส่งส่วนที่เหลือต่อ
      // (ห้องจริงถอยไปถามทำความรู้จักใหม่ ชื่อคลาสกับข้อเสนอที่ยังไม่ได้ส่งหายไป)
      : (f.overlap?.cut && f.overlap.stage === "BRIDGE") ? "resume_cut"
        // รีวิวเคสจริงทั้งวัน 5 ต.ค.: ระดับที่บอกเป็นนัยในข้อความแรก (ตอบว่าใช้อยู่ และสนใจ AI อีกตัวด้วย) นับเป็นระดับที่รู้แล้ว (เคยได้คำถามสำรวจ 4–5 ข้อติดกัน)
        : (depthReached && !held) ? "discovery_depth"
          : (!low && taskQuestionPending(f) && (TASK_ANSWER_RE.test(t) || TASK_ALL_ANSWER_RE.test(t)) && !Number.isInteger(f.answeredLevel)) ? "task_answered"
            : (capReached && !held) ? "discovery_cap" : null;
  // feedback ทีม 10 ต.ค. (แชทจริง 3–10 ต.ค.: 55 จาก 123 ห้องที่เชื่อมเข้าคลาสเชื่อมตั้งแต่คำตอบแรกหรือที่สอง): ตอบแค่หมวดงานจากตัวเลือก
  // ("งานขายครับ" · "คอนเทน" + "ขาย") เคยได้คำขายคลาส + ข้อเสนอส่งรอบทันที — ยังไม่รู้ว่าทำธุรกิจอะไร/อยากให้ AI ช่วยส่วนไหน
  // = ถามเจาะอีกหนึ่งข้อก่อน (เพดานคำถามสองข้อติดยังคุม: ตอบข้อเจาะแล้วเชื่อมเข้าคลาสเสมอ)
  if (["goal", "task_answered"].includes(bridge) && f.bareTaskPick && !hot && !capReached && !enroll && !COMMIT_RE.test(t)) {
    return decision("DISCOVERY", "dig", mods);
  }
  if (bridge) {
    if (low) mods.push("reassure");
    return decision("BRIDGE", bridge, mods);
  }
  if (low) return decision("REASSURE", "low_confidence", mods);
  if (hot) {
    // รีวิวเคสจริงทั้งวัน 5 ต.ค.: ลูกค้าบ่นว่าถูกถามหลายข้อ/คุยไม่รู้เรื่อง แล้วถามว่าคนหรือบอทตอบ (หลังได้ราคาแล้ว) — ก้าวถัดไปห้ามเป็นคำถามชวนเลือกรอบ
    // ตัวจับบ่นของเครื่องเดิมไม่เห็นรูปนี้ → ใส่ตัวปรับถูกถามเยอะเอง: ขอโทษสั้น ๆ ตอบตรง (ธรรมนูญ: ถามว่าคนหรือบอท = บอกตามจริง) ไม่ถาม
    // รีวิวเคสจริงทั้งวัน 5 ต.ค. (รอบรีวิว): ห้องร้อนถามว่าใครทักมา/ทักมาทำไม = ตอบตามจริงตรง ๆ แบบไม่ถาม (ไม่ปิดห้อง ไม่ชวนเลือกรอบ)
    if (!mods.includes("fatigue") && (FRUSTRATION_RE.test(t) || FRUSTRATION_RE.test(String(f.prevUserText || "")) || (WHO_ASK_RE.test(t) && !TRUST_ASK_RE.test(t) && !WHO_CURIOUS_RE.test(t)))) mods.push("fatigue");
    return decision("LOGISTICS", "after_price", mods, { logistics: "next" });
  }
  if (held) return decision("DISCOVERY", "no_work_use", mods);
  // แชทจริง 13 ต.ค.: รู้งานแล้ว และเคยถามข้อ "งานไหนทำซ้ำ/กินเวลา" ไปแล้ว — ทำความรู้จักต่อ = คำถามเดิมรอบที่สาม → เชื่อมเข้าคลาสแทน
  if (f.goal && taskQuestionAnsweredBefore(f)) return decision("BRIDGE", "task_answered", mods);
  return decision("DISCOVERY", "default", mods);
}

