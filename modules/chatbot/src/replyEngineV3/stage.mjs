const DETAILS_ASK_ALL = new RegExp(DETAILS_ASK_RE.source, "giu");
// ถามคลาสออนไลน์ = ข้อมูลคลาสสอนสดไม่ใช่คำตอบ (เลนคลาสออนไลน์ของเครื่องเดิมรับช่วง) — ไม่ใส่ตัวปรับ details
// ตรวจคิว 13 ต.ค.: พิมพ์ "ออนไลน" / "ออนไล" (ไม่มีการันต์) หลุดจากเลนคลาสออนไลน์ → v3 ตอบว่ามีแต่เรียนสด
const ONLINE_ASK_RE = /ออนไล|ออนลาย|online|ย้อนหลัง/iu;
const DETAILS_STAGES = new Set(["FIRST_CONTACT", "SCREEN_PRICE"]);
function turnModifiers(core, f) {
  const extra = [];
  if (f.firstReply && !NO_INTRO_STAGES.has(core.stage)) extra.push("intro");
  // ข้อความแรกที่ขอรายละเอียด = งานของเทิร์นมีข้อมูลคลาสเองแล้ว (แทนขั้น "ตอบก่อน" ที่ออกมาเป็นประโยคเดียว)
  const details = f.firstReply && DETAILS_STAGES.has(core.stage) && (core.stage === "FIRST_CONTACT" || core.ladder)
    && DETAILS_ASK_RE.test(String(f.text || "")) && !ONLINE_ASK_RE.test(String(f.text || ""));
  if (details) extra.push("details");
  const counted = core.stage === "BRIDGE" && COUNTED_BRIDGES.has(core.reason);
  // ถามเรื่องอื่นมาด้วย ("ขอรายละเอียดหน่อย ต้องมีพื้นฐานไหม") = ยังตอบข้อนั้นก่อน (ท่อนขอรายละเอียดไม่นับเป็นคำถามซ้ำ)
  const asked = details ? String(f.text || "").replace(DETAILS_ASK_ALL, " ") : f.text;
  // พี่ง้วง 12 ต.ค.: ข้อความแรกบอกว่าจะสมัคร แล้วถามอะไรมาด้วย = ตอบข้อนั้นก่อนเหมือนทักแรก
  // (ข้อความเปิดห้องที่บอกรอบ/ถามวันที่มาด้วย มีขั้นตอบเรื่องรอบในงานอยู่แล้ว)
  const opening = Boolean(core.enrollOpening) && core.stage === "BRIDGE";
  if ((ANSWER_FIRST_STAGES.has(core.stage) || counted || opening) && (asksNonMoney(asked) || f.trialLinkRequested)) extra.push("answer_first");
  return extra.length ? { ...core, modifiers: [...(core.modifiers || []), ...extra] } : core;
}

const AFTER_PRICE_STAGES = new Set(["REASSURE", "CONCEPT", "MISREAD"]);
export function decideStage(f) {
  const concern = concernOf(f);
  const pick = roundPickOf(f);
  const enroll = pick || ENROLL_RE.test(String(f.text || ""));
  const core = {
    ...turnModifiers(decideCore(f, { concern, pick, enroll }), f),
    // ป้ายของเทิร์น (ตัวเลือกปิดท้าย + ด่านหลังร่างใช้): enroll = เลือกรอบ/ถามวิธีสมัครเอง · roundPick = เลือกรอบแล้ว
    // · paymentAsk = ถามวิธีจ่ายเอง (เงินตึงแต่ถามผ่อน = คำตอบเรื่องผ่อนต้องอยู่ครบ) · buying = พร้อมซื้อเทิร์นนี้
    ...(enroll ? { enroll: true } : {}), ...(pick ? { roundPick: true } : {}), ...(concern?.paymentAsk ? { paymentAsk: true } : {}),
  };
  // รีวิวเคสจริงทั้งวัน 5 ต.ค.: หลังแจ้งราคา/ส่งรอบ คำถามแนวคิด/ข้อความให้กำลังใจ/แก้ความเข้าใจ ยังตอบตามจังหวะเดิม แต่ปิดท้ายด้วยก้าวถัดไป
  // (เดิมงานของจังหวะพวกนี้ปิดด้วยคำถามเรื่องงาน = ถอยกลับไปทำความรู้จัก)
  const afterPrice = Boolean(f.priceQuoted || f.roundsSent) && AFTER_PRICE_STAGES.has(core.stage) && core.reason !== "confused_after_price";
  const base = afterPrice ? { ...core, afterPrice: true } : core;
  const d = buyingNow(base, f) ? { ...base, buying: true } : base;
  const avoid = avoidedClosings(d, f);
  return avoid.length ? { ...d, avoid } : d;
}

/** question = ต้องจบด้วยคำถาม · hot = คำถามหรือข้อเสนอขออนุญาต · slot = จบที่ช่องเติม · none = ไม่ถาม · free = ไม่บังคับ */
export function questionPolicy(d = {}) {
  const mods = d.modifiers || [];
  if (["GOODBYE", "EXIT", "SILENT"].includes(d.stage) || mods.includes("fatigue") || mods.includes("schedule_check")) return "none";
  if (d.stage === "FIRST_CONTACT" || (d.stage === "SCREEN_PRICE" && d.ladder)) return "slot";
  // เงินตึง = ปิดด้วยประโยคใส่ใจหรือคำถามเบา ๆ ก็ได้ · ข้อกังวลหลังลูกค้าเมินข้อเสนอเดิม = ไม่บังคับถาม (เคสจริง 5 ต.ค.)
  // รีวิวเคสจริง 5 ต.ค.: ขอพื้นฐานก่อนบอกราคา (SCREEN_PRICE) ยังต้องถามคำถามคัดกรอง · ลูกค้าบอกจะสมัครเอง = ปิดด้วยก้าวสมัคร
  // รีวิวเคสจริงทั้งวัน 5 ต.ค. (รอบรีวิว): บ่นว่าค่าเรียนไม่ไหว / ปฏิเสธข้อเสนอ = ไม่บังคับถาม
  if ((mods.includes("money_hardship") && d.stage !== "SCREEN_PRICE" && !d.enroll)
    || (d.stage === "OBJECTION" && (declinedOffer(d) || d.softDecline || d.notReady))) return "free";
  // รีวิวเคสจริงทั้งวัน 5 ต.ค.: คนทำเล่นที่บอกว่าไม่มีงานจะใช้ = ปิดด้วยประโยคอบอุ่นได้ ไม่บังคับถามข้อที่สี่
  if (d.stage === "DISCOVERY" && d.reason === "no_work_use") return "free";
  // หลังแจ้งราคา/ส่งรอบ และตอบเรื่องวันที่ = ก้าวถัดไปที่ชัด (ชวนเลือกรอบ/ถามว่ายังติดเรื่องไหน)
  if (["BRIDGE", "PRICE", "DEAL_PAIR"].includes(d.stage) || d.afterPrice
    || (d.stage === "LOGISTICS" && ["rounds", "booking", "date", "next"].includes(d.logistics))) return "hot";
  if (d.stage === "LOGISTICS") return "free";
  return "question";
}

/** ช่องเติมที่เปิดในเทิร์นนี้ + ช่องที่ระบบต้องวางเองถ้าโมเดลลืม */
export function openSlotsFor(d = {}, { hasReview = false, socialReview = false, trialInvite = false } = {}) {
  const open = [];
  const required = [];
  if (d.stage === "FIRST_CONTACT" || (d.stage === "SCREEN_PRICE" && d.ladder)) { open.push("บันได"); required.push(["บันได", "end"]); }
  if (d.stage === "PRICE" || d.stage === "DEAL_SINGLE") { open.push("ราคา"); required.push(["ราคา", "beforeLast"]); }
  if (d.stage === "DEAL_PAIR") { open.push("ดีล"); required.push(["ดีล", "beforeLast"]); }
  // รีวิวเคสจริงทั้งวัน 5 ต.ค.: เงินตึง/ต้องยืมเงินมาเรียน ได้ลิงก์รีวิวที่ระบบวางเอง (ช่องบังคับ) = ยังโน้มน้าวให้ซื้อ — เทิร์นนี้ไม่เปิดช่องรีวิว
  // รีวิวเคสจริงทั้งวัน 5 ต.ค. (รอบรีวิว): บ่นว่าค่าเรียนไม่ไหว / ปฏิเสธข้อเสนอ / งงหลังราคา = ไม่ยกรีวิวมาโน้มน้าว
  const quietTurn = d.softDecline || d.offerDeclined || d.notReady || d.reason === "confused_after_price";
  // พี่ง้วง 12 ต.ค.: รีวิวคนจริงตามบทสนทนา (socialProof.mjs ตัดสินแล้ว — รู้โจทย์/หลังราคา/ข้อกังวล/ขอดูเอง · เงินตึงและจังหวะเงียบไม่เคยได้)
  if ((socialReview || (hasReview && (d.stage === "REASSURE" || d.stage === "OBJECTION") && !quietTurn))
    && !(d.modifiers || []).includes("money_hardship")) {
    open.push("รีวิว"); required.push(["รีวิว", "beforeLast"]);
  }
  // คำชวนทดลองเรียนฟรี (สิทธิ์ของวันนี้จองแล้ว) — ลิงก์ที่อนุมัติวางด้วยช่องเติมเสมอ ไม่ให้โมเดลพิมพ์ลิงก์เอง
  if (trialInvite) { open.push("ทดลองเรียน"); required.push(["ทดลองเรียน", "beforeLast"]); }
  return { open, required };
}

