// หยุดทัก: ลูกแพรปิดห้อง (EXIT) · ลูกค้าปฏิเสธข้อเสนอ/คลาส/ยังไม่พร้อม/บ่นงบ · เงินตึง · ดูแลใจ (ป่วย/ตกงาน/รู้สึกโดนตื๊อ) · ลูกค้าลาเอง
