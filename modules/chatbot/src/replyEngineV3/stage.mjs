const OPENS_WITH_YES = /^(?:ได้|เอา|ok|โอเค|สนใจ|ขอ(?!โทษ|คิด)|ส่ง|อยาก(?:ลอง|ได้|ดู)|รบกวน)/iu;

/**
 * ตัวปิดของสองเทิร์นล่าสุดที่ลูกค้ายังไม่ตอบรับ = เทิร์นนี้ห้ามปิดซ้ำ (เคสจริง 5 ต.ค.: ชวนดูรอบซ้ำสี่ครั้ง ลูกค้าไม่เคยตอบ)
 * ไม่นับ: ข้อเสนอที่ลูกค้าเพิ่งรับ · ชนิดที่ลูกค้าถามเองหรือพร้อมซื้อเทิร์นนี้
 * @returns {Array<{text: string, types: string[]}>}
 */
export function avoidedClosings(d = {}, f = {}) {
  const recent = Array.isArray(f.recentClosings) ? f.recentClosings : [];
  if (!recent.length || closesWithSlotOrGoodbye(d)) return [];
  const requested = requestedTypes(d, f);
  // รีวิวเคสจริง 6–7 ต.ค.: ตอบคำถามชวนเลือกรอบด้วยวันอย่างเดียว ("เสาร์ 17") = เลือกรอบแล้ว ไม่ใช่เมินข้อเสนอรอบ
  const engaged = (item) => isShortAccept(item.reply, { offer: item.text, burst: item.text })
    || closingTypes(item.reply).some((type) => (item.types || []).includes(type)) || stillInterested(item.reply)
    || roundPickOf({ text: item.reply, lastBotText: item.text, prevRole: "assistant" });
  // รีวิวเคสจริง 5 ต.ค.: "ได้เลยครับ รบกวนส่งให้หน่อย ขอบคุณมาก" เคยนับว่าเมินข้อเสนอ เพราะไม่ได้ขึ้นจังหวะ accepted_
  const text = String(f.text || "").trim();
  const opensWithYes = f.prevRole === "assistant" && OPENS_WITH_YES.test(text) && !HESITATE_RE.test(text) && !concernOf(f)?.hardship;
  const latestTaken = /^accepted_/u.test(String(d.reason || "")) || (d.reason === "list_request" && Boolean(acceptanceOf(f).accepted))
    || opensWithYes;
  return recent
    // ตัวปิดของก้อนล่าสุด = ลูกค้ากำลังตอบเทิร์นนี้ (ตัดสินจากจังหวะ) · ก้อนก่อนหน้า = ดูจากข้อความที่ลูกค้าตอบไปแล้ว
    .filter((item) => !(item.latest === false ? engaged(item) : latestTaken))
    .map((item) => ({ text: item.text, types: (item.types || []).filter((type) => !requested.has(type)) }));
}

