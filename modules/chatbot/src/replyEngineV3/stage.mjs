const EXIT_REPORTED_RE = /(?:ลูกค้า|เขา|เพื่อน|คน(?:อื่น)?|ลูกศิษย์)\S{0,20}(?:บอก|ตอบ|พิมพ์|พูด|ทัก)|(?:แฟน|สามี|ภรรยา|ลูก|หัวหน้า|เจ้านาย|พ่อ|แม่|เขา|เพื่อน)\S{0,6}(?:ไม่(?:ค่อย)?สนใจ|ไม่เอา|ไม่ต้องการ|ไม่เรียน)/u;
const LEVEL_OR_ROUND_RE = /(?:^|\s|ข้อ)[1-5](?!\d)|[1-5]️?⃣|รอบ\s*\d/u;
const EXIT_MAX_CHARS = 160;

/** ห้องร้อน: ลูกแพรแจ้งราคา/ส่งรอบไปแล้ว หรือเพิ่งเสนออะไรค้างไว้ (ข้อเสนอขออนุญาต / ชวนเลือกรอบ) */
function contextOfferText(offer) {
  if (!offer) return "";
  if (offer.text) return String(offer.text);
  if (offer.type === "registration") return `ให้ลูกแพรส่งรายละเอียดการสมัคร${offer.roundLabel ? `สำหรับ${offer.roundLabel}` : ""}ให้ไหมคะ?`;
  if (offer.type === "rounds") return "ให้ลูกแพรส่งรอบเรียนที่เปิดอยู่ให้ดูไหมคะ?";
  if (offer.type === "review") return "ให้ลูกแพรส่งรีวิวและเคสผู้เรียนให้ดูไหมคะ?";
  if (offer.type === "content") return "ให้ลูกแพรส่งหัวข้อและรายละเอียดให้ดูไหมคะ?";
  if (offer.type === "class") return "ให้ลูกแพรเล่ารายละเอียดคลาสที่เหมาะให้ดูไหมคะ?";
  return "ให้ลูกแพรส่งรายละเอียดให้ดูไหมคะ?";
}

function pendingOfferOf(f = {}) {
  if (f.pendingOffer?.status === "pending") return contextOfferText(f.pendingOffer);
  if (f.prevRole !== "assistant") return "";
  // รีวิวเคสจริงทั้งวัน 5 ต.ค. (รอบรีวิว): ทีมงานพิมพ์ถามต่อจากข้อเสนอของลูกแพร = ลูกค้ากำลังตอบทีมงาน ไม่ใช่ตอบข้อเสนอนั้น
  const lastTurn = (Array.isArray(f.history) ? f.history : []).at(-1);
  if (String(lastTurn?.content || "").startsWith(ADMIN_PREFIX_TEXT)) return "";
  const sentence = offerSentence(String(f.lastBotText || ""));
  if (sentence) return sentence;
  const latest = (Array.isArray(f.recentClosings) ? f.recentClosings : []).find((item) => item.latest !== false && (item.types || []).length);
  return latest?.text || "";
}
const ADMIN_PREFIX_TEXT = "[แอดมินทีมงานพิมพ์เอง]";
const hotRoomOf = (f = {}) => Boolean(f.priceQuoted || f.roundsSent || pendingOfferOf(f));

/** เหตุของการปิดอย่างสุภาพ ("" = ไม่ใช่) — wrong_click · not_interested · price_decline · hardship_decline · who_are_you · not_for_class */
export function exitReasonOf(f = {}) {
  const t = String(f.text || "").trim();
  if (!t || [...t].length > EXIT_MAX_CHARS || EXIT_REPORTED_RE.test(t)) return "";
  if (buyingWords(t) || ROUND_PICK_RE.test(t) || ENROLLED_RE.test(t)) return "";
  // คำไทยติดกันไม่เว้นวรรค — ตรวจคำปฏิเสธ/กดผิดจากข้อความที่ตัดช่องว่างทิ้ง ("ไม่ สนใจ ค่ะ" · "กด ผิด ค่ะ")
  const compact = t.replace(/\s+/gu, "");
  if (NEGATED_DECLINE_RE.test(compact) || TRUST_ASK_RE.test(t)) return "";
  const history = Array.isArray(f.longHistory) && f.longHistory.length ? f.longHistory : (Array.isArray(f.history) ? f.history : []);
  const firstTurn = !history.some((turn) => turn?.role === "user");
  const hot = hotRoomOf(f);
  const withoutNothing = t.replace(/ไม่มีอะไร\S*/gu, " ");
  const asks = ASKS_RE.test(withoutNothing) || STILL_ASKING.test(withoutNothing) || CONCEPT_RE.test(t) || LOGISTICS_RE.test(t)
    || DISCOUNT_RE.test(t) || PRICE_REASK.test(t);
  // คำถามว่าเป็นใครเป็นรูปคำถามอยู่แล้ว — ข้ามตัวกันคำถาม แต่เอ่ยเรื่องคลาส/AI/โฆษณา หรือขอข้อมูลด้วย = ไม่ปิด
  // ห้องร้อน = ตอบตรง ๆ แบบไม่ถาม (ตัวตัดสินจังหวะใส่ตัวปรับเอง) ไม่ปิดห้อง
  if (WHO_ASK_RE.test(t)) {
    const curious = WHO_CURIOUS_RE.test(t) || CONCEPT_RE.test(t) || LOGISTICS_RE.test(t) || PRICE_REASK.test(t);
    return curious || hot ? "" : "who_are_you";
  }
  if (asks || EXIT_GUARD_RE.test(t) || LEVEL_OR_ROUND_RE.test(t)) return "";
  // "กดผิด" กลางบทสนทนา (ตอบบันไดพลาด) ไม่ใช่กดเข้ามาผิด — นับเฉพาะข้อความแรกของห้อง หรือคู่กับ "ไม่มีอะไร"
  const wrongClick = (WRONG_CLICK_RE.test(compact) || WRONG_CLICK_EN.test(t)) && !WRONG_CLICK_DENIED.test(compact);
  if (wrongClick && (firstTurn || /ไม่มีอะไร/u.test(t))) return "wrong_click";
  const hardship = Boolean(concernOf(f)?.hardship);
  const pass = EXPLICIT_PASS_RE.test(compact) || EXPLICIT_PASS_EN.test(t);
  const money = MONEY_WORD_RE.test(t) && !MONEY_OK_RE.test(t);
  // ต้องยืมเงินมาเรียน/เป็นหนี้แล้วบอกว่าไม่ไหว = ปิดอย่างดูแลใจ (ทุกห้อง)
  if (hardship && MUST_BORROW_RE.test(t) && (pass || MONEY_DECLINE_RE.test(t))) return "hardship_decline";
  if (hot) return pass ? (money ? "price_decline" : "not_interested") : "";
  if (NOT_FOR_CLASS_RE.test(compact)) return "not_for_class";
  // รีวิวเคสจริงทั้งวัน 5 ต.ค. (รอบรีวิวสอง): มีคำถามของลูกแพรค้างอยู่ = รับคำเงียบ ๆ ใน decideCore แทนการปิดห้อง
  if (!firstTurn && BROWSING_RE.test(t) && !pendingQuestion(f)) return "not_for_class";
  if (pass || NOT_INTERESTED_RE.test(compact) || NOT_INTERESTED_EN.test(t)) return money ? "price_decline" : "not_interested";
  return "";
}

// รีวิวเคสจริงทั้งวัน 5 ต.ค. (รอบรีวิว): คำบ่นว่าค่าเรียนไม่ไหว/เกินกำลังที่ไม่ได้ขอผ่าน = ข้อกังวลเรื่องงบแบบดูแลใจ (ไม่ถามบังคับ ไม่ขายต่อ)
// หลังการ์ดราคาตอบสั้น ๆ ว่า "ไม่ไหวค่ะ / เกินกำลังค่ะ" ก็คือเรื่องงบ · "มาคนเดียวคงไม่ไหว" = บอกทางมาเป็นคู่ได้ (ข้อมูลดีลที่อนุมัติแล้ว ไม่พิมพ์ตัวเลขเอง)
const BARE_DECLINE_RE = /^(?:คง|ก็|แต่|ตอนนี้|ช่วงนี้|อืม+|เอ่อ)?(?:ไม่ไหว|คงไม่ไหว|เกินกำลัง|สู้ไม่ไหว|คงยาก|เอื้อมไม่ถึง)(?:จริงๆ|จริง|เลย|แล้ว|ค่ะ|คะ|ค่า|ครับ|คับ|นะ|จ้า|อะ|อ่ะ)*[.!…]*$/u;
const ALONE_RE = /คนเดียว|ท่านเดียว|ต่อคน|ต่อท่าน/u;
const PRICE_IN_BURST = /\d{1,3},\d{3}\s*บาท|ราคาปกติ|โปรโมชั่น|early ?bird/iu;
/** ข้อกังวลเรื่องงบที่ไม่ได้ปิดห้อง · null = ไม่ใช่ */
export function budgetDeclineOf(f = {}) {
  const t = String(f.text || "").trim();
  if (!t || [...t].length > EXIT_MAX_CHARS || ASKS_RE.test(t) || STILL_ASKING.test(t) || buyingWords(t) || PAYMENT_ASK_RE.test(t)) return null;
  const compact = t.replace(/\s+/gu, "");
  if (NEGATED_DECLINE_RE.test(compact)) return null;
  const afterPriceCard = f.prevRole === "assistant" && (PRICE_IN_BURST.test(String(f.lastBotText || "")) || Boolean(f.priceQuoted));
  const linked = moneyDeclined(t) || (ALONE_RE.test(t) && MONEY_DECLINE_RE.test(t) && Boolean(f.priceQuoted));
  if (!linked && !(afterPriceCard && BARE_DECLINE_RE.test(compact))) return null;
  return { alone: ALONE_RE.test(t) };
}

