const TRUST_ASK_RE = /พี่ง้วง|ใครสอน|ผู้สอน|คนสอน|สอน|วิทยากร|อาจารย์|โค้ช|ครู|เจ้าของ|เหมาะกับใคร|น่าเชื่อถือ/u;
// ข้อความถามว่าใครทักมาที่เอ่ยเรื่องคลาส/AI/โฆษณา/ความสนใจ หรือขอข้อมูล = คนที่อยากรู้เรื่องคลาส (รีวิวเคสจริงทั้งวัน 5 ต.ค.: "นี่ใครคะ เห็นโฆษณาเรื่อง AI เลยทักมา")
const WHO_CURIOUS_RE = /โฆษณา|\bai\b|เอไอ|คลาส|คอร์ส|เรียน|อบรม|workshop|สนใจ|ขอ(?:ข้อมูล|รายละเอียด|ทราบ|ดู)|ใช่(?:ไหม|มั้ย|มั๊ย)|(?:ไหน|อะไร)บ้าง/iu;
// ไม่ได้มาเรียนชัด ๆ (ทุกห้อง) · แค่ทักดูเฉย ๆ (เฉพาะกลางห้องที่ยังไม่ได้ราคา — ข้อความแรกจากโฆษณาคือคนที่กำลังดู ไม่ใช่คนปฏิเสธ)
const NOT_FOR_CLASS_RE = /ไม่ได้(?:มา|จะ|อยาก|สนใจ|ตั้งใจ)\S{0,6}(?:เรียน|สมัคร|ซื้อ)/u;
