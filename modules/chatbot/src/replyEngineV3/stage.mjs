const FORWARD_TO_DECIDER = `(?<!ใบ)(?:แจ้ง|ส่ง|เสนอ|นำเสนอ|ส่งต่อ|เอา|นำ|ยื่น)\\s?(?:ราคา|ค่าเรียน|ข้อมูล|รายละเอียด|เรื่องนี้)?\\S{0,8}?\\s?(?:ไป(?:ยัง|ให้|ที่|ทาง)?|ให้)\\s?(?:ทาง)?\\s?${DECIDER}`;
