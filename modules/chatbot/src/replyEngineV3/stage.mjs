// ส่วนก่อนหน้าต้องไม่ถาม ไม่ใช่ข้อกังวล และไม่ได้ตอบคำถามสำรวจที่ลูกแพรถามค้าง ("ใช้ ChatGPT ค่ะ / ขอบคุณค่ะ" = ตอบแล้วขอบคุณ)
// บับเบิลท้ายต้องเป็นคำเลื่อน/คำลาชัด — "ขอบคุณ" เฉย ๆ ต่อท้ายเรื่องที่เล่ามา ลาได้เฉพาะตอนส่วนก่อนหน้าเป็นแค่คำรับ
const LAST_BUBBLE_DEFER = /^(?:ขอ(?:เอา)?)?ไว้\S{0,4}?(?:ก่อน|โอกาสหน้า|คราวหน้า)|^(?:ขอตัว|บาย|bye)/iu;
const DEFER_GOODBYE_RE = new RegExp(`${LATER_DEFER}|ไว้(?:โอกาสหน้า|ก่อน|คราวหน้า|ค่อย)|ขอ(?:คิด|ปรึกษา|ดู)(?:ดู)?ก่อน|ไม่มี(?:แล้ว|อะไร)|บาย`, "iu");
function burstGoodbye(f) {
  const parts = Array.isArray(f.parts) ? f.parts.map((part) => String(part).trim()).filter(Boolean) : [];
  if (parts.length < 2) return false;
  const last = parts.at(-1);
  const before = parts.slice(0, -1).join("\n");
  if (ASKS_RE.test(parts.join("\n")) || STILL_ASKING.test(before) || LEVEL_OR_ROUND_RE.test(before) || OBJECTION_RE.test(before)) return false;
  const burst = String(f.lastBotText || "");
  const offered = Boolean(offerSentence(burst)) || OFFER_ASK_RE.test(burst);
  // รีวิวเคสจริงทั้งวัน 5 ต.ค. (รอบรีวิว): ตอบคำถามสำรวจแล้วบับเบิลท้ายขอเลื่อน/บาย ("ร้านกาแฟค่ะ" + "ขอไว้ก่อนนะคะ ต้องไปทำงาน") เคยได้คำถามต่อ
  // — คำเลื่อน/คำลาชัดในบับเบิลท้ายชนะคำถามที่ค้าง (บับเบิลท้ายที่ยังบอกว่าสนใจไม่นับ)
  if (LAST_BUBBLE_DEFER.test(last) && !buyingWords(last)) return true;
  if (pendingQuestion(f) && !offered) return false;
  // ข้อเสนอค้าง + "โอเคครับ / ขอบคุณครับ" = รับข้อเสนอ (กติกาเดิมของ isGoodbye: ลาเฉพาะคำเลื่อนชัด ๆ)
  const ackBefore = parts.slice(0, -1).every((part) => {
    const bare = part.replace(LINE_EMOJI_NAME, " ").replace(EMOJI, " ").replace(/\s+/gu, " ").trim();
    return !bare || FAREWELL_ACK.test(bare);
  });
  if (!DEFER_GOODBYE_RE.test(last) && (offered || !ackBefore)) return false;
  return isGoodbye({ ...f, text: last, parts: [last] }, last);
}

function isGoodbye(f, t) {
  const trimmed = t.trim();
  if ([...t].length > 80 || f.money || ASKS_RE.test(t)) return false;
  // ลูกแพรลาไปแล้วโดยไม่มีข้อเสนอค้าง ชนะตัวจับ continuation (มันอ่าน "มีอะไรทักมาได้เสมอนะคะ" เป็นข้อเสนอ)
  if (afterBotFarewell(f, trimmed)) return true;
  if (f.continuation?.action === "continue_previous_offer") return false;
  const unEmoji = trimmed.replace(EMOJI, " ").trim();
  const lead = ACK_LEAD.exec(unEmoji)?.[0] || "";
  let core = unEmoji;
  if (lead) {
    // "ค่ะ ขอบคุณค่ะ" ต่อข้อเสนอที่ค้าง = รับ (ลาเฉพาะคำเลื่อนชัด ๆ) · ส่วนที่เหลือต้องเป็นแค่คำลา ไม่ใช่เรื่องงานของเขา
    const burst = String(f.lastBotText || "");
    core = unEmoji.slice(lead.length);
    if (offerSentence(burst) || OFFER_ASK_RE.test(burst)) return DEFERRAL.test(core) && !STILL_ASKING.test(core);
    const rest = core.replace(GOODBYE_PHRASES, " ").replace(/ค่ะ|คะ|ครับ|คับ|นะ|มาก|จ้า|\[ลูกค้า\]|\s/gu, "");
    if ([...rest].length > 6) return false;
  }
  if (!GOODBYE_RE.test(core)) return false;
  if (STILL_ASKING.test(core.replace(GOODBYE_PHRASES, " "))) return false;
  if (GOODBYE_EXPLICIT.test(core) || !GOODBYE_AMBIGUOUS.test(core)) return true;
  const asked = pendingQuestion(f);
  return !asked || ANYTHING_ELSE_ASK.test(asked);
}

const ACCEPT_WORD_MAX = 8;
function isShortAccept(t, { offer = "", burst = "" } = {}) {
  const value = String(t || "").trim();
  const core = stripAcceptTail(value.replace(EMOJI, "")).trim();
  // เหลือแต่คำรับ ("ได้" / "อยากดู" / "สนใจ") หลังตัดคำขอบคุณและคำสุภาพ — มีเรื่องอื่นปน ("ได้ค่ะ แต่กลัวจำไม่ไหว") ไม่นับ
  const bare = value.replace(EMOJI, "").replace(ACCEPT_FILLER, "");
  const fillerOnly = Boolean(bare) && [...bare].length <= ACCEPT_WORD_MAX;
  return ([...core].length <= (offer ? 20 : 15) || fillerOnly) && SHORT_ACCEPT_RE.test(value) && !HESITATE_RE.test(value)
    && (Boolean(offer) || OFFER_ASK_RE.test(burst));
}

// ลูกค้ารับข้อเสนอที่ลูกแพรเพิ่งเสนอไหม — accepted = ประโยคข้อเสนอที่รับ (ไม่มีประโยคข้อเสนอ = ทั้งก้อน) · "" = ไม่ได้รับ
// ข้อเสนอส่งรายละเอียดการสมัครของรอบที่รู้แล้ว (รอบที่เลือกไว้ / ข้อเสนอเอ่ยวันที่ / รอบนี้) — ข้อเสนอที่ยังชวนเลือกรอบอยู่
// ("เลือกรอบแล้วลูกแพรส่งรายละเอียดการสมัครให้เลยนะคะ สะดวกเริ่มรอบไหนดีคะ?") รับแล้วยังต้องเลือกรอบก่อน
function enrollOfferForRound(offer, f) {
  if (!isRegistrationDetailsOffer(offer) || CHOOSE_ROUND_ASK.test(offer)) return false;
  return Boolean(f.pickedRound) || DAY_TOKEN_RE.test(offer) || /รอบ(?:นี้|นั้น)|ที่เลือก/u.test(offer);
}
function enrollDoubt(f, t, concern) {
  return HESITATE_RE.test(t) || NOT_READY_RE.test(t) || NOT_DECIDED_RE.test(t) || CARE_WAITING_RE.test(t) || OBJECTION_RE.test(t)
    || ENROLL_DOUBT_RE.test(t) || Boolean(f.hesitates) || Boolean(concern?.hardship);
}

function acceptanceOf(f) {
  if (f.pendingOffer?.accepted) {
    const contextOffer = contextOfferText(f.pendingOffer);
    return { offer: contextOffer, accepted: contextOffer };
  }
  const burst = String(f.lastBotText || "");
  const offer = f.prevRole === "assistant" ? offerSentence(burst) : "";
  const shortAccept = f.prevRole === "assistant" && isShortAccept(f.text, { offer, burst });
  return { offer, accepted: f.continuation?.action === "continue_previous_offer" || shortAccept ? (offer || burst) : "" };
}

