const PRICE_STAGE_SET = new Set(["PRICE", "DEAL_PAIR", "DEAL_SINGLE"]);

/**
 * ลูกค้าพร้อมซื้อเทิร์นนี้: บอกจะสมัคร/จอง/พร้อมเรียน/เอา/สนใจ · ถามวิธีจ่าย · จังหวะถามราคา/ส่วนลด/commitment/sales_offer
 * รีวิวเคสจริง 5 ต.ค.: ตัวกันปิดซ้ำเคยกันก้าวปิดการขาย ("สมัครยังไง" ได้ข้อเสนอหัวข้อแทนรอบ) — พร้อมซื้อ = ปลดล็อกรอบและการสมัครเสมอ
 * เหลือตัวกันถ้อยคำเดิม ≥0.8 อย่างเดียว (หลังแจ้งราคาชวนเลือกรอบได้หนึ่งครั้ง ประโยคชวนเลือกรอบเดิมซ้ำไม่ได้)
 */
export function buyingNow(d = {}, f = {}) {
  const t = String(f.text || "");
  // ปิดอย่างสุภาพ/เงียบ = ไม่ปลดรอบหรือการสมัคร (ประโยคปฏิเสธที่มีคำว่าค่าเรียน ไม่ใช่การถามราคา)
  if (d.stage === "EXIT" || d.stage === "SILENT") return false;
  // ถามวิธีจ่าย ("จ่ายบัตรเครดิตได้ไหม") = พร้อมจ่าย
  return Boolean(d.enroll || BUY_REASONS.has(d.reason) || buyingWords(t) || PAYMENT_ASK_RE.test(t));
}

// ชนิดที่ลูกค้าขอเองเทิร์นนี้ = ไม่นับว่าเมิน (ถามรอบ = บอกรอบแล้วถามว่าสะดวกรอบไหนได้)
function requestedTypes(d, f) {
  // ลูกค้าพูดถึงเรื่องนั้นเองเทิร์นนี้ ("รอบ 24 ค่ะ") = ตอบรับ/คุยต่อ ไม่ใช่เมิน — ตรวจซ้ำเคสจริง 5 ต.ค. ผ่านไปป์ไลน์จริง:
  // ลูกค้าเลือกรอบแล้ว ด่านหลังร่างตัดข้อเสนอส่งรายละเอียดการสมัครรอบนั้นทิ้ง (ก้าวที่ปิดการขาย)
  const requested = new Set(closingTypes(f.text));
  // ถามวันที่เอง = บอกรอบที่ใกล้วันนั้นแล้วชวนเลือกได้ (ไม่นับว่าเมินข้อเสนอรอบ)
  if (d.stage === "LOGISTICS" && ["rounds", "booking", "date"].includes(d.logistics)) requested.add("rounds");
  if (d.logistics === "booking") requested.add("booking");
  // รีวิวเคสจริง 6–7 ต.ค.: การ์ดราคาที่ค้างจ่ายหลังคำถามคัดกรอง (price_owed) ไม่ได้ปลดข้อเสนอรอบ ทั้งที่ลูกค้าถามราคาเอง —
  // ปิดท้ายเลยกลายเป็นคำถามคัดกรองซ้ำ · การ์ดราคาทุกแบบ = ชวนเลือกรอบได้หนึ่งครั้ง (ประโยคเดิมเป๊ะยังห้ามซ้ำ ≥0.8)
  if (PRICE_STAGE_SET.has(d.stage)) { requested.add("price"); requested.add("rounds"); }
  if (buyingNow(d, f)) { requested.add("rounds"); requested.add("booking"); }
  return requested;
}

