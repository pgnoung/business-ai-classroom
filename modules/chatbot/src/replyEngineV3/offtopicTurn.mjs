const NEUTRAL_CLOSE_CATEGORIES = new Set(["gambling", "off_topic_personal"]);
const NEUTRAL_CLOSE = "ปิดด้วยคำขอบคุณที่เป็นกลางหนึ่งประโยค เช่น \"ขอบคุณที่เข้าใจนะคะ\" — ไม่อวยพรเรื่องคู่ ความรัก หรือโชค ไม่หยอก ไม่ใช้อีโมจิ";

/** งานของเทิร์นตีจบ (ข้อความเดียว) — หมวดไม่รู้จัก = น้ำเสียงกลางแบบสุภาพ */
export function offtopicCloseMoves(d = {}, f = {}) {
  const category = String(d.offtopic || "");
  const monk = category === "monk";
  const closing = monk ? "ปิดด้วยคำนอบน้อม เช่น \"กราบนมัสการค่ะ\""
    : NEUTRAL_CLOSE_CATEGORIES.has(category) ? NEUTRAL_CLOSE : "อวยพรหรือให้กำลังใจหนึ่งประโยคอย่างจริงใจ";
  return [
    ...(f.firstReply && !monk ? ["ขึ้นต้นด้วย \"สวัสดีค่ะ\""] : []),
    CATEGORY_MOVES[category] || "รับคำของเขาอย่างสุภาพและเข้าใจ",
    "บอกสั้น ๆ ว่าแชทนี้ลูกแพรดูแลเรื่องสอบถามคลาสเรียน AI ของพี่ง้วง",
    closing,
    "เทิร์นนี้ข้อความเดียวสั้น ๆ ไม่ถาม ไม่ขาย ไม่ส่งราคา รอบ หัวข้อ รีวิว ลิงก์ หรือรูป ไม่เอ่ยชื่อคลาส "
      + "ไม่รับปากว่าทีมงานจะติดต่อกลับ และไม่บอกว่าระบบปิดแชท",
  ];
}

/**
 * แทนคำตัดสินของเทิร์นด้วยจังหวะตีจบ (pure) — ข้อเท็จจริงอื่นของเทิร์นคงเดิม (ประวัติ ชื่อที่เรียกได้ ทักแรกหรือไม่)
 * ตัดรูป/รีวิว/ช่องเติม/รูปบรรยากาศ-รีวิว-คำชวนทดลองเรียนของตัวตัดสินเทิร์น (socialProof) ทิ้ง: คำลาต้องไม่มีอะไรขายติดไป
 * (รีวิวรอบ 4: socialProof ที่ค้างอยู่ทำให้งานของเทิร์นลาสั่งแนบรูป/{{รีวิว}} และเครื่องบังคับแทรกรูป — ทุกตัวที่อ่าน socialProof เห็นค่าว่างจากตรงนี้)
 */
export function withOfftopicClose(built, category) {
  if (!built?.ok) return built;
  return {
    ...built,
    decision: { stage: "GOODBYE", reason: OFFTOPIC_CLOSE_REASON, modifiers: [], offtopic: String(category || "") },
    slots: { open: [], required: [], values: {} },
    facts: { ...built.facts, imageOffer: null, review: null, socialProof: null },
  };
}
