export function interestWording(plan) {
  if (!plan || typeof plan !== "object") return plan;
  const fix = (value) => TASK_WORDING.reduce((text, [pattern, to]) => text.replace(pattern, to), value);
  return Object.fromEntries(Object.entries(plan).map(([key, value]) => [key, typeof value === "string" ? fix(value) : value]));
}

// คำตอบจริงของ Opus ยาวกว่าช่วงความยาวของงานเทิร์น 10–25% และ 6.1 ทำตามช่วงจนห้วน → ขยายช่วงขึ้น 25% (งาน + ด่าน S6)
const TEACHER_BAND_FACTOR = 1.25;
export function teacherBand(band) {
  if (!Array.isArray(band) || band.length !== 2) return band;
  const up = (n) => (Number.isFinite(n) ? Math.round((n * TEACHER_BAND_FACTOR) / 10) * 10 : n);
  return [up(band[0]), up(band[1])];
}
function teacherBandPlan(plan) {
  if (!Array.isArray(plan?.band)) return plan;
  const band = teacherBand(plan.band);
  const text = String(plan.text || "").replace(`ความยาว: ราว ${plan.band[0]}–${plan.band[1]} ตัวอักษร`, `ความยาว: ราว ${band[0]}–${band[1]} ตัวอักษร`);
  return { ...plan, band, text };
}

// ลูกค้าเพิ่งตอบบันไดระดับ (ข้อความก่อนหน้าของลูกแพรมีบันได) ด้วยตัวเลขที่ไม่ได้มาเดี่ยว ๆ เช่น "ใช้ระดับ 4 ค่ะ" "เคยใช้บ้างครับ\n3"
// (ระบบอ่านระดับได้เอง = facts.answeredLevel ใช้ค่านั้นก่อน · งาน DISCOVERY เดิมมีบรรทัดระดับอยู่แล้ว ข้างบนแปลงเป็นแบบครู)
const LADDER_IN_BOT = /1️⃣|ระดับที่เท่าไหร่|ระดับไหน|ประมาณระดับ/u;
const LEVEL_IN_USER = /(?:ระดับ|ข้อ|stage|level|เลเวล)\s*([1-5])(?!\d)|^\s*([1-5])\s*(?:ค่ะ|คะ|ครับ|นะ|จ้า)?\s*$/imu;
export function ladderLevelAnswer(userText = "", lastBot = "") {
  if (!LADDER_IN_BOT.test(String(lastBot || ""))) return null;
  const m = LEVEL_IN_USER.exec(String(userText || ""));
  return m ? Number(m[1] || m[2]) : null;
}
// เลือกหลายข้อในบันได ("4 และ 5" · "4,5" · "ข้อ 3 กับ 4") — ครูหยิบมาครบทุกข้อ (รอบ ต.ค.: เคยรับแค่ข้อแรก)
const LEVEL_LIST_IN_USER = /^\D{0,12}([1-5])\s*(?:,|และ|กับ|&|\/|-|ถึง|หรือ|\+)\s*([1-5])(?!\d)/u;
export function ladderLevelsAnswer(userText = "", lastBot = "") {
  if (!LADDER_IN_BOT.test(String(lastBot || ""))) return [];
  const m = LEVEL_LIST_IN_USER.exec(String(userText || "").trim());
  return m && m[1] !== m[2] ? [Number(m[1]), Number(m[2])].sort() : [];
}
// คำตอบสั้นว่า "ยัง/ไม่เคย/ไม่มี" ต่อคำถามของลูกแพร — ครูเปิดด้วยการรับแบบอบอุ่น ("ไม่เป็นไรเลยค่ะ … แปลว่าเริ่มจากตรงนี้ได้สบาย ๆ")
const NOT_YET_RE = /^(?:ยัง(?:ไม่\S{0,12})?|ไม่เคย\S{0,12}|ไม่มี\S{0,8}|ไม่ค่อย\S{0,12}|ไม่ครับ|ไม่ค่ะ)\s*(?:ค่ะ|คะ|ครับ|คับ|จ้า|นะ)?\s*$/u;
export const NOT_YET_LINE = "- เขาตอบสั้น ๆ ว่ายัง/ไม่เคย: เปิดด้วย \"ไม่เป็นไรเลยค่ะ\" แล้วบอกว่าแปลว่าอะไรสำหรับเขาแบบให้กำลังใจ (เช่น เริ่มจากตรงนี้ได้สบาย ๆ) ก่อนเล่าเรื่องอื่น ไม่เปิดด้วยประโยคอธิบายลอย ๆ";
// คำว่า "ยัง" ที่ตอบข้อเสนอ ("สนใจดูรอบไหมคะ" → "ยังครับ") คือยังไม่เอา ไม่ใช่ยังไม่เคยใช้ — บรรทัดนี้ใช้เฉพาะตอบคำถามที่ไม่ใช่ข้อเสนอ
const lastLine = (text) => String(text || "").split("\n").map((line) => line.trim()).filter(Boolean).at(-1) || "";

/**
 * งานของเทิร์นแบบครู (การ์ดเปิดเท่านั้น): ถ้อยคำแบบครู → บรรทัดระดับที่เพิ่งตอบ (อ่านจากบันได) → ช่วงความยาว ×1.25
 * (ลองบรรทัด "จุดคุ้มค่าที่เพิ่งพูด ไม่ย้ำ" แล้ว 8 พ.ย.: 6.1 หลบไปพูดเรื่องอื่นที่ไม่ตรงกับที่เคยบอกลูกค้า กรรมการติ จึงเอาออก)
 * @param {{ text: string, band?: number[] }} plan งานจาก stageTask()
 * @param {{ facts?: object, history?: Array<{role: string, content: string}>, userText?: string }} context
 */
// จังหวะขอพื้นฐานก่อนราคา (กรรมการติซ้ำทุกชุด 8 พ.ย.): ครูปิดประโยคคุณค่าด้วยผลที่เขาได้กลับไป + 😊 หนึ่งตัว ·
// ข้อความแรกในห้องขอแบบ "สั้น ๆ ก่อน" ("อีกนิด" อ่านเหมือนเคยถามแล้ว)
export const SCREEN_TEACHER_LINE = "- สูตรครูของจังหวะนี้: ประโยคคุณค่าจบด้วยสิ่งที่เขาได้กลับไป เช่น \"เรียนจบก็กลับไปใช้กับงานต่อได้เลยค่ะ\" "
  + "และใส่ 😊 หนึ่งตัวในข้อความนี้ · ถ้าเขาถามโครงสร้างคอร์สหรือเรื่องอื่นมาด้วย ตอบสั้น ๆ ตามข้อมูลก่อน";
const FIRST_MESSAGE_MARK = "นี่คือข้อความแรกของลูกแพรในห้องนี้";
export function teacherPlan(plan, { decision = {}, facts = {}, history = [], userText = "" } = {}) {
  const base = interestWording(plan);
  if (!base || typeof base.text !== "string") return teacherBandPlan(base);
  const worded = base.text.includes(FIRST_MESSAGE_MARK)
    ? { ...base, text: base.text.replace("ลูกแพรขอทราบพื้นฐานการใช้ AI อีกนิด", "ลูกแพรขอทราบพื้นฐานการใช้ AI สั้น ๆ ก่อนนะคะ") } : base;
  const bots = (Array.isArray(history) ? history : []).filter((turn) => turn?.role === "assistant").map((turn) => String(turn.content || ""));
  const lastBot = bots.at(-1) || "";
  const level = Number.isInteger(facts?.answeredLevel) && LEVEL_TEACHER[facts.answeredLevel] ? facts.answeredLevel : ladderLevelAnswer(userText, lastBot);
  const levels = ladderLevelsAnswer(userText, lastBot);
  const top = levels.length ? levels.at(-1) : level;
  const extra = [
    levels.length ? `- เขาเลือกหลายข้อ (${levels.join(" และ ")}) — หยิบมาครบทุกข้อในประโยคแรก ไม่รับแค่ข้อแรก` : "",
    top && !worded.text.includes(`เขาเพิ่งตอบระดับ ${top}`) ? `- ${levelLine(top)}` : "",
    NOT_YET_RE.test(String(userText || "").trim()) && !OFFER_ASK_RE.test(lastLine(lastBot)) && !worded.text.includes("ไม่เป็นไรเลยค่ะ") ? NOT_YET_LINE : "",
    decision?.stage === "SCREEN_PRICE" ? SCREEN_TEACHER_LINE : "",
  ].filter(Boolean);
  return teacherBandPlan(extra.length ? { ...worded, text: `${worded.text}\n${extra.join("\n")}` } : worded);
}
