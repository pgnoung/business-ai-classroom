/** ถ้อยคำของระดับที่ตัดสินแล้ว — ระดับ 0 คืนสตริงว่าง (พรอมต์เดิมทุกไบต์) */
export function coachingBrakeRule(assessment) {
  const level = Number(assessment?.level) || 0;
  if (level < 1) return "";
  const capped = Math.min(COACHING_BRAKE_MAX_LEVEL, level);
  return [HEADER(capped), ESCAPE_HATCH, ROLE, PRECEDENCE, ...LEVEL_LINES[capped]].join("\n");
}

/** สวิตช์ runtime — ไม่มีค่า = on (คำสั่งเจ้าของ) · off = ปิด · อ่านพัง = off (พฤติกรรมเดิม) */
export function coachingBrakeMode(db) {
  // White-label: โปรไฟล์ generic ปิดฟีเจอร์เฉพาะธุรกิจคอร์สของพี่ง้วงเสมอ (ค่าใน DB ไม่มีผล)
  if (isGenericProfile(activeBrand())) return "off";
  try {
    const raw = String(db?.getSetting?.(COACHING_BRAKE_MODE_KEY) ?? "").trim().toLowerCase();
    return raw === "off" ? "off" : "on";
  } catch {
    return "off";
  }
}

/**
 * จุดเดียวที่ไปป์ไลน์เรียก — คืนบรรทัดคำสั่ง (หรือ "") และห้ามโยน error เด็ดขาด
 * ตัวเบรกพัง = เทิร์นนั้นได้พรอมต์เดิม ไม่ใช่ลูกค้าไม่ได้คำตอบ
 */
export function coachingBrakeDirective({ db, customerId = "", logger = null, ...turn } = {}) {
  try {
    if (coachingBrakeMode(db) !== "on") return "";
    const assessment = assessCoachingTurn(turn);
    if (!assessment.level) return "";
    logger?.info?.(`pipeline: coaching brake level=${assessment.level} reason=${assessment.reason} customer=${customerId}`);
    return coachingBrakeRule(assessment);
  } catch (err) {
    logger?.warn?.(`pipeline: coaching brake ประเมินไม่สำเร็จ — ใช้พรอมต์เดิม (${err?.message || err})`);
    return "";
  }
}
