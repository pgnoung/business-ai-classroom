export const NATURAL_VOICE_MODE_KEY = "natural_voice_mode";
export const NATURAL_VOICE_MODES = Object.freeze(["on", "off"]);

/** ไม่มีค่า = off · on = น้ำเสียงใหม่ · ค่าแปลก/อ่านพัง = off */
export function naturalVoiceMode(db) {
  // White-label: โปรไฟล์ generic ปิดฟีเจอร์เฉพาะธุรกิจคอร์สของพี่ง้วงเสมอ (ค่าใน DB ไม่มีผล)
  if (isGenericProfile(activeBrand())) return "off";
  try {
    const raw = String(db?.getSetting?.(NATURAL_VOICE_MODE_KEY) ?? "").trim().toLowerCase();
    return raw === "on" ? "on" : "off";
  } catch {
    return "off";
  }
}

// persona ฉบับวิธีคุย (เดิม PERSONA_VOICE_V2 4 ต.ค. 2026) ย้ายไปอยู่ใน soul.md ของ instance เส้น legacy ตรงตัว
// (18 ต.ค. 2026 ขั้นที่ 1 ของแผน soul) — ไม่มี soul หรือ soul ไม่มีน้ำเสียงนี้ = ไม่แทน persona (เหมือนร้านอื่นเดิม)
export function personaVoiceV2() {
  return soulBlock("legacy");
}

