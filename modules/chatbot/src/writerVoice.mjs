/** พรอมต์ฉบับน้ำเสียงใหม่จากชิ้นส่วนเดิม — คืนเฉพาะ persona/rules ที่เปลี่ยน
 *  persona ฉบับวิธีคุยมาจาก soul (เส้น legacy): instance ที่ไม่มี soul หรือเส้นนี้ว่าง คืน {} = ไม่เปลี่ยนอะไร
 *  (เดิมเช็กคำว่า "ลูกแพร" ใน persona — ผลเท่ากันสำหรับลูกแพร แต่ไม่ฝังชื่อแบรนด์ไว้ในโค้ดกลาง) */
export function naturalVoiceArgs({ rules = "" } = {}) {
  const voice = personaVoiceV2();
  if (!voice) return {};
  const lines = String(rules).split("\n")
    .filter((line) => !DROPPED_FORM_RULE_PREFIXES.some((prefix) => line.startsWith(prefix)))
    .map((line) => (line.startsWith(BULLET_RULE_PREFIX) ? BULLET_RULE_NATURAL : line));
  // บรรทัดที่เอ่ยคำเรื่องเงินลงทะเบียนเป็น neutral ตามธรรมเนียม priceDirectives (เทสต์กวาดกติกาเห็นครบ)
  const contract = VOICE_CONTRACT.split("\n").map((line) => (PRICE_MENTION.test(line) ? priceRule("neutral", line) : line)).join("\n");
  return { persona: voice, rules: `${lines.join("\n")}\n${contract}` };
}
