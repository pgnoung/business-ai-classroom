const IDENTITY_TEMPLATE_MAX_CHARS = 360;
const IDENTITY_DISCLOSURE_RE = /(?:\bAI\b|ปัญญาประดิษฐ์|ผู้ช่วยอัจฉริยะ)/iu;
const IDENTITY_HUMAN_HANDOFF_RE = /(?:ทีมงาน|คนจริง|เจ้าหน้าที่)/u;

export function resolveIdentityTemplate(value = "") {
  const template = String(value || "").trim();
  if (!template) return IDENTITY_TEMPLATE;
  if (
    template.length > IDENTITY_TEMPLATE_MAX_CHARS
    || /[\u0000-\u001f\u007f]/u.test(template)
    || !IDENTITY_DISCLOSURE_RE.test(template)
    || !IDENTITY_HUMAN_HANDOFF_RE.test(template)
  ) {
    throw new Error("Identity template must be bounded, explicitly disclose AI, and offer a human/team handoff.");
  }
  return template;
}

