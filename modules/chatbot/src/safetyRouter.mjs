// English `unsubscribe` appears in workflow questions and quoted recipient speech.
// Accept only a positive, self-directed command; Thai consent keeps the existing
// full-message safeguards below.
const ENGLISH_POSITIVE_COMMAND = /^(?:please\s+)?unsubscribe\s+(?:me|my\s+email\s+newsletter)$/iu;
const QUOTED_SUBJECT_LEAD = /(?:(?:ลูกค้า|ผู้รับ|คนรับ|สมาชิก)[^\n]{0,40}?(?:พิมพ์|บอก|พูด|แจ้ง|ตอบ)(?:ว่า)?|(?:the\s+)?(?:customer|recipient|member)\s+(?:said|wrote|asked|told(?:\s+me)?))\s*[:：]?\s*$/iu;
const EXPLICIT_THAI_SELF_OPTOUT = /^แต่\s*สำหรับ\s*(?:ผม|ฉัน|ดิฉัน|หนู|เรา)\s*[,，]?\s*(?:ไม่ต้องส่งข้อความ|อย่าส่งข้อความ|ไม่ต้องทัก|อย่าทัก)(?:มา)?(?:อีก|แล้ว)?/u;

function optOutCommandSegments(text) {
  return String(text || "").split(/(?:\r?\n|[.!?;])+/u).map((part) => part.trim()).filter(Boolean);
}

function followsReportedSubject(segments, index) {
  const previous = String(segments[index - 1] || "").replace(/\s+/gu, " ").trim();
  return QUOTED_SUBJECT_LEAD.test(previous);
}

function hasDirectOptOutCommand(text) {
  const full = String(text || "").trim();
  if (/^unsubscribe[.!]?$/iu.test(full)) return true;
  const segments = optOutCommandSegments(full);
  return segments.some((segment, index) => {
    if (!ENGLISH_POSITIVE_COMMAND.test(segment) && !EXPLICIT_THAI_SELF_OPTOUT.test(segment)) return false;
    return !followsReportedSubject(segments, index);
  });
}

