export function loadSafetyRules(file, { logger = console } = {}) {
  if (!file) return [];
  try {
    const parsed = JSON.parse(readFileSync(file, "utf8"));
    if (!Array.isArray(parsed)) return [];
    return parsed
      .filter((r) => Array.isArray(r?.keywords) && r.keywords.length && typeof r?.template === "string" && r.template)
      .map((r) => ({
        keywords: r.keywords.map(String),
        // v1.2.2 (เคสจริง 2026-08-12): ภาษาไทยไม่มีช่องว่างระหว่างคำ การเทียบแบบ
        // substring จึงทำให้ "ใบเสนอราคา" ของลูกค้าไปชนคีย์เวิร์ด "ราคา" แล้วยิง
        // template ผิดเรื่องทันที — excludeKeywords คือรายการบริบทที่ต้องไม่นับ
        excludeKeywords: Array.isArray(r.excludeKeywords) ? r.excludeKeywords.map(String) : [],
        // v1.4.45: กฎที่ "พลาดจับแล้วยังแก้ได้" ขอยกเว้นตัวเองได้เมื่อลูกค้าเล่าโจทย์ธุรกิจ
        // (เส้นอันตรายไม่ตั้งธงนี้ — พลาดจับแล้วกู้คืนไม่ได้ ต้องจับไว้ก่อนเสมอ)
        excludeUseCaseFraming: r.excludeUseCaseFraming === true,
        // 20 ต.ค. 2026 (คำตอบ C4 ข้อ 12): กฎแจ้งโอน/สลิป ขอข้อมูลลงทะเบียนไปพร้อมกันได้ (pipeline เติมฟอร์มจากการ์ด เฉพาะห้องที่ยังไม่เคยกรอก)
        askRegistration: r.askRegistration === true,
        template: String(r.template),
        reason: String(r.reason || "custom_urgent"),
      }));
  } catch (err) {
    logger.warn?.(`safetyRouter: อ่าน safety rules ไม่ได้ (${err?.message || err}) — ใช้กฎ default เท่านั้น`);
    return [];
  }
}

