// = ช่องโหว่เดียวกันเปิดคนละบาน (คำสั่งพี่ง้วง 2026-09-05)
export function normalizeThai(text) {
  // audit 2026-08-24: ตัวอักษรความกว้างศูนย์ (ZWSP/ZWNJ/BOM/soft hyphen) แทรกกลางคำได้
  // ทั้งจากการ copy-paste และจากคนที่ตั้งใจเลี่ยงตัวกรอง — "ข\u200bอใบกำกับ" เคยรอดทุกด่าน
  // NFC ทำให้สระ/วรรณยุกต์ที่ประกอบต่างลำดับเทียบกันได้ (ใบกํากับ vs ใบกำกับ)
  return String(text || "")
    .normalize("NFC")
    .replace(/[\u200b-\u200f\u2060\ufeff\u00ad]/gu, "")
    .replace(/\u0e40\u0e40/gu, "\u0e41");
}

