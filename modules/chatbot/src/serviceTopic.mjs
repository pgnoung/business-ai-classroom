// จับเฉพาะ "เรื่องที่อยากเรียน/อยากได้" — ช่องทางที่ลูกค้าใช้ทำธุรกิจอยู่แล้วไม่นับ ("ขายของผ่าน LINE OA ค่ะ" = เล่างาน ตอบคำถามค้นหาโจทย์)
// ทักมาทาง LINE / เห็นโฆษณาในเฟส / ร้านยิงแอดเอง / อยากทำแชทบอทเอง (= คลาส Workflow) ก็ไม่นับ
// "วิทยากร" ไม่นับ (ลูกค้าถามว่าใครสอน) · "ปรึกษา" เฉย ๆ ไม่นับ ("ขอปรึกษาหน่อยค่ะ" = คุยทั่วไป)
const CHANNEL = String.raw`line\s*(?:oa|ads?|official|crm|marketing)|ไลน์\s*(?:โอเอ|oa|official|แอด|ads?)|facebook\s*(?:ads?|marketing)|(?<![a-z])fb\s*ads?|เฟส(?:บุ๊[คก]|บุค)?\s*(?:แอด|ads?)|แอดเฟส|meta\s*ads?`;
const WANT = String.raw`สนใจ|อยาก|เรียน|สอน|คลาส|คอร์ส|ปรึกษา|ช่วย(?:ดู|ทำ|วาง|ปรับ)|ปรับ|ตั้งค่า|วางระบบ|พัฒนา`;
const COURSE = String.raw`คลาส|คอร์ส|สอน|เรียน|อบรม|ที่ปรึกษา|workshop`;
const BUILD_FOR_ME = String.raw`(?:รับ|จ้าง|ทำให้|วางระบบ(?:ให้)?|บริการ)[^\n]{0,15}(?:แชท\s*บ[อ็]?ท|chat\s*bot|ระบบตอบแชท|แอดมิน\s*ai|ai\s*แอดมิน)`;
export const NON_AI_SERVICE_TOPIC = new RegExp([
  `(?:${WANT})[^\n]{0,20}?(?:${CHANNEL})`,
  `(?:${CHANNEL})[^\n]{0,20}?(?:${COURSE})`,
  "ที่ปรึกษา|(?<![a-z])consult|คอนซัล",
  BUILD_FOR_ME,
].join("|"), "iu");

export function mentionsNonAiService(texts = []) {
  return (Array.isArray(texts) ? texts : [texts]).some((text) => NON_AI_SERVICE_TOPIC.test(String(text ?? "")));
}
