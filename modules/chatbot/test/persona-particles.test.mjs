const PARTICLES_ONLY = /นะครับ|นะคะ|ครับผม|ครับ|ค่ะ|คะ/gu;
function assertParticlesOnly(input) {
  const result = enforceFemaleParticles(input);
  assert.equal(result.text.replace(PARTICLES_ONLY, ""), input.replace(PARTICLES_ONLY, ""), `เนื้อหาเปลี่ยน: ${JSON.stringify(input)} → ${JSON.stringify(result.text)}`);
  assert.ok(result.fixes.every((item) => item.kind !== "self_correction"), `ไม่ควรยุบ: ${JSON.stringify(input)}`);
  assert.doesNotMatch(result.text, /ครับ/u, input);
}

