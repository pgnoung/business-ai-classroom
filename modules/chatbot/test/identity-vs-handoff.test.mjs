// "ตอนนี้ผมคุยกับคนจริงหรือคุยกับบอทอยู่" คือคำถามตัวตน แต่ตัวจับ handoff แบบเปลือย
// /คุยกับคนจริง/ แย่งไปก่อน ลูกค้าได้ "ลูกแพรส่งเรื่องให้ทีมงานคนจริง…" โดยไม่มีการเปิดเผยว่าเป็น AI
// (การเปิดเผย AI เมื่อถูกถามเป็นเงื่อนไข license ของโปรดักต์ — IDENTITY_TEMPLATE)
// อีกสี่รูปประโยคไม่ถูกจับเลย โมเดลจึงตอบเองโดยไม่มีแม่แบบเปิดเผยตัวตน
//
// ธุรกิจนี้ขายคอร์ส AI ลูกค้าพิมพ์ "AI" แทบทุกประโยค ตัวจับใหม่จึงต้องไม่กินคำถามธุรกิจ
// ("ใช้ AI หรือจ้างคนดี", "ใช้ AI ตอบแชทลูกค้าได้ไหม") — มีเทสต์คุมอยู่ท้ายไฟล์
import test from "node:test";
import assert from "node:assert/strict";
import { routeMessage } from "../src/safetyRouter.mjs";

for (const text of [
  "ตอนนี้ผมคุยกับคนจริงหรือคุยกับบอทอยู่ครับ",
  "อันนี้แอดมินตอบ หรือ ai ตอบคะ",
  "อันนี้ admin ตอบ หรือ AI ตอบคะ",
  "ใช้เอไอตอบผมอยู่ใช่ไหมครับ",
  "น้องแพรเป็น AI ใช้ไหมครับ ตอบไวมาก",
  "ลูกแพร ai ไหม",
  "บอทหรือคนตอบคะ",
  "นี่คุยกับคนจริงหรือ AI อยู่คะ",
]) {
  test(`identity question routes identity and discloses AI — ${text}`, () => {
    const route = routeMessage({ text });
    assert.equal(route.route, "identity");
    assert.match(route.template, /AI|ปัญญาประดิษฐ์|ผู้ช่วยอัจฉริยะ/u);
  });
}

test("คำสั่งขอคนจริงตรง ๆ ยังเป็น handoff", () => {
  for (const text of [
    "ขอคุยกับคนจริงครับ",
    "เอาเป็นว่าขอคุยกับคนจริงเลยดีกว่าครับ แบบนี้ไม่โอเค",
    "นี่บอทใช่มั้ย ถ้าใช่ขอคุยกับแอดมินค่ะ",
    "ขอคุยกับคนจริงหน่อยได้มั้ย ไม่อยากคุยกับบอท",
  ]) assert.equal(routeMessage({ text }).route, "human_handoff", text);
});

test("ถามตัวตนพร้อมขอคุยกับคน (ยังสงสัยอยู่) ยังเป็นเส้นตัวตนเหมือนเดิม", () => {
  for (const text of ["คุยกับคนจริงอยู่ป่าวคะ", "ขอคุยกับคนจริงไหมคะ อันนี้ใช่บอทมั้ย"]) {
    assert.equal(routeMessage({ text }).route, "identity", text);
  }
});

test("คำถามธุรกิจที่มีคำว่า AI/คน ห้ามกลายเป็นคำถามตัวตน", () => {
  for (const text of [
    "ใช้ AI หรือจ้างคนดีครับ",
    "ใช้บอทหรือจ้างแอดมินเพิ่มดีคะ",
    "ใช้ AI ตอบแชทลูกค้าได้ไหมครับ",
    "ใช้เอไอตอบลูกค้าผมได้ไหมคะ",
    "บอทตอบหรือคนตอบ ลูกค้าจะชอบแบบไหนมากกว่ากันคะ",
  ]) assert.equal(routeMessage({ text }).route, "ai", text);
});
