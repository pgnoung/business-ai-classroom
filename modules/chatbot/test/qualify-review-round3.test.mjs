// ข้อความลูกค้า/ลูกแพรทุกบรรทัดเป็นประโยคสังเคราะห์
import test from "node:test";
import assert from "node:assert/strict";
import { enforceFemaleParticles } from "../src/personaParticles.mjs";
import { fastReclaimSignal } from "../src/qualifyFastReclaim.mjs";

const fix = (text) => enforceFemaleParticles(text).text;
const signal = (text) => fastReclaimSignal({ text, route: {}, prioritySafetyRoute: false, handoffHint: null });

test("ครับบบ ที่ยืด ตามด้วยคำไทย: ไม่เหลือ บ ค้าง และไม่กิน บ ของคำถัดไป (idempotent)", () => {
  const rows = [
    ["ได้เลยครับบบเดี๋ยวลูกแพรส่งให้นะครับ", "ได้เลยค่ะเดี๋ยวลูกแพรส่งให้นะคะ"],
    ["ได้ครับบเลย", "ได้ค่ะเลย"],
    ["ขอบคุณครับบอส", "ขอบคุณค่ะบอส"],
    ["ขอบคุณครับบบอส", "ขอบคุณค่ะบอส"],
    ["ได้ครับบบริษัท", "ได้ค่ะบริษัท"],
  ];
  for (const [input, want] of rows) {
    assert.equal(fix(input), want, input);
    assert.equal(fix(want), want, `idempotent: ${want}`);
  }
});

test("คำถามจริงหลังประโยคที่มี ว่า… และเว้นวรรค ยังได้ คะ · คำรายงานที่วิ่งถึงท้ายได้ ค่ะ", () => {
  assert.equal(fix("ลูกแพรเช็คแล้วว่ารอบเสาร์เต็ม สนใจรอบอาทิตย์ไหมครับ"), "ลูกแพรเช็คแล้วว่ารอบเสาร์เต็ม สนใจรอบอาทิตย์ไหมคะ");
  assert.equal(fix("ทีมงานบอกว่าคลาสเต็มแล้ว พี่สะดวกรอบหน้าไหมครับ"), "ทีมงานบอกว่าคลาสเต็มแล้ว พี่สะดวกรอบหน้าไหมคะ");
  assert.equal(fix("เดี๋ยวลูกแพรเช็คให้ว่ามีที่ไหมครับ"), "เดี๋ยวลูกแพรเช็คให้ว่ามีที่ไหมค่ะ");
});

test("คำถามตัวเลือกที่ลงท้าย …หรือเพิ่มรายได้ ได้ คะ · ประโยคบอกช่องทาง …หรือ…ได้ ยังได้ ค่ะ", () => {
  assert.equal(fix("ตอนนี้อยากเพิ่มยอดขายหรือเพิ่มรายได้ครับ"), "ตอนนี้อยากเพิ่มยอดขายหรือเพิ่มรายได้คะ");
  assert.equal(fix("สนใจลดต้นทุนหรือเพิ่มรายได้ครับ"), "สนใจลดต้นทุนหรือเพิ่มรายได้คะ");
  assert.equal(fix("โอนหรือจ่ายบัตรได้ครับ"), "โอนหรือจ่ายบัตรได้ค่ะ");
});

test("เปิด AI คืนเร็ว: ภาษาเจ้าของธุรกิจเรื่องรายได้/รับเงินผ่านบัตร = สัญญาณซื้อ · คำถามค่าจ้างของคนหางาน = ไม่เปิด", () => {
  for (const text of ["อยากเพิ่มรายได้ค่ะ ขอเลขบัญชีโอนเลยค่ะ", "อยากเพิ่มรายได้ให้ร้านค่ะ ค่าใช้จ่ายเท่าไหร่คะ", "รายได้ร้านตกมากค่ะ ต้องจ่ายเท่าไหร่คะ",
    "ลงทุนเท่าไหร่คะ อยากเพิ่มรายได้ร้าน", "รับเงินผ่านบัตรเครดิตได้ไหมคะ", "คอร์สราคาเท่าไหร่คะ"]) {
    assert.notEqual(signal(text), "", text);
  }
  for (const text of ["เงินเดือนเท่าไหร่คะ", "ได้เงินวันละเท่าไหร่คะ", "ค่าจ้างเท่าไหร่คะ", "สนใจงานค่ะ", "ไม่สมัครค่ะ"]) {
    assert.equal(signal(text), "", text);
  }
});

test("ลูกค้าแก้ว่าไม่ได้หางาน แต่สนใจคอร์ส = เปิด AI คืน", () => {
  assert.equal(signal("ไม่ได้สนใจงานค่ะ สนใจคอร์ส"), "interest");
});
