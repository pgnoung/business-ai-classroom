// golden-money-rule.test.mjs — "ตัวเลขนี้เป็นการอ้างราคาไหม"
//
// กฎนี้ตัดสินว่าราคาที่หลุดถึงลูกค้าจะถูกจับหรือไม่ จึงต้องล็อกด้วยเคสโจมตีจริง ไม่ใช่ความเชื่อ
// รายการสำนวนมาจากการสำรวจคำตอบจริง 1,401 ตัวเลข ในรายงาน 111 ไฟล์ของรอบที่จ่ายเงินไปแล้ว
//
// ประวัติ: กฎเดิมเป็น "การปฏิเสธ" (ตรวจทุกเลข ยกเว้นบรรทัดที่มีคำว่า ปี/เวลา/ท่าน/คน)
// ซึ่งพังสองทาง — พลาดราคาจริงเพราะธุรกิจนี้พูดว่า "ท่านละ 11,900 บาท" เสมอ
// และฟ้อง "รหัสไปรษณีย์ 10270" ว่าเป็นราคาผิด กฎใหม่เป็น "การยืนยัน": ต้องมีบริบทเงิน
import test from "node:test";
import assert from "node:assert/strict";
import { poisonGlobalFetch } from "./helpers.mjs";
import { checkTurn, moneyMatches } from "../src/brain/goldenAssert.mjs";

poisonGlobalFetch();

const APPROVED = new Set([11900, 12900, 19900, 79000]);
const flags = (text) => checkTurn({ bubbles: [{ text }], images: [], customer: {} }, [],
  { approvedAmounts: APPROVED }).some((f) => f.rule === "price_not_approved");

// ราคานอกตาราง เขียนด้วยสำนวนที่พบจริงในคลัง — ต้องจับได้ทุกอัน
const REAL_PRICE_FRAMINGS = [
  "ราคา 33,333 บาทค่ะ", "ท่านละ 33,333 บาท", "เหลือ 33,333 บาทค่ะ",
  "ลดเหลือเพียง 33,333.- ค่ะ", "โปรพิเศษ 33,333 บ. เท่านั้น", "ค่าเรียนทั้งหมด 33,333 ค่ะ",
  "ยอดรวม 33,333 ค่ะ", "มัดจำ 33,333 ก่อนนะคะ", "งบประมาณ 33,333 ต่อรอบค่ะ",
  "ราคาโปรโมชั่นพิเศษ 33,333 ค่ะ", "the rate of THB 33,333 per person",
  "regular price 33,333 baht", "โอนมา 33,333 ได้เลยค่ะ", "ชำระ 33,333 ผ่านพร้อมเพย์นะคะ",
  "หัวละ 33,333 ค่ะ", "คนละ 33,333 บาท", "ส่วนลดเหลือ 33,333 บาท/ท่าน",
  "เริ่มต้นที่ 33,333 ค่ะ", "33,333 บาท/ท่าน", "💰 ราคาปกติ 33,333 บาท",
  "ค่าใช้จ่ายอยู่ที่ 33,333 ค่ะ", "ราคาเต็ม 33,333 ลด 10%", "Early Bird 33,333 บาท",
  "จ่าย 33,333 แล้วได้เลยค่ะ",
];

// ตัวเลขที่ไม่ใช่ราคา — ทุกอันมาจากคำตอบจริงในคลัง ต้องไม่ถูกฟ้องสักอัน
const NOT_PRICES = [
  "รอบวันเสาร์ที่ 12 กันยายน 2026 ค่ะ",
  "รอบเดือนพฤศจิกายน 2569 มีดังนี้ค่ะ",
  "รหัสไปรษณีย์ 10270 เรียบร้อยค่ะ",
  "ลูกแพรบันทึกเบอร์ 081-234-5678 ให้แล้วค่ะ",
  "เวลา 10:00–17:00 น. ค่ะ",
  "ส่วนรอบเรียนปี 2027 ยังไม่ได้ประกาศนะคะ",
  "มีผู้เรียนแล้วกว่า 1200 ท่านค่ะ",
  "เอกสารเลขที่ 45678 ค่ะ",
];

test("ราคานอกตารางต้องถูกจับทุกสำนวนที่ธุรกิจนี้ใช้จริง", () => {
  const missed = REAL_PRICE_FRAMINGS.filter((text) => !flags(text));
  assert.deepEqual(missed, [], `สำนวนที่หลุด: ${JSON.stringify(missed)}`);
});

test("ปี เบอร์โทร รหัสไปรษณีย์ เวลา จำนวนคน ต้องไม่ถูกอ่านว่าเป็นราคา", () => {
  const wrong = NOT_PRICES.filter((text) => flags(text));
  assert.deepEqual(wrong, [], `ฟ้องผิด: ${JSON.stringify(wrong)}`);
});

test("ราคาที่อยู่ในตารางแล้ว ต้องไม่ถูกฟ้อง (รวมยอดรวมตามจำนวนท่าน)", () => {
  assert.equal(flags("ท่านละ 11,900 บาท"), false);
  assert.equal(flags("มาเรียน 2 ท่าน ยอดรวม 23,800 บาทค่ะ"), false, "ผลคูณของราคาอนุมัติยังผ่าน");
});

test("สัญกรณ์ราคาไทยทุกแบบต้องถูกอ่านเป็นเงิน", () => {
  for (const [text, want] of [
    ["ลดเหลือ 11,900.- ค่ะ", "11,900"],
    ["ลดเหลือ 11,900.– ค่ะ", "11,900"],
    ["ลดเหลือ 11,900.− ค่ะ", "11,900"],
    ["ราคา 11,900. ค่ะ", "11,900"],
    ["฿11,900 ค่ะ", "11,900"],
    ["ราคา 11,900.00 บาท", "11,900"],
    ["ยอดโอนสุทธิ 12,538.32 บาทค่ะ", "12,538"],
  ]) {
    const hits = moneyMatches(text);
    assert.equal(hits.length, 1, `${text} ต้องอ่านเป็นเงินหนึ่งจำนวน`);
    assert.equal(hits[0][1], want, text);
  }
});

test("ราคาที่มีสตางค์และไม่อยู่ในตาราง ต้องถูกจับ (เคสภาษี R13)", () => {
  assert.equal(flags("ฐานก่อน VAT 12,056.07 บาท"), true,
    "ตัวเลขภาษีที่บอทคำนวณเองไม่อยู่ในตารางราคา — ด่านราคาตัวจริงก็ตัดประโยคนี้ทิ้งเหมือนกัน");
  assert.equal(flags("ราคาคลาสรวม VAT 11,900.00 บาท"), false, "สตางค์ .00 ของราคาที่อนุมัติแล้ว ต้องผ่าน");
});

test("บรรทัดที่มีทั้งราคาและวันที่ ต้องจับเฉพาะราคา", () => {
  const line = "ราคาปกติ 19,900 บาท/ท่าน รอบวันเสาร์ที่ 12 กันยายน 2026";
  assert.deepEqual(moneyMatches(line).map((m) => m[1]), ["19,900"],
    "ปีในประโยคเดียวกับราคา ต้องไม่ถูกนับเป็นเงิน");
});

test("กฎ no_price ใช้นิยามเดียวกัน — วันที่ไม่ทำให้ 'ห้ามบอกราคา' ตก", () => {
  const noPrice = (text) => checkTurn({ bubbles: [{ text }], images: [], customer: {} },
    [{ type: "no_price" }], { approvedAmounts: APPROVED }).some((f) => f.rule === "no_price");
  assert.equal(noPrice("รอบวันเสาร์ที่ 12 กันยายน 2026 ค่ะ"), false);
  assert.equal(noPrice("ราคา 19,900 บาทค่ะ"), true);
});
