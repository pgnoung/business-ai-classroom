// รีวิว 2026-10-03 รอบ 3 (M2): humanizer ทำงานหลังด่านตัด "คุณลูกค้า" — ห้ามใส่คำนี้กลับเข้าไปเอง
test("humanizer: \"ของท่าน\" -> \"ของคุณ\" (ไม่ใช่ \"ของคุณลูกค้า\")", () => {
  const bubbles = createHumanizer().humanize({ customerId: "U-h", text: "คลาสนี้ออกแบบมาเพื่อธุรกิจของท่านโดยเฉพาะค่ะ" });
  const text = bubbles.map((bubble) => bubble.text).join("\n");
  assert.match(text, /ธุรกิจของคุณโดยเฉพาะ/u);
  assert.ok(!text.includes("คุณลูกค้า"), text);
});

// รีวิว 2026-10-03 รอบ 3 (M3): ถ้อยคำที่ทำให้โมเดลทวนคำตอบเป็นประโยคแยก และคำถามประโยคเดิมทุกห้อง
test("พรอมต์ไม่สั่งให้ทวนระดับ/ยกประโยคคำถามตัวอย่างตรงตัว", () => {
  const history = [];
  const number = buildReplyFocusRules({ text: "3", history }).join("\n");
  assert.ok(!number.includes("รับรู้ระดับนั้น"), number);
  assert.ok(!number.includes("อยากให้ AI ช่วยงานไหนเป็นอย่างแรก"), number);
  assert.match(number, /ไม่แยกประโยคทวนว่าลูกค้าอยู่ระดับไหน/u);
  const positive = buildReplyFocusRules({ text: "เคยค่ะ", history }).join("\n");
  assert.ok(!positive.includes("รับรู้อย่างอบอุ่นว่าเริ่มใช้ AI มาแล้ว"), positive);
  assert.match(positive, /ไม่แยกประโยคทวนว่าลูกค้าเคยใช้ AI แล้ว/u);
  assert.ok(!CLOSING_QUESTION_RULE.includes("ไม่ทราบว่าตอนนี้อยากนำไปช่วยงานด้านไหนบ้างนะคะ"));
  const style = buildConversationStyleRules({ text: "สนใจค่ะ", customer: {} });
  assert.match(style, /ร้อยเข้ากับประโยคที่เสนอ ไม่แยกเป็นประโยคทวน/u);
  // บันไดถามระดับ AI ของข้อความแรกเป็นถ้อยคำมาตรฐาน — กติกาน้ำเสียงต้องไม่สั่งให้เปลี่ยน
  assert.match(style, /ยกเว้นคำถามบันไดระดับ AI ในข้อความแรก/u);
});

