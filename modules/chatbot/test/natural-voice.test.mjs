test("e2e: ห้องไม่มีชื่อ โมเดลเขียน \"คุณลูกค้า\" มา ลูกค้าไม่เห็นคำนี้", async () => {
  const db = memoryDb();
  const app = createApp({
    config: testConfig({ HISTORY_TURNS: "6" }),
    db,
    overrides: {
      hermesFetch: hermesFetchStub("เข้าใจค่ะคุณลูกค้า ใช้ AI ช่วยงานจริงอยู่แล้ว ต่อยอดได้ไม่ยากเลยค่ะ\nตอนนี้คุณลูกค้าอยากให้ AI ช่วยงานส่วนไหนก่อนคะ?"),
      lineFetch: lineFetchStub(), sleep: async () => {},
    },
    logger: silent,
  });
  db.upsertCustomer("U-noname", {});
  db.insertMessage({ customerId: "U-noname", direction: "out", content: "สวัสดีค่ะ" });
  const result = await app.pipeline.handleInboundText({ customerId: "U-noname", text: "3", replyToken: "rt-noname" });
  assert.equal(result.sent, true);
  const text = db.messagesFor("U-noname", 20).filter((m) => m.direction === "out").map((m) => m.content).join("\n");
  assert.ok(text.length > 0, "ต้องมีข้อความที่ส่งออก");
  assert.ok(!text.includes("คุณลูกค้า"), text);
  db.close();
});

