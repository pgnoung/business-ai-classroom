test("ห้องที่ไม่มีชื่อเรียกได้: ตัด \"คุณลูกค้า\" ออกจากร่างของโมเดล (หลังคำเชื่อมเหลือ \"คุณ\")", () => {
  assert.equal(generic.generic, true);
  for (const [draft, expected] of [
    ["เข้าใจค่ะคุณลูกค้า ค่าเรียนหลักหมื่นเกินงบที่ตั้งไว้", "เข้าใจค่ะ ค่าเรียนหลักหมื่นเกินงบที่ตั้งไว้"],
    ["ขอบคุณที่เข้าใจนะคะ คุณลูกค้า 😊", "ขอบคุณที่เข้าใจนะคะ 😊"],
    ["ตอนนี้คุณลูกค้าใช้ทำสินค้าประเภทไหนคะ?", "ตอนนี้ใช้ทำสินค้าประเภทไหนคะ?"],
    ["คุณลูกค้า ค่าเรียนรวมการสอนแล้วค่ะ", "ค่าเรียนรวมการสอนแล้วค่ะ"],
    ["ส่งรายละเอียดให้คุณลูกค้าดูนะคะ", "ส่งรายละเอียดให้คุณดูนะคะ"],
    // บันไดของห้องไม่มีชื่อใช้ถ้อยคำ persona ตรงตัว "ไม่ทราบว่าเคยใช้ AI…" (รีวิวรอบ 3: ไม่เหลือ "คุณ")
    ["ไม่ทราบว่า คุณลูกค้า\nเคยใช้ AI มาประมาณ ระดับที่เท่าไหร่แล้วคะ ?", "ไม่ทราบว่าเคยใช้ AI มาประมาณ ระดับที่เท่าไหร่แล้วคะ ?"],
  ]) {
    assert.equal(dropGenericAddress(draft, generic), expected, draft);
  }
  // "ขอบคุณลูกค้า" มีตัวอักษรชุดเดียวกัน ห้ามแตะ
  assert.equal(dropGenericAddress("ขอบคุณลูกค้าทุกท่านที่ไว้ใจค่ะ", generic), "ขอบคุณลูกค้าทุกท่านที่ไว้ใจค่ะ");
  // ห้องที่มีชื่อเรียกได้ ไม่ผ่านด่านนี้ (ด่านชื่อเดิมคุมอยู่แล้ว)
  assert.equal(dropGenericAddress("เข้าใจค่ะคุณลูกค้า", named), "เข้าใจค่ะคุณลูกค้า");
});

test("พรอมต์ห้องที่ไม่มีชื่อเรียกได้: ไม่สั่งให้เรียก \"คุณลูกค้า\" อีก", () => {
  const rules = baseRules("general", [], { customer: { display_name: "" }, currentText: "สนใจค่ะ", history: [{ role: "assistant", content: "สวัสดีค่ะ" }] });
  assert.ok(!rules.includes('ชื่อที่ใช้เรียกลูกค้าคนนี้คือ "คุณลูกค้า"'));
  assert.match(rules, /ยังไม่มีชื่อที่ใช้เรียกลูกค้าคนนี้ได้/u);
  assert.match(rules, /ไม่เรียกว่า "คุณลูกค้า" กลางบทสนทนา/u);
  // ห้องที่มีชื่อ: บรรทัดเดิมทุกไบต์
  const withName = baseRules("general", [], { customer: { known_name: "มิน" }, currentText: "สนใจค่ะ", history: [] });
  assert.match(withName, /ชื่อที่ใช้เรียกลูกค้าคนนี้คือ "คุณมิน"/u);
});

