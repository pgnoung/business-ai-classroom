// F2 (ตรวจย้อนหลัง ก.ย. 2026 — D713): "ยังไม่อยากเอา AI ไปใช้กับงานประจำ แต่อยากลองทำคลิปให้ AI คิด"
// คือลีดที่กำลังเล่าโจทย์ ไม่ใช่คนที่ปฏิเสธบอท — เดิมคำว่า "ไม่อยากเอา AI" ทำให้โดนแม่แบบส่งต่อ
// + ปิด AI ถาวร + push + ทวง SLA ทั้งที่ลูกค้ากำลังบอกว่าอยากเรียนอะไร
// ข้อความในไฟล์นี้เป็นประโยคสังเคราะห์ทั้งหมด
import test from "node:test";
import assert from "node:assert/strict";
import { routeMessage } from "../src/safetyRouter.mjs";

test("รำคาญบอทจริง ยังส่งต่อคน", () => {
  for (const text of [
    "ไม่อยากคุยกับบอทแล้ว ขอคนหน่อยค่ะ",
    "ไม่อยากคุยกับบอทค่ะ",
    "ไม่อยากคุยกับบอท แต่อยากลองเรียนคลาส AI ค่ะ",
    "เบื่อบอทแล้วครับ",
    "ไม่อยากให้บอทตอบค่ะ",
    "ไม่อยากให้บอทมายุ่งค่ะ",
  ]) assert.equal(routeMessage({ text }).route, "human_handoff", text);
});

test("เล่าว่าไม่อยากเอา AI ไปใช้กับงานประจำ แต่อยากลองเรื่องอื่น = ลีดเล่าโจทย์", () => {
  for (const text of [
    "งานประจำยังไม่อยากเอา AI ไปช่วยครับ แต่อยากลองทำคลิปสั้นให้ AI คิดให้",
    "ไม่อยากให้ AI มาแทนพนักงานหน้าร้าน แต่อยากใช้กับงานหลังบ้าน",
    "ตอนนี้ยังไม่อยากใช้ AI กับบัญชี ส่วนคอนเทนต์อยากลองดู",
    "ผมทำร้านอาหารครับ ไม่อยากเอา AI ไปตอบลูกค้าเรื่องเงิน แต่อยากลองใช้กับคอนเทนต์",
  ]) {
    const route = routeMessage({ text });
    assert.equal(route.route, "ai", text);
    assert.equal(route.escalate, null, text);
  }
});

test("คำขอคนตรง ๆ ชนะเสมอ แม้ข้อความมีรูปเล่าโจทย์ปน", () => {
  assert.equal(
    routeMessage({ text: "ไม่อยากให้ AI มาช่วยตอบแล้วค่ะ ขอคุยกับคนจริงเลย" }).route,
    "human_handoff",
  );
});
