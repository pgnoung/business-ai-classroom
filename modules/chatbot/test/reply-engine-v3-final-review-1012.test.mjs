// (1) คำขอให้เราส่งราคา ที่บอกด้วยว่าจะเอาไปเสนอหัวหน้า ยังเป็นคำถามราคาเสมอ — ตัดเฉพาะการ "ส่งต่อเอง" ที่ไม่มีคำขอ
// (2) ปฏิเสธ / สมัครไปแล้ว / นักเรียนเก่า ไม่ใช่การบอกว่าจะสมัคร
import assert from "node:assert/strict";
import test from "node:test";

import { asksAboutMoney } from "../src/priceDisclosure.mjs";
import { enrollIntentOf } from "../src/replyEngineV3/stage.mjs";

test("คำขอราคาที่บอกว่าจะเอาไปเสนอหัวหน้า ยังเป็นคำถามราคา · ส่งต่อเองไม่ใช่", () => {
  for (const text of ["ส่งราคาให้หน่อยครับ จะเอาไปเสนอหัวหน้า", "ส่งราคามาให้หน่อยครับ จะเอาไปให้หัวหน้า",
    "ส่งราคาคลาสให้ฝ่ายบุคคลของบริษัทได้ไหมครับ", "ขอราคาไปเสนอหัวหน้าครับ", "ไม่รวมอาหารเท่าไหร่ครับ", "เรียนเท่าไหนครับ"]) {
    assert.equal(asksAboutMoney(text), true, text);
  }
  for (const text of ["แจ้งราคาไปยัง ผู้บริหารเพื่อพิจารณาก่อนครับ", "เดี๋ยวขอเอาราคาไปให้หัวหน้าดูก่อนนะครับ",
    "ยังไม่ค่อยได้ใช้เท่าไหร่ค่ะ", "2 ค่ะ ใช้ไม่เป็นเท่าไร"]) {
    assert.equal(asksAboutMoney(text), false, text);
  }
});

test("ปฏิเสธ / สมัครแล้ว / นักเรียนเก่า ไม่ใช่การบอกว่าจะสมัคร · บอกว่าจะสมัครจริงยังนับ", () => {
  for (const text of ["ยังไม่อยากสมัครค่ะ ขอดูข้อมูลก่อน", "ไม่ได้อยากสมัครค่ะ แค่ถามเฉย ๆ", "สมัครเรียนแล้วค่ะ", "จองที่นั่งแล้วค่ะ",
    "เคยสมัครเรียนรอบที่แล้วค่ะ", "เคยสมัครคลาสไปแล้วค่ะ"]) {
    assert.equal(enrollIntentOf(text), false, text);
  }
  for (const text of ["จะสมัครเรียน", "สมัครเรียนค่ะ", "อยากสมัครค่ะ", "จะสมัครรอบ 7 พ.ย. ค่ะ", "สนใจสมัครเรียนครับ"]) {
    assert.equal(enrollIntentOf(text), true, text);
  }
});

test("ตัวจับใหม่ทั้งสองเร็วกับข้อความยาว 5,000 ตัวอักษร", () => {
  const started = performance.now();
  enrollIntentOf(`${"ไม่".repeat(1600)}สมัคร${" แล้ว".repeat(100)}`);
  asksAboutMoney(`${"ส่งราคา".repeat(700)}หน่อย`);
  assert.ok(performance.now() - started < 50);
});
