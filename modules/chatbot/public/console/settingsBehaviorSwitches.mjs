export const GENERIC_HIDDEN_SWITCHES = Object.freeze(new Set([
  "owner_chat_mode", "owner_chat_model", "lesson_digest_mode", "qualify_sweep_mode", "identity_link_mode",
  "natural_voice_mode", "meta_capi_mode", "ad_referral_capture", "reply_engine",
]));

export function visibleSwitches(switches, state) {
  const list = Array.isArray(switches) ? switches : [];
  return isGeneric(state) ? list.filter((item) => !GENERIC_HIDDEN_SWITCHES.has(item?.key)) : list;
}

function nextValue(item) {
  const i = item.values.indexOf(item.value);
  return item.values[(i + 1) % item.values.length];
}

export async function behaviorSwitchesBlock({ api, toast, refresh, state } = {}) {
  const data = await api("/console/api/settings/behavior-switches").catch(() => null);
  const switches = visibleSwitches(data?.switches, state);
  if (!switches.length) return null;
  const rows = switches.map((item) => {
    const copy = BEHAVIOR_SWITCH_COPY[item.key] || { title: item.key };
    // สวิตช์เลือกโมเดล: จุดเขียว = ค่าที่พี่ง้วงขอ (luna) — ไม่มีค่า "ปิด" ให้โมเดล
    const on = !OFF_VALUES.has(item.value);
    const hint = copy[item.value] || "";
    if (!data.canEdit) {
      return el("div", { class: "ht-row" },
        el("strong", null, `${copy.title}: `),
        el("span", { class: on ? "is-on-text" : "is-off-text" }, LABEL[item.value] || item.value),
        el("p", { class: "block-hint" }, hint));
    }
    return el("button", {
      class: "switch-line",
      role: "switch",
      "aria-checked": on ? "true" : "false",
      onclick: async () => {
        const value = nextValue(item);
        try {
          await api("/console/api/settings/behavior-switches", { method: "POST", body: { key: item.key, value } });
          toast(`${copy.title}: ${LABEL[value] || value} — มีผลตั้งแต่ข้อความถัดไป`);
          await refresh?.();
        } catch (error) {
          toast(error.message);
        }
      },
    },
      switchDot(on),
      el("span", { class: `switch-state ${on ? "is-on-text" : "is-off-text"}` }, `${copy.title}: ${LABEL[item.value] || item.value}`),
      el("span", { class: "switch-line-hint" }, hint),
    );
  });
  return el("section", { class: "block" },
    el("h2", { class: "block-title" }, "สวิตช์พฤติกรรมลูกแพร"),
    el("p", { class: "block-hint" },
      data.canEdit
        ? "แตะเพื่อสลับ มีผลตั้งแต่ข้อความถัดไปทันที ไม่ต้องรีสตาร์ต — ถ้าลูกแพรตอบแปลกหลังเปิด ปิดกลับได้ทันที"
        : "เฉพาะ Super Admin เท่านั้นที่เปลี่ยนได้ — ทีมดูสถานะได้อย่างเดียว"),
    ...rows,
  );
}
